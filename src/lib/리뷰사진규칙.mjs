/** 주소가 포털·언론사의 것인가 — 도메인으로만 본다 */
export function 남의집인가(주소) {
  const m = String(주소 ?? '').match(/^[a-z]+:\/\/([^/]+)/i);
  if (!m) return false;
  const 집 = m[1].toLowerCase();
  return 남의집.some((d) => 집 === d || 집.endsWith('.' + d));
}

/** 주소에서 경로 부분만 추출 — 도메인에 'logo' 가 포함된 곳(예: logos.com)을 오탐하지 않게 */
function 주소경로(주소) {
  const s = String(주소 ?? '');
  return s.replace(/^[a-z]+:\/\/[^/]+/i, '').toLowerCase();
}

function 엠블럼판별(사진) {
  const 문구 = [사진?.제목, 사진?.대체텍스트, 사진?.캡션].filter(Boolean).join(' ').toLowerCase();
  const 경로 = 주소경로(사진?.src);
  const 출처경로 = 주소경로(사진?.출처주소);
  return 엠블럼어휘.filter((w) => 문구.includes(w) || 경로.includes(w) || 출처경로.includes(w));
}

/**
 * 리뷰 1건의 사진을 검증하여 **위반 사항을 문장으로 반환한다.** 빈 배열이면 통과다.
 *
 * @param {{category: string, image?: object}} 리뷰 — 프런트매터 원본
 * @returns {string[]} 위반 사항. 무엇을 어떻게 수정하면 되는지까지 기재한다
 */
export function 사진위반(리뷰) {
  const 위반 = [];
  const 분류코드 = 리뷰?.category;
  const 해당분류 = 분류조회(분류코드);
  if (!해당분류) {
    위반.push(`분류 「${분류코드}」는 미등록이다 — src/lib/리뷰분류.mjs 에 등재된 것만 사용한다`);
    return 위반;
  }

  const 사진 = 리뷰?.image;
  if (!사진) {
    /* ⛔ 사진이 없는 리뷰를 차단하지 않는다. 사장님은 「사진은 많이 있을 거다」라고 하셨지
       「없으면 게재하지 마라」고 하지 않으셨다. 다만 게재하면 규칙을 준수해야 한다. */
    return 위반;
  }

  if (!사진.src) 위반.push('사진 주소(src)가 없다');
  if (!사진.제공처) 위반.push('제공처가 없다 — 「/ 라이엇 게임즈」처럼 캡션에 부기할 명칭이다');
  if (!사진.출처주소) 위반.push('출처주소가 없다 — 어느 화면에서 입수했는지 기재한다');
  if (!사진.대체텍스트) 위반.push('대체텍스트(alt)가 없다 — 시각장애 이용자가 이 사진을 인지할 수 없다');

  /* ① 자체 서버에 보관하여 사용한다. 외부 서버를 직접 참조하면 일방적으로 중단될 수 있고,
        해당 서버에 당사 방문자 수만큼 부하를 전가한다. 내려받아 public/review/ 에 보관한다.
     ⚠ 출처주소는 «원 소재지»를 그대로 기재한다 — 내려받았다고 출처가 당사가 되지 않는다. */
  if (사진.src && !String(사진.src).startsWith('/review/')) {
    위반.push(`사진은 내려받아 자체 서버에 보관한다 — /review/… 로 기재한다 (현재: ${사진.src})`);
  }

  /* ② 제공처 유형이 해당 분류에서 허용되는가 */
  const 허용 = 해당분류.허용출처;
  if (!사진.제공처유형) {
    위반.push(`제공처유형이 없다 — ${해당분류.명칭} 에는 ${허용.join('·')} 중 하나를 기재한다`);
  } else if (!허용.includes(사진.제공처유형)) {
    위반.push(
      `${해당분류.명칭} 에 「${사진.제공처유형}」 사진은 사용하지 않는다 — `
      + `${허용.join('·')} 만 사용한다`,
    );
  }

  /* ③ 🔴 스포츠 계열의 엠블럼 금지 — 사장님이 명시적으로 금지하신 항목이다
     ─────────────────────────────────────────────────────────────────────
     🔴🔴 [2026-10-29 · 사장님] 「**연합뉴스 사진만 있으면 스코어와 각 팀의 엠블럼을
       사용해서 이미지를 세련되게 만들어**」
     ⭐ 두 말씀은 어긋나지 않는다. 10-26 에 막으신 것은 **엠블럼을 경기 사진 «대신»
       내거는 것**이다. 여기 허락하신 것은 **우리가 지은 점수판 그림**이고 엠블럼은 그 부품이다.
     ⇒ `제공처유형: own`(자체 제작)일 때만 이 금지를 푼다.
     ⛔ 남이 준 사진(team·league)에는 그대로 건다 — 구단 엠블럼을 받아다 사진 자리에
       걸어 두는 길은 여전히 막혀 있다.
     ⛔ 「own 이라 적으면 통과」가 되지 않는다 — 위 ①(자체 서버 보관)이 함께 선다. */
  /* ④ 🔴 자체 제작 그림의 출처주소에 포털·언론사 주소를 적지 않는다 (사장님 2026-11-20)
     ⛔ 지면이 그 주소를 「사진을 받아 온 곳」으로 내보낸다 — 안 가져온 것을 가져왔다고 적는 셈이다 */
  if (사진.제공처유형 === 'own' && 남의집인가(사진.출처주소)) {
    위반.push(
      '자체 제작 그림의 출처주소에 포털·언론사 주소를 적지 않는다 — '
      + `그 종목을 주관하는 곳의 공식 주소로 적는다 (현재: ${사진.출처주소})`,
    );
  }

  if (스포츠계열인가(분류코드) && 사진.제공처유형 !== 'own') {
    const 적출어휘 = 엠블럼판별(사진);
    if (적출어휘.length) {
      위반.push(
        `스포츠 리뷰에 엠블럼·로고를 사진으로 사용하지 않는다(적출 어휘: ${적출어휘.join(', ')}) — `
        + '구단이나 협회가 제공하는 «경기 사진»을 사용한다',
      );
    }
  }

  return 위반;
}

/**
 * 🔴🔴 [2026-10-26 · 라이브에서 터진 것] **사진이 404 였다.**
 * ───────────────────────────────────────────────────────────────────────────
 * 첫 리뷰를 배포하고 라이브를 눌러 보니 지면은 200 인데 **사진만 404** 였다.
 *   `public/review/…`      → `dist/review/…`          서울마켓츠 뿌리
 *   kculturewire.com 요청  → `/wikitip` 이 앞에 붙는다 → `dist/wikitip/review/…` 를 찾는다
 * ⇒ 세 사이트가 한 서버를 쓰므로 **KCW 가 쓰는 파일은 `public/wikitip/` 밑에 두어야 한다**
 *   (`public/wikitip/cardnews` 가 이미 그렇게 돼 있었다).
 *
 * ⛔ 빌드는 통과했다. 스키마도 통과했다. **파일이 거기 있는지는 아무도 안 봤다.**
 *   그래서 여기서 본다 — 없으면 빌드가 선다.
 * ⚠ 브라우저 주소(`/review/…`)와 파일 자리(`public/wikitip/review/…`)는 다르다.
 *   둘을 헷갈리지 않도록 이 함수 하나가 그 변환을 쥔다.
 *
 * @param {string} src  리뷰에 적힌 주소 (`/review/…`)
 * @param {{존재하나?: (경로: string) => boolean}} 도구  검사용으로 갈아끼울 수 있게 둔다
 */
export function 사진파일자리(src) {
  return `public/wikitip${String(src ?? '')}`;
}

export function 사진파일없나(리뷰, 존재하나) {
  const src = 리뷰?.image?.src;
  if (!src || typeof 존재하나 !== 'function') return null;
  const 자리 = 사진파일자리(src);
  if (존재하나(자리)) return null;
  return `사진 파일이 없다 — ${자리} 에 두어야 kculturewire.com 에서 ${src} 로 나간다`
    + ' (세 사이트가 한 서버를 쓴다. public/ 뿌리에 두면 404 다)';
}

