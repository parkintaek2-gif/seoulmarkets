/**
 * 같은 시 안의 다른 구를 찾는다.
 *
 * ## 🔴 왜 (2026-11-18 · 5번 · 실측)
 *
 *   네이버에 「화성시 고등학교 진학률」을 쳤더니 우리 지면이 뜨는데,
 *   **「화성시 만세구」(2곳)가 떴다.** 손님이 찾는 「화성시」(24곳)가 아니다.
 *
 *   화성시는 우리 자료에서 네 장으로 갈려 있다 —
 *   ```
 *   경기도-화성시          24곳   ← 주소에 구가 안 적힌 학교
 *   경기도-화성시-동탄구     7곳
 *   경기도-화성시-만세구     2곳
 *   경기도-화성시-효행구     1곳
 *   ```
 *   네 장을 합쳐야 화성시 **34곳**이다. 그런데 화성시 지면은 24곳만 보여 주고
 *   나머지 10곳이 있다는 말을 **한 마디도 하지 않는다.**
 *   손님은 「화성시에 고등학교가 24곳이구나」로 읽고 나간다. **사실과 다르다.**
 *
 *   같은 꼴이 20개 시에 있다 — 성남시·부천시·전주시·포항시·고양시·수원시 …
 *
 * ## ⛔ 왜 합쳐 버리지 않나
 *
 *   합치면 「동탄구 고등학교」를 찾는 손님이 갈 곳이 없어진다. 동탄은 그 자체로
 *   찾는 이름이다. **갈라 두되 서로 가리키게** 한다.
 *
 * ⛔ 이름을 글자로 자르지 않는다 — 「수원시 장안구」와 「수원시」를 가르려면
 *   빈칸을 봐야 한다. 「고양시 일산서구」처럼 구 이름에 시 이름이 안 들어가기도 한다.
 */

export type 동네 = { slug: string; 이름: string; 시도: string; 곳: number };

/**
 * 이름에서 **시 부분**만 꺼낸다.
 *   「화성시」        → 「화성시」
 *   「화성시 동탄구」  → 「화성시」
 *   「성북구」        → 「성북구」   (빈칸이 없으면 그대로)
 */
export function 시부분(이름: string): string {
  const s = String(이름 ?? '').trim();
  const 빈칸 = s.indexOf(' ');
  return 빈칸 < 0 ? s : s.slice(0, 빈칸);
}

/**
 * 같은 시의 다른 동네들. **자기 자신은 뺀다.**
 *
 * ⚠ 「성북구」처럼 빈칸이 없는 이름은 같은 시가 없다 — 빈 배열이 돌아온다.
 *   그래야 서울 강서구가 부산 강서구를 「같은 시」로 끌어오지 않는다
 *   (시·도가 다르므로 애초에 걸러지지만, 이름만으로도 안전하게 둔다).
 */
export function 같은시다른구<T extends 동네>(나: { slug: string; 이름: string; 시도: string }, 모두: T[]): T[] {
  const 내시 = 시부분(나.이름);
  /* 빈칸이 없는 이름은 「시 안의 구」가 아니다 — 묶을 것이 없다 */
  const 나는구인가 = 나.이름.includes(' ');
  return 모두
    .filter((a) => a.시도 === 나.시도 && a.slug !== 나.slug && 시부분(a.이름) === 내시)
    /* 내가 구가 아니고 상대도 구가 아니면 이름이 같다는 뜻이다 — 있을 수 없다.
       걸러 두면 자료가 이상해졌을 때 조용히 틀리지 않는다 */
    .filter((a) => 나는구인가 || a.이름.includes(' '))
    .sort((a, b) => a.이름.localeCompare(b.이름, 'ko'));
}

/** 같은 시 전체 학교 수 — 나를 포함한다. ⛔ 「우리 시에 N곳」을 말할 때 쓴다 */
export function 같은시합계<T extends 동네>(나: 동네, 다른구: T[]): number {
  return (Number(나.곳) || 0) + 다른구.reduce((a, b) => a + (Number(b.곳) || 0), 0);
}
