/**
 * 지면에-닿는가.mjs — **바뀐 파일이 지은 지면을 달라지게 하나.** 순수 함수만 둔다.
 *
 * ── 🔴 왜 따로 두나 (2026-11-18 · 5번) ────────────────────────────────
 * 배포하는 자 둘이 같은 물음을 쓴다. 처음엔 `될때까지-배포한다-서울마켓츠.mjs` 에만
 * 두었는데, 다른 자에서 쓰려면 **그 파일을 들여와야 한다.**
 * 그 파일은 들여오는 순간 배포 단추를 누른다 — 오늘 그 사고가 두 번 났다
 * (`ping-indexnow.mjs` 로 통보 8,108장 · 배포 단추 한 번).
 *
 * ⇒ 쓰는 쪽이 둘 이상이면 **아무것도 하지 않는 자리**로 꺼낸다.
 *   문(`직접불렸나`)을 다는 것은 둘째 방어고, 첫째는 **밖에 닿는 것과 안 닿는 것을 섞지 않는 것**이다.
 *
 * ── 🔴🔴 거르는 목록이다. 허용 목록이 아니다 ─────────────────────────
 * 처음에 `src|public|content` 만 「닿는다」로 잡는 허용 목록으로 썼다(2번이 검수해서 잡았다).
 * 그러면 **모르는 것이 「안 닿는다」가 된다** — 지면 자료가 `data/` 로 새로 생기면
 * 그 변경을 못 보고 옛 묶음을 라이브로 내보낸다. 허용 목록은 틀릴 때 나쁜 쪽으로 틀린다.
 *
 * ⚠ **git 은 한글 경로를 따옴표로 감싸 낸다** — 따옴표를 안 벗기면 이 거르개가 통째로 헛돈다.
 *   형제 자(`올린다-지어진지면.mjs` 의 `깨끗한가()`)가 겪어서 적어 둔 것이다.
 * ⛔ `scripts/` 는 **빼지 않는다.** 짓는 자(`build-once.mjs`)가 거기 있다.
 *   「이 스크립트는 지면과 상관없을 것」은 짐작이다 — 짐작으로 빼면 옛 판이 나간다.
 */

/**
 * 🔴 빌드가 **돌면서 스스로 다시 쓰는** 파일. `src/` 밑이지만 사람이 고친 것이 아니다.
 *
 * `build-once.mjs` 가 빌드 «앞에서» 이 둘을 부른다(112~122줄). 그러니 방금 올린 묶음은
 * 이미 새 내용으로 지어진 것이고, 커밋에 남은 그 변경은 **그 빌드가 낸 자국**이다.
 * 그것을 보고 「지면이 바뀌었으니 다시 지어라」 하면 **끝나지 않는다** — 다시 지으면 또 바뀐다.
 *
 * ⛔ 짐작으로 더하지 않는다 — `build-once.mjs` 가 실제로 부르는 자의 «나갈곳»을 읽고 적는다.
 */
export const 빌드가스스로쓰는것 = [
  'src/data/100yearmap/lastmod.json',      /* scripts/build-100y-lastmod.mjs 34줄 */
  'src/data/korea-disclosures-feed.json',  /* scripts/build-korea-disclosures-feed.mjs 32줄 */
];

/** 지면에 안 닿는 자리. ⛔ 여기 없는 것은 전부 «닿는다»로 친다 */
export const 안닿는곳 = /^(docs|logs|archive|tmp|dist|out)\/|\.(log|tsv)$/;

/** 바뀐 파일 가운데 **지은 지면이 달라지는 것**만 골라낸다 */
export function 지면에닿는것(파일들) {
  const 닿는다 = (f) => {
    const p = String(f).replace(/\\/g, '/').replace(/^"|"$/g, '');
    if (빌드가스스로쓰는것.includes(p)) return false;
    if (안닿는곳.test(p)) return false;
    return true;                              /* 🔴 모르는 것은 «닿는다» */
  };
  return (파일들 ?? []).filter(닿는다);
}

/**
 * 올린 묶음이 **지금 내보낼 것으로 써도 되나**.
 * @returns { 써도되나, 까닭, 걸린것 }
 */
export function 올린것을써도되나({ 올린커밋, 지금커밋, 바뀐것 }) {
  if (!올린커밋) return { 써도되나: false, 까닭: '쪽지를 못 읽었다', 걸린것: [] };
  if (올린커밋 === 지금커밋) return { 써도되나: true, 까닭: '올린 것이 바로 이 커밋이다', 걸린것: [] };
  /* ⛔ 무엇이 바뀌었는지 못 가리면 옛 판으로 친다. 모르는 것을 통과로 읽지 않는다 */
  if (바뀐것 == null) return { 써도되나: false, 까닭: '무엇이 바뀌었는지 못 가렸다', 걸린것: [] };
  const 걸린것 = 지면에닿는것(바뀐것);
  return 걸린것.length
    ? { 써도되나: false, 까닭: '지면에 닿는 것이 바뀌었다', 걸린것 }
    : { 써도되나: true, 까닭: '그 사이 바뀐 것이 지면에 안 닿는다', 걸린것: [] };
}

