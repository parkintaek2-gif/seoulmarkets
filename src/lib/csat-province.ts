/**
 * csat-province.ts — 시·도 한 곳의 수능 지원자 현황
 *
 * ── 🔴 왜 (2026-11-18 · 5번) ────────────────────────────────────────
 * `/100y/region/[시·도]` 17장의 제목이 「충북 — 지역으로 보기」였다.
 * **수치 이름이 한 글자도 없다.** 11-18 아침 측정에서 나온 것은 이것이었다 —
 * ```
 * 「의정부시 고등학교」          우리 0개 · 블로그 62
 * 「의정부시 고등학교 진학률」     우리 6개 · 블로그 48
 * ```
 * 지역 이름만으로는 안 들고 **수치 이름이 붙어야 든다.** 17장 전부가 그 상태였다.
 *
 * ⭐ 그리고 새 지면을 만드는 것보다 **있는 지면에 수치를 하나 더 얹는 것이 싸다.**
 *   그래서 평가원 원표(`csat-kice-tables.json`)를 이 17장에 잇는다.
 *
 * ⚠ 이 표가 주는 것은 **지원자 수**다. 시험 당일 실제로 본 사람(응시자)이 아니다 —
 *   결시자는 이 표에 없다. 화면에도 「지원자」로 적는다. 「응시자」로 바꿔 쓰지 않는다.
 * ⛔ 왜 그 과목을 골랐는지는 이 표가 답하지 않는다. 까닭을 지어 붙이지 않는다.
 * ⛔ 「몇 위」·「상위 몇 %」를 내지 않는다 — 지역 지면의 규칙 그대로다.
 * ⛔ 표에 그 시·도가 없으면 **null 을 돌려준다.** 0 으로 채우지 않는다.
 */
import 원 from '../data/100yearmap/csat-kice-tables.json';

export type 시도수능 = {
  시도: string;
  학년도: number;
  /** 지원자 수 (응시자가 아니다) */
  지원자: number;
  /** 지난 학년도 지원자 수. 표에 없으면 null */
  지난해: number | null;
  /** 올해 − 지난해. 지난해가 없으면 null */
  증감: number | null;
  /** 전국 지원자 가운데 이 시·도의 몫(%) */
  전국몫: number;
  /** 수학 선택자 가운데 미적분(%). 수학 선택자가 0이면 null */
  미적분율: number | null;
  /** 국어 선택자 가운데 언어와 매체(%). 국어 선택자가 0이면 null */
  언매율: number | null;
  /** 지원자 가운데 제2외국어·한문을 고른 사람(%) */
  제2외율: number | null;
};

const 표 = 원 as any;

/** 이 자료가 담은 학년도 — 큰 것이 올해다 */
export const 학년도들 = (): number[] =>
  Object.keys(표.시도별 ?? {}).map(Number).filter(Number.isFinite).sort((a, b) => a - b);

export const 올해학년도 = (): number | null => {
  const ys = 학년도들();
  return ys.length ? ys[ys.length - 1] : null;
};

/** 시험 날·성적통지 날 등 — 화면에 날을 손으로 박지 않으려고 자료에서 가져온다 */
export const 시험정보 = (): { 날: string; 성적통지: string; 시험장: number } | null => {
  const s = 표.시험;
  return s && s.날 ? { 날: String(s.날), 성적통지: String(s.성적통지 ?? ''), 시험장: Number(s.시험장 ?? 0) } : null;
};

export const 출처이름 = (): string => String(표.출처?.이름 ?? '');

const 몫 = (위: number, 아래: number): number | null =>
  아래 > 0 ? Math.round((위 / 아래) * 1000) / 10 : null;

/**
 * 시·도 한 곳을 뽑는다. `짧은지역명()` 이 내는 이름(서울·충북·전남 …)을 그대로 받는다.
 * ⛔ 비슷한 글자로 짐작해 잇지 않는다 — 표에 없으면 null 이다.
 */
export function 시도수능뽑기(짧은시도: string | null | undefined): 시도수능 | null {
  const 이름 = String(짧은시도 ?? '').trim();
  if (!이름 || 이름 === '계') return null;

  const 올해 = 올해학년도();
  if (올해 == null) return null;

  const 올 = 표.시도별?.[String(올해)]?.[이름];
  if (!올 || !Number.isFinite(Number(올.계)) || Number(올.계) <= 0) return null;

  const 지원자 = Number(올.계);
  const 전국 = Number(표.시도별?.[String(올해)]?.['계']?.계 ?? 0);

  const 지난 = 표.시도별?.[String(올해 - 1)]?.[이름];
  const 지난해 = 지난 && Number.isFinite(Number(지난.계)) && Number(지난.계) > 0 ? Number(지난.계) : null;

  const 수학선택 = Number(올.확통 ?? 0) + Number(올.미적분 ?? 0) + Number(올.기하 ?? 0);
  const 국어선택 = Number(올.화작 ?? 0) + Number(올.언매 ?? 0);

  return {
    시도: 이름,
    학년도: 올해,
    지원자,
    지난해,
    증감: 지난해 == null ? null : 지원자 - 지난해,
    전국몫: 몫(지원자, 전국) ?? 0,
    미적분율: 몫(Number(올.미적분 ?? 0), 수학선택),
    언매율: 몫(Number(올.언매 ?? 0), 국어선택),
    제2외율: 몫(Number(올.제2외선택 ?? 0), 지원자),
  };
}

/** 제목에 올릴 한 토막 — 「수능 지원자 1만3,693명」. 값이 없으면 null */
export function 제목토막(s: 시도수능 | null): string | null {
  if (!s || !(s.지원자 > 0)) return null;
  return `수능 지원자 ${s.지원자.toLocaleString('ko-KR')}명`;
}

/* ── 자가시험 ─────────────────────────────────────────────── */
/* eslint-disable no-console */
if (typeof process !== 'undefined' && process.argv?.includes('--자가시험')) {
  let 통 = 0; const 실: string[] = [];
  const 검 = (이름: string, 참: boolean) => { if (참) 통 += 1; else 실.push(이름); };

  const 올해 = 올해학년도();
  검('학년도가 둘 이상이다', 학년도들().length >= 2);
  검('올해 학년도가 2027이다', 올해 === 2027);

  const 충북 = 시도수능뽑기('충북');
  검('충북이 나온다', !!충북);
  검('충북 지원자가 원표와 같다 (13,693)', 충북?.지원자 === 13693);
  검('지난해 값이 붙는다', typeof 충북?.지난해 === 'number');
  검('증감이 올해−지난해다',
    충북 != null && 충북.지난해 != null && 충북.증감 === 충북.지원자 - 충북.지난해);
  /* ⛔ 미적분율의 분모는 지원자가 아니라 «수학을 고른 사람»이다 — 수학미선택이 섞이면 틀린다 */
  검('미적분율 분모가 수학 선택자다',
    충북?.미적분율 === Math.round((3856 / (8774 + 3856 + 297)) * 1000) / 10);
  검('언매율 분모가 국어 선택자다',
    충북?.언매율 === Math.round((2095 / (11460 + 2095)) * 1000) / 10);

  /* 🔴 17개 시도가 하나도 안 빠진다 — 한 곳이라도 null 이면 그 지면 제목이 비어 버린다 */
  const 시도순: string[] = 표.시도순 ?? [];
  검('표가 17개 시·도를 담는다', 시도순.length === 17);
  검('17개 시·도가 모두 뽑힌다', 시도순.every((x) => 시도수능뽑기(x) != null));
  검('17개 시·도 합이 전국 계와 같다',
    시도순.reduce((a, x) => a + (시도수능뽑기(x)?.지원자 ?? 0), 0)
    === Number(표.시도별?.[String(올해)]?.['계']?.계));
  검('전국몫을 다 더하면 100 언저리다',
    Math.abs(시도순.reduce((a, x) => a + (시도수능뽑기(x)?.전국몫 ?? 0), 0) - 100) < 0.5);

  /* ⛔ 「계」는 시·도가 아니다. 지역 지면이 이것을 집으면 전국 값이 한 지역 값으로 나간다 */
  검('계는 시·도로 치지 않는다', 시도수능뽑기('계') === null);
  검('표에 없는 이름은 null 이다', 시도수능뽑기('충청북도') === null);
  검('빈 이름은 null 이다', 시도수능뽑기('') === null && 시도수능뽑기(null) === null);

  검('제목토막이 수치 이름을 단다', 제목토막(충북) === '수능 지원자 13,693명');
  검('값이 없으면 제목토막도 없다', 제목토막(null) === null);

  const 시 = 시험정보();
  검('시험 날이 자료에서 온다', 시?.날 === '2026-11-19');
  검('출처가 평가원이다', 출처이름().includes('한국교육과정평가원'));

  if (실.length) { console.error('🔴 실패 ' + 실.length + '개\n - ' + 실.join('\n - ')); process.exit(1); }
  console.log(`✅ 시·도 수능 지원자 — 자가시험 ${통}개 통과`);
  process.exit(0);
}
