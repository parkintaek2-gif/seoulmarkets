/** 한 글자를 규칙대로 푼다. 한글이 아니면 그대로 돌려준다 */
export function 글자풀기(글자) {
  const c = String(글자 ?? '').charCodeAt(0);
  if (!Number.isFinite(c) || c < 0xac00 || c > 0xd7a3) return String(글자 ?? '');
  const n = c - 0xac00;
  return 초성[Math.floor(n / 588)] + 중성[Math.floor((n % 588) / 28)] + 종성[n % 28];
}

/** 첫 글자만 크게 */
const 크게 = (s) => (s ? s[0].toUpperCase() + s.slice(1) : s);

/**
 * 이름 한 벌을 로마자로.
 *
 * @returns {{로마자:string|null, 성:string|null, 이름:string|null, 관례인가:boolean, 까닭:string}}
 *   ⛔ 한글이 아니거나 비었으면 **로마자가 null** 이다. 지어내지 않는다.
 *   ⚠ `관례인가` 가 false 면 성을 규칙으로 푼 것이다 — 본인 표기와 다를 수 있다.
 */
export function 이름로마자(이름) {
  /* 🔴 [2026-10-11 08:0x · 5번] **글자 사이 공백 때문에 멀쩡한 이름을 놓치고 있었다.**
   *   공시에 「윤 성 진」·「이 종 원」처럼 **글자마다 띄어 쓴** 꼴이 섞여 있다.
   *   아래 「한글만인가」 검사가 그것을 떨어뜨려 로마자가 null 이 되었고,
   *   지면이 한글 이름을 그대로 내어 영문 지면에 한국어가 샜다.
   * 🔴🔴 처음에 **공백을 그냥 지웠다가 거짓을 만들 뻔했다.**
   *   「무뇨스 바르셀로 호세 안토니오」가 `Mu Nyo-seu-ba-reu-sel-ro-...` 로 지어졌다.
   *   **공백이 바로 외국인 이름을 걸러 주던 표시**였는데 그 길을 내가 막은 것이다.
   * ⇒ 실측해서 길이로 가른다. 공백 든 이름 98건을 재 보니 깨끗이 갈렸다 —
   * ```
   *   2~4자 42건   「전   웅」·「이   인」        글자 사이 띄움 — 한국 이름이다
   *   5자+  56건   「진광(CHEN GUANG)」·「TANIYAMA KEN」·「전태연 주1)」  — 손대지 않는다
   * ```
   * ⛔ 공백을 뺀 길이가 2~4자일 때만 지운다. 그보다 길면 **그대로 두어 아래에서 걸린다.** */
  /* 🔴 [2026-10-11 08:1x · 5번] **각주 표시가 붙은 이름을 통째로 놓치고 있었다.**
   *   로마자를 못 옮긴 71명을 재 보니 **42명이 각주 때문**이었다 —
   *     박동호(*2) · 최우일(*1) · 이승준(*) · 전태연⏎주1) · 김도현⏎(주1)
   *   공시가 표 아래 주석을 가리키려고 붙인 것이지 이름의 일부가 아니다.
   * ⛔ 각주만 뗀다. 괄호 안에 «글자»가 들어 있으면(「진광(CHEN GUANG)」) 손대지 않는다 —
   *   그것은 외국인 이름의 영문 병기라 우리가 옮길 것이 아니다. */
  const 받은것 = String(이름 ?? '')
    .replace(/\(\s*\*+\s*\d*\s*\)/g, '')     /* (*) · (*1) · (*2) */
    .replace(/\(\s*주\s*\d*\s*\)/g, '')      /* (주1) */
    .replace(/주\s*\d+\s*\)/g, '')           /* 주1)  — 괄호가 한쪽만 있는 꼴 */
    .replace(/\*+\d*/g, '')                  /* 괄호 없이 붙은 별표 */
    .trim();
  const 공백뺀것 = 받은것.replace(/\s+/g, '');
  const 원 = (공백뺀것.length >= 2 && 공백뺀것.length <= 4) ? 공백뺀것 : 받은것;
  /* 🔴 [2026-10-11 08:2x] 각주를 뗀 «원문»도 돌려준다 — 지면이 로마자 옆에 한글을 병기하는데,
     거기에 각주가 그대로 남아 「Lee Seung-jun (이승준(*))」으로 나갔다.
     그 별표가 가리키는 주석은 **우리 지면에 없다.** 뜻이 없는 글자를 손님에게 내지 않는다.
     ⛔ 버리는 것이 아니다 — 받은 글은 공시 원본에 그대로 있다. */
  const 정돈한이름 = 원;
  if (!원) return { 정돈한이름, 로마자: null, 성: null, 이름: null, 관례인가: false, 까닭: '빈 이름' };
  /* ⛔ 한글이 하나도 없으면 우리가 옮길 것이 아니다 — 이미 영문이거나 다른 말이다 */
  if (!/[가-힣]/.test(원)) {
    return { 정돈한이름, 로마자: null, 성: null, 이름: null, 관례인가: false, 까닭: '한글이 아니다' };
  }
  /* ⛔ 한글 아닌 글자가 섞여 있으면 손대지 않는다 — 직함이 붙었거나 꼴이 깨진 것이다 */
  if (!/^[가-힣]+$/.test(원)) {
    return { 정돈한이름, 로마자: null, 성: null, 이름: null, 관례인가: false, 까닭: '한글만으로 되어 있지 않다' };
  }
  if (원.length < 2) {
    return { 정돈한이름, 로마자: null, 성: null, 이름: null, 관례인가: false, 까닭: '한 글자는 성과 이름을 못 가른다' };
  }

  /* 두 글자 성을 «먼저» 본다 — 세 글자 이름(남궁수)도 있으므로 길이로 막지 않는다 */
  const 두 = 원.slice(0, 2);
  let 성글자; let 성영문; let 관례;
  if (두글자성[두] && 원.length >= 3) {
    성글자 = 두; 성영문 = 두글자성[두]; 관례 = true;
  } else {
    성글자 = 원[0];
    성영문 = 성관례[성글자] ?? null;
    관례 = 성영문 !== null;
    if (!성영문) 성영문 = 크게(글자풀기(성글자));
  }

  const 이름글자 = 원.slice(성글자.length);
  if (!이름글자) {
    return { 정돈한이름, 로마자: null, 성: null, 이름: null, 관례인가: false, 까닭: '이름 자리가 비었다' };
  }
  /* 이름은 음절마다 붙임표 — 「영현」 → 규칙대로 「Yeong-hyeon」.
     ⚠ 관례 표기(Young-hyun)는 사람마다 달라 지어낼 수 없다. 규칙대로 적는다.
     ⛔ 붙임표 «뒤»는 소문자다 — 처음에 Yeong-Hyeon 으로 냈다가 자가시험이 잡았다.
       표기법은 한 이름을 한 낱말로 보고 첫 글자만 크게 쓴다. */
  const 이름영문 = [...이름글자]
    .map((g, i) => (i === 0 ? 크게(글자풀기(g)) : 글자풀기(g)))
    .join('-');

  return {
    정돈한이름,
    로마자: `${성영문} ${이름영문}`,
    성: 성영문,
    이름: 이름영문,
    관례인가: 관례,
    까닭: 관례 ? '성은 널리 쓰이는 표기, 이름은 국립국어원 규칙' : '성·이름 모두 국립국어원 규칙(관례 표기를 모른다)',
  };
}

