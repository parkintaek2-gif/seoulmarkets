/**
 * 전각을 반각으로, 전각 공백을 보통 공백으로.
 * ⚠ 이 한 줄이 없으면 「ＣＥＯ」 쓰는 회사에서만 조용히 틀린다 — 겉으로 똑같아 보인다.
 */
export function 반각으로(글) {
  return String(글 ?? '')
    .replace(/[！-～]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xFEE0))
    .replace(/　/g, ' ')
    /* 🔴 [2026-10-11 12:2x · 5번] **키릴 글자가 섞여 들어온 회사가 있다.**
       실측 — 종목 7571 의 표지가 「代表取締役社長ＣＥО  山野  義友」인데
       그 「О」는 로마자 O(U+004F)가 아니라 **키릴 О(U+041E)** 다. 눈으로는 똑같다.
       ⇒ 전각을 반각으로 모아도 「CEО」가 되어 조각 「CEO」에 안 걸렸다.
       ⚠ 겉이 같은 글자는 «그 회사에서만» 조용히 틀린다. 가장 늦게 들키는 갈래다.
       ⛔ 바꾸는 것은 여기 적힌 다섯 글자뿐이다 — 러시아어 이름을 손대지 않으려고
         로마자와 모양이 «완전히» 같은 것만 골랐다. */
    .replace(/[АЕОСР]/g, (c) => ({
      'А': 'A', 'Е': 'E', 'О': 'O', 'С': 'C', 'Р': 'P',
    }[c] ?? c));
}

/**
 * 표지 한 줄을 직위와 이름으로.
 * @returns {{직위:string|null, 이름:string|null, 직위영문:string|null, 원문:string}}
 *   ⛔ 못 가르면 직위·이름을 **지어내지 않고** null 로 둔다. 원문은 언제나 돌려준다.
 */
export function 대표자가르기(원문) {
  const 민 = 반각으로(원문).replace(/\s+/g, ' ').trim();
  if (!민) return { 직위: null, 이름: null, 직위영문: null, 원문: String(원문 ?? '') };

  /* 조각을 떼는 동안에는 공백을 무시한다 — 「代表取締役社長 社長役員」처럼 사이에 끼어 있다 */
  let 남은 = 민.replace(/ /g, '');
  const 직위조각 = [];
  const 영문조각 = [];
  let 돌이 = 0;
  while (남은 && 돌이++ < 20) {
    const 맞는것 = 조각.find(([ko]) => 남은.startsWith(ko));
    if (!맞는것) break;                      /* 모르는 글자가 나오면 거기서부터 이름이다 */
    직위조각.push(맞는것[0]);
    if (맞는것[1] && !영문조각.includes(맞는것[1])) 영문조각.push(맞는것[1]);
    남은 = 남은.slice(맞는것[0].length);
  }
  /* ⛔ 한 조각도 못 뗐으면 직위를 모르는 것이다 — 통째로 이름이라고 하지 않는다 */
  if (!직위조각.length) return { 직위: null, 이름: null, 직위영문: null, 원문: String(원문 ?? '') };
  /* ⛔ 뗀 뒤 남은 것이 없으면 이름이 없는 것이다 — 직위를 이름으로 쓰지 않는다 */
  if (!남은) return { 직위: 직위조각.join(''), 이름: null, 직위영문: 영문조각.join(', ') || null, 원문: String(원문 ?? '') };

  /* 이름은 **원문 쪽에서** 떠 온다 — 성과 이름 사이 공백을 살리려고.
     뗀 글자 수만큼 원문(공백 민 것)에서 건너뛴 자리부터가 이름이다 */
  const 뗀수 = 직위조각.join('').length;
  let 본수 = 0;
  let 자리 = 0;
  for (; 자리 < 민.length && 본수 < 뗀수; 자리 += 1) if (민[자리] !== ' ') 본수 += 1;
  let 이름 = 민.slice(자리).trim().replace(/\s+/g, ' ');

  /* 🔴🔴 [2026-10-11 12:3x · 5번] **한 칸에 사람이 «둘» 들어 있는 회사가 넷 있다.**
   * ```
   *   5136  代表取締役CEO　高橋　和久代表取締役CPO　鳥生　格
   *   6049  代表取締役　CEO　山木　学代表取締役　COO　領下　崇
   *   462A · 504A 도 같은 꼴
   * ```
   *   그대로 두면 이름이 「高橋 和久代表取締役CPO 鳥生 格」이 되어 **그런 사람이 없다.**
   *   지면에 그 글자가 한 사람 이름으로 박힌다 — 지어낸 것과 다를 바 없다.
   * ✅ 이름 안에 **직위 조각이 다시 나오면** 거기서부터가 둘째 사람이다. 거기서 끊는다.
   *   ⛔ 사람 이름에 「代表取締役」이 들어갈 일은 없다 — 그래서 이 자가 안전하다.
   * ⚠ 둘째 사람은 **버리지 않고** `또있다` 로 밝힌다. 「한 명뿐」이라고 말하지 않는다.
   *   ⛔ 「대표가 한 명」이라고 적는 것과 「우리가 한 명만 담았다」는 다른 말이다. */
  /* 🔴 [2026-10-11 12:3x] 처음에 「한자 조각이면 아무거나」로 끊었더니 **더 나빠졌다** —
       8219 의 「ＯＭＯリテール本部長　遠藤　泰三」이 `本部長` 에서 끊겨
       이름이 **「OMOリテール」**이 됐다. 그것은 사람 이름이 아니다.
     ⇒ 내가 찾는 것은 「아무 직위」가 아니라 **「둘째 사람의 시작」**이다.
       실측한 넷이 전부 `代表…` 으로 다시 시작한다. 그것만 본다.
     ⛔ 고치다가 더 나쁘게 만들지 않는다. 넓힌 뒤에는 반드시 전수로 다시 센다. */
  /* 🔴 [2026-10-11 12:4x · 5번] **「〇〇本部長」은 부서 이름이 «앞»에 온다.**
       실측 다섯 — 海外事業本部長 · 営業本部長 · マーケティング本部長 ·
       ＯＭＯリテール本部長 · デジタル推進本部長.
     앞에서부터 떼는 구조라 「海外事業」에서 멈춰 「本部長」에 못 닿는다.
     ⇒ 이름 안에 「本部長」이 있으면 **그 뒤부터가 이름**이다. 앞은 통째로 직위다.
     ⛔ 사람 이름에 「本部長」 세 글자가 들어갈 일은 없다 — 그래서 이 자가 안전하다
       (「本」 한 글자는 성에 쓰이지만 세 글자째는 아니다. 단독 「長」을 안 넣은 것과 같은 결이다). */
  const 본부장자리 = 이름.indexOf('本部長');
  if (본부장자리 > 0) 이름 = 이름.slice(본부장자리 + 3).trim();

  /* 🔴 [2026-10-11 13:2x · 5번] **이름 «끝»에 직위가 붙은 꼴 — 라이브를 눌러 보고 찾았다.**
   *   4612(닛폰페인트홀딩스) 지면에 「若月 雄一郎取締役」이 한 사람 이름으로 박혀 있었다.
   *   그런 사람은 없다. 원문이
   *     代表取締役共同社長　若月　雄一郎取締役　代表執行役共同社長　ウィー・シューキム
   *   인데, 둘째 사람의 직위가 「取締役 代表執行役共同社長」이라 앞 두 글자가 첫 사람에게 붙었다.
   * ⇒ 이름이 직위 조각으로 **끝나면** 그 조각을 뗀다.
   *   ⛔ 이름 «안»이 아니라 «끝»만 본다 — 안까지 보면 멀쩡한 이름을 자른다(本部長 때 겪었다).
   *   ⛔ 두 글자 이상 «한자» 조각만 본다 — 부호·로마자 약어는 이름 끝에 오지 않는다.
   *   ⛔ 떼서 이름이 비면 안 뗀다 — 직위를 이름으로 쓰지 않는 규칙과 같은 결이다.
   * ⚠ 전수 3,700명을 재 보니 걸리는 사람이 **딱 하나**고 떼도 비는 이름은 0명이다.
   *   한 사람을 위해 넣는 것이 아니라, 분기마다 오는 **같은 꼴**을 막으려고 넣는다.
   * ⛔⛔ **차례가 뜻을 가른다 — 둘째 사람을 끊은 «뒤»에 본다.**
   *   처음에 이 자를 앞에 뒀더니 안 걸렸다. 그때 이름은 아직
   *   「若月 雄一郎取締役 代表執行役共同社長 ウィー・シューキム」이라 取締役 으로 «끝나지 않는다».
   *   아래 끊기가 먼저 돌아야 「若月 雄一郎取締役」이 되고, 그제서야 끝이 보인다. */
  let 또있다 = null;
  const 뒤직위 = 조각
    .filter(([ko]) => ko.startsWith('代表'))
    .map(([ko]) => 이름.indexOf(ko))
    .filter((i) => i > 0);
  if (뒤직위.length) {
    const 끊을자리 = Math.min(...뒤직위);
    또있다 = 이름.slice(끊을자리).trim() || null;
    이름 = 이름.slice(0, 끊을자리).trim();
  }

  const 끝조각 = 조각
    .map(([ko]) => ko)
    .filter((k) => k.length >= 2 && /^[㐀-鿿]+$/.test(k))
    .find((k) => 이름.endsWith(k) && 이름.slice(0, -k.length).trim());
  if (끝조각) 이름 = 이름.slice(0, -끝조각.length).trim();

  return {
    직위: 직위조각.join(''),
    이름: 이름 || null,
    직위영문: 영문조각.join(', ') || null,
    또있다,
    원문: String(원문 ?? ''),
  };
}

/** 직위만 영문으로 — 못 옮기면 null */
export function 일본직위영문(직위) {
  const r = 대표자가르기(`${String(직위 ?? '')} 　`);
  return r.직위영문;
}

