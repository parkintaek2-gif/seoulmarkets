/**
 * 초등학교 **지역 한 장**(/elementary/area/[slug])의 목록을 만든다.
 *
 * ## 🔴 왜 목록을 여기 한 곳에 두나
 *
 *   `[slug].astro` 의 `getStaticPaths` 와 `sitemap.xml.ts` 가 **같은 목록**을 봐야 한다.
 *   두 곳에 따로 적으면 한쪽만 늘어 「사이트맵엔 있는데 지면이 404」 또는
 *   「지면은 있는데 사이트맵에 없다」가 된다 — 이 저장소에서 2026-08-06 에
 *   `/after` 가 바로 그렇게 어긋난 적이 있다.
 *
 * ⛔ 슬러그를 여기 말고 다른 데서 이어 붙이지 않는다.
 */
import { 지역슬러그, 열쇠만들기, type 지역 } from './school-area';

export type 초등지역 = {
  /** 「경기도 화성시」 — 학교 자료의 `열쇠` 칸과 같은 글자 */
  열쇠: string;
  시도: string;
  구: string;
  /** 그 지역의 초등학교 수 */
  곳: number;
  /** 문 연 지 100년이 넘은 곳 수 */
  백년: number;
  /** 주소에 쓰는 조각 — 「경기도-화성시」 */
  slug: string;
};

/**
 * 지역 한 줄을 `school-area` 가 아는 꼴로 바꾼다.
 *
 * ⚠ 세종은 시·도와 이름이 같다. `지역슬러그` 가 그 경우를 한 번만 쓰게 처리하므로
 *   여기서 따로 손대지 않는다 — 손대면 두 벌이 된다.
 */
function 꼴맞추기(a: { 시도: string; 구: string; 열쇠?: string }): 지역 {
  return {
    시도: a.시도,
    이름: a.구,
    열쇠: a.열쇠 ?? 열쇠만들기(a.시도, a.구),
    /* 「수원시 장안구」처럼 이름에 빈칸이 있으면 큰 시 안의 구다 */
    시안의구: /\s/.test(a.구),
  };
}

/**
 * 낼 지면 목록. **슬러그가 겹치면 뒤엣것을 버린다** —
 * 겹친 채로 두면 Astro 가 같은 주소를 두 번 만들어 빌드가 죽는다.
 *
 * ⚠ 곳수가 적다고 빼지 않는다. 한 곳뿐인 동네도 그 동네 사람에게는 찾는 지면이다.
 *   (고등학교 지면은 값을 받던 때라 10곳으로 갈랐지만, 여기는 파는 것이 없다.)
 */
export function 초등지역목록(자료: { 지역: any[] }): 초등지역[] {
  const 본것 = new Set<string>();
  const 낸다: 초등지역[] = [];
  for (const a of 자료.지역 ?? []) {
    if (!a || !a.시도 || !a.구) continue;
    const slug = 지역슬러그(꼴맞추기(a));
    if (본것.has(slug)) continue;
    본것.add(slug);
    낸다.push({
      열쇠: a.열쇠 ?? 열쇠만들기(a.시도, a.구),
      시도: a.시도,
      구: a.구,
      곳: Number(a.곳) || 0,
      백년: Number(a.백년) || 0,
      slug,
    });
  }
  return 낸다;
}

/** 한 지역의 주소. ⛔ 지면에서 따로 이어 붙이지 않는다 */
export const 초등지역주소 = (slug: string): string => `/elementary/area/${slug}`;
