/**
 * 🈁 **조사 고르기** — 「광진구**은**」 을 「광진구**는**」 으로.
 *
 * ## 🔴 왜 (2026-08-10 07:5x · 라이브에서 눈으로 찾았다)
 *
 *   2번이 「일반고 1,703장이 비어 있다」 하셔서 한 장을 열어 봤는데, 비어 있지 않았고
 *   대신 **이것**이 보였다 —
 *   ```
 *   삼척시은 학교가 8곳이라 무료로 열어 둔 지면입니다.     ← /school/7801089
 *   ```
 *   ⚠ 자가 못 잡는 종류다. 200 이고 숫자도 맞다. **읽어야만 보인다.**
 *
 * ## 얼마나 나오나 (실측)
 *
 *   ```
 *   학교 지면    64개 지역이 틀린다 → 그 지역 학교 **425장**   (「은」이 박혀 있다)
 *   대학 지면    17곳                                        (「…과학기술원는/를」)
 *   고교 학과    47곳                                        (「보통과정는」·「과학가」)
 *   ```
 *
 * ## ⚠ 이 자가 못 하는 것
 *
 *   ```
 *   ⛔ 숫자·영문·기호로 끝나는 말은 **손대지 않는다.** 「A대학」 같은 것은 사람이 정한다
 *   ⛔ 「이/가」 를 「은/는」 으로 바꾸는 일 같은 **뜻 고르기는 안 한다.** 받침만 본다
 *   ⚠ 한글이 아닌 글자로 끝나면 **박아 둔 것을 그대로** 돌려준다. 조용히 바꾸지 않는다
 *   ```
 */

/** 조사 쌍 — 앞이 받침 있을 때 / 없을 때 */
const 쌍들 = {
  은는: ['은', '는'],
  이가: ['이', '가'],
  을를: ['을', '를'],
  와과: ['과', '와'],
  으로로: ['으로', '로'],
} as const;

export type 조사쌍 = keyof typeof 쌍들;

/** 조사를 고를 때 어디까지 셀 것인가 */
export type 셈법 = {
  /** 영문·숫자로 끝나는 말도 «읽는 소리»로 받침을 센다. 기본은 끈 상태다 */
  영문숫자?: boolean;
};

/**
 * 마지막 글자에 받침이 있나.
 * ⚠ 한글 음절이 아니면 `null` — **모른다**는 뜻이다. 0/false 로 뭉개지 않는다.
 */
export function 받침있나(말: string, 셈: 셈법 = {}): boolean | null {
  const 끝 = String(말 ?? '').trim().slice(-1);
  const c = 끝.charCodeAt(0);
  if (c >= 0xac00 && c <= 0xd7a3) return (c - 0xac00) % 28 !== 0;
  if (셈.영문숫자) {
    const 읽음 = 읽는법[끝.toUpperCase()];
    if (읽음) return 읽음 !== '';
  }
  return null; /* 한글 음절이 아니다 — 모른다 */
}

/**
 * 🔴 [2026-11-20] **영문·숫자로 끝나는 말의 받침** — 읽는 소리의 끝을 적어 둔다.
 * ─────────────────────────────────────────────────────────────────────────
 * 「창원 LG**이** 수원 KT**을** 이겼다」가 케이리뷰 그림 설명에 들어갈 뻔했다.
 * 구단 이름은 거의 영문으로 끝난다(DB·LG·KT·SK·KCC) — 한글 음절만 보면 영영 못 고른다.
 * ⇒ 값은 «그 글자를 읽는 소리»의 끝소리다. 빈 문자열은 받침이 없다는 뜻이다.
 * ⛔ 기본으로 켜지 않는다 — 백년지도 지면 8곳이 이 자를 이미 쓰고 있고,
 *   그곳들은 「영문은 손대지 않는다」를 전제로 기본값을 박아 두었다.
 *   새로 쓰는 쪽이 `{ 영문숫자: true }` 로 켠다.
 */
const 읽는법: Record<string, string> = {
  A: '', B: '', C: '', D: '', E: '', F: '', G: '', H: '', I: '', J: '', K: '',
  L: 'ㄹ', M: 'ㅁ', N: 'ㄴ', O: '', P: '', Q: '', R: 'ㄹ', S: '', T: '',
  U: '', V: '', W: '', X: '', Y: '', Z: '',
  '0': 'ㅇ', '1': 'ㄹ', '2': '', '3': 'ㅁ', '4': '', '5': '', '6': 'ㄱ',
  '7': 'ㄹ', '8': 'ㄹ', '9': '',
};

/** 끝소리가 `ㄹ` 인가 — 「으로/로」를 가르는 데만 쓴다 */
function 리을로끝나나(말: string, 셈: 셈법): boolean {
  const 끝 = String(말).trim().slice(-1);
  const c = 끝.charCodeAt(0);
  if (c >= 0xac00 && c <= 0xd7a3) return (c - 0xac00) % 28 === 8;
  if (셈.영문숫자) return 읽는법[끝.toUpperCase()] === 'ㄹ';
  return false;
}

/**
 * 말 뒤에 붙일 조사를 고른다.
 * @param 기본 한글이 아닌 것으로 끝나 못 고를 때 돌려줄 것(지금 지면에 박혀 있던 것)
 *
 * ⚠ `ㄹ` 받침은 「으로/로」에서 예외다 — 「서울로」이지 「서울으로」가 아니다.
 */
export function 조사(말: string, 쌍: 조사쌍, 기본?: string, 셈: 셈법 = {}): string {
  const 받침 = 받침있나(말, 셈);
  if (받침 === null) return 기본 ?? 쌍들[쌍][1];
  /* ⚠ `ㄹ` 받침은 「으로/로」에서 예외다 — 「서울로」이지 「서울으로」가 아니다 */
  if (쌍 === '으로로' && 리을로끝나나(말, 셈)) return '로';
  return 받침 ? 쌍들[쌍][0] : 쌍들[쌍][1];
}

/** 말과 조사를 붙여서 돌려준다 — `말조사('광진구','은는')` → `'광진구는'` */
export function 말조사(말: string, 쌍: 조사쌍, 기본?: string, 셈: 셈법 = {}): string {
  return `${말}${조사(말, 쌍, 기본, 셈)}`;
}

