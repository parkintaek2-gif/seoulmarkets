/**
 * 유닛자리표.mjs — **어느 사이트를 어느 자리가 맡나. 여기가 정본이다.**
 *
 * ── 🔴🔴 왜 (2026-10-10 21:1x · 5번) ───────────────────────────────
 * 22시 방문자 방송이 담당을 **뒤바꿔** 내고 있었다 —
 * 「6번 SeoulMarkets」·「5번 K Culture Wire」·「3번 백년지도」.
 * 그런데 지금 분장은 역할 카드에 이렇게 박혀 있다 —
 * ```
 * 5번   SeoulMarkets 개발 · 감수 · 자물쇠 셋
 * 2번   SeoulMarkets 개발 분담
 * 1번   «모든 사이트» 콘텐트 — 네 곳 × 6편
 * ```
 * 3·4·6번은 사장님이 2026-10-04 에 「원래 안쓰잖아」라고 하신 자리다.
 *
 * ⛔ 그 틀린 이름표가 **사장님께 가는 방송에 그대로 찍히고 있었다.**
 *   「누구를 깨워야 하나」가 엉뚱한 데로 간다.
 * ⛔ 같은 표가 `broadcast-visitors-dwell.mjs` 와 `유닛별-방문자.mjs` **두 곳**에 있었다.
 *   두 곳에 적으면 한 곳만 고쳐진다 — 오늘 그 꼴이었다.
 * ⇒ **여기 한 곳**에 둔다. 두 자가 여기서 가져다 쓴다.
 *
 * ⚠ 한 사이트에 손이 둘일 수 있다. 방송은 «그 사이트를 맡은 자리»를 적는 것이므로 둘 다 적는다.
 * ⚠ 분장이 바뀌면 **역할 카드와 함께** 고친다. 여기만 고치면 다음에 또 어긋난다.
 */

export const 자리표 = [
  { 유닛: '1번', 이름: '백년지도', 호스트: ['100yearmap.com', 'www.100yearmap.com'] },
  { 유닛: '1번', 이름: 'KLifeMap', 호스트: ['klifemap.ai', 'www.klifemap.ai'] },
  { 유닛: '1번', 이름: 'K Culture Wire', 호스트: ['kculturewire.com', 'www.kculturewire.com'] },
  { 유닛: '5번·2번', 이름: 'SeoulMarkets', 호스트: ['seoulmarkets.com', 'www.seoulmarkets.com'] },
];

/** 우리가 만든 것이라 아무 자리 것도 아닌 호스트 */
export const 우리것 = ['127.0.0.1', 'localhost', 'parkintaek2-gif.github.io'];

/** 사장님이 「원래 안 쓴다」고 하신 자리 (2026-10-04) — 방송에 적지 않는다 */
export const 안쓰는자리 = [3, 4, 6];

/* ── 자가시험 ─────────────────────────────────────────────────── */
if (process.argv[1] && process.argv.includes('--자가시험')) {
  let 통 = 0; let 탈 = 0;
  const 검 = (이름, 참) => { if (참) { 통++; console.log('✅', 이름); } else { 탈++; console.log('🔴', 이름); } };

  검('네 사이트가 다 있다', 자리표.length === 4);
  검('🔴 SeoulMarkets 는 5번·2번이다 — 오늘 6번으로 적혀 있었다',
    자리표.find((x) => x.이름 === 'SeoulMarkets').유닛 === '5번·2번');
  검('🔴 K Culture Wire 는 1번이다 — 오늘 5번으로 적혀 있었다',
    자리표.find((x) => x.이름 === 'K Culture Wire').유닛 === '1번');
  검('🔴 안 쓰는 자리(3·4·6번)가 이름표에 하나도 없다',
    !자리표.some((x) => 안쓰는자리.some((n) => x.유닛.includes(`${n}번`))));
  검('⛔ 호스트가 겹치지 않는다 — 겹치면 한 방문이 두 번 세어진다', (() => {
    const 다 = 자리표.flatMap((x) => x.호스트);
    return new Set(다).size === 다.length;
  })());
  검('⛔ 우리 것은 자리표에 없다 — 우리 확인이 방문자로 섞이면 안 된다',
    !자리표.some((x) => x.호스트.some((h) => 우리것.includes(h))));
  검('모든 줄이 유닛·이름·호스트를 갖는다',
    자리표.every((x) => x.유닛 && x.이름 && Array.isArray(x.호스트) && x.호스트.length));

  console.log(탈 ? `\n🔴 자가시험 ${탈}건 탈` : `\n✅ 자가시험 ${통} 통과`);
  process.exit(탈 ? 1 : 0);
}
