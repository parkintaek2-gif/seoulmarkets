#!/usr/bin/env node
/**
 * check-jbnews-막힌기사.mjs
 *   — **데스킹에 막혀 안 나간 기사가 «그대로 버려졌나»를 본다.**
 *
 * ── 🔴🔴 왜 (2026-10-05 · 5번) ────────────────────────────────────────
 * `collect-jbnews-sports-articles.mjs` 는 기사를 막은 뒤 화면에 이렇게 찍는다 —
 * ```
 *   ⛔ 안 보냈다 — 연합뉴스 사진이 없다 (사장님 2026-10-02)
 *   ⭐ 막고 끝내지 않는다 — 회차에 다시 쓰라고 시킨다
 * ```
 * **그런데 그 아랫줄이 거짓이었다.** 자국만 남기고 `continue` 할 뿐,
 * 회차에 다시 쓰라고 «시키는 자리가 없다». 화면은 했다고 말하는데 안 한 것이다.
 *
 * 그래서 오늘 재 보니 **이틀 사이에 세 건**이 그대로 버려져 있었다 —
 * ```
 *   2026-10-04 11시 · 2026-10-04 14시 · 2026-10-05 09시   전부 「사진이 없다」
 * ```
 * 사장님은 그 세 건을 못 받으셨고, 아무 데서도 안 걸렸다.
 *
 * ⭐ 막는 것은 옳다(사진 없는 기사는 중부매일이 못 쓴다). **막고 잊는 것**이 흠이다.
 * ⛔ 이 자는 배포를 막지 않는다 — 기사는 배포와 상관이 없다. 두 시간 점검에서 «보이게» 한다.
 *
 * 쓰는 법
 *   node scripts/check-jbnews-막힌기사.mjs
 *   node scripts/check-jbnews-막힌기사.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const 자국방 = path.join(뿌리, 'docs', '고정업무-마커', '중부매일-스포츠-보낸자국');

/** 며칠 치를 보나 — 그보다 오래된 것은 이미 때가 지났다 */
export const 볼날수 = 3;

/** 파일 이름에서 날과 회차를 집는다. ⛔ 못 집으면 null */
export function 날회차(이름) {
  const m = /^(\d{4}-\d{2}-\d{2})_(\d{2})시\.txt$/.exec(String(이름 ?? ''));
  return m ? { 날: m[1], 시: m[2] } : null;
}

/**
 * 자국 하나를 읽는다.
 * ⛔ 「안보냄」과 「보냄」이 한 파일에 같이 있으면 **나중에 보낸 것**이다 — 막힌 것이 아니다.
 */
export function 자국읽기(글) {
  const s = String(글 ?? '');
  const 막혔나 = /\[안보냄\]|\[병역·안보냄\]/.test(s);
  /**
   * ⚠ 「받는곳 (안 보냄)」 의 «안 보냄» 을 보냄으로 읽으면 안 된다 — 줄머리로 가린다.
   *
   * 🔴🔴 [2026-10-05 14:5x · 5번] **이 자가 `[보냄]` 머리를 기다리고 있었는데
   *   보내는 쪽은 그런 머리를 «한 번도 적은 적이 없다».** 실제로 적히는 꼴은
   *   `[스포츠] 2026-10-05 09시 — 제목` 과 `받는곳 parkintaek2@gmail.com` 이다.
   *   ⇒ 그래서 09·10·11시 세 건을 사진 붙여 다시 보낸 «뒤»에도
   *     이 자가 「그대로 버려졌다」고 계속 울었다. 거짓 빨강이다.
   *   ⛔ 거짓 빨강이 쌓이면 진짜 빨강을 못 본다 — 자가 자기 꼴을 지어내고 있었다.
   * ⭐ 보냈다는 표는 **받는곳에 진짜 주소가 적혔나**다. 그것만이 밖에서 난 결과다.
   */
  const 보냈나 = s.split(/\r?\n/).some((줄) => {
    const t = 줄.trim();
    if (/^\[보냄\]/.test(t)) return true;
    const m = /^받는곳\s+(.+)$/.exec(t);
    return !!m && /@/.test(m[1]);        /* ⛔ 「(안 보냄)」 에는 `@` 가 없다 */
  });
  const 까닭 = (s.match(/^까닭\s+(.+)$/m) ?? [])[1] ?? '';
  const 제목 = (s.match(/^\[(?:안보냄|병역·안보냄)\]\s+(.+)$/m) ?? [])[1] ?? '';
  /* 🔴 [2026-10-06 · 5번] 「까닭」은 다섯 글자 딱지일 뿐이다 — 데스킹이 «무슨 말»을 했는지가
     있어야 회차 지시문을 고칠 수 있다. 없는 자국(옛날 것)은 null 이다.
     ⛔ null 을 ''로 뭉개지 않는다 — 「안 적혀 있다」와 「까닭이 없다」는 다른 칸이다. */
  const 말줄 = s.match(/^데스킹말\s+(.+)$/m);
  const 데스킹말 = 말줄 ? 말줄[1].trim() : null;
  /* 🔴🔴 [2026-11-12 · 5번] **「접었다」를 적을 자리가 없었다.**
     ─────────────────────────────────────────────────────────────
     11-11 에 막힌 배구 기사 넷은 경기가 이틀 지나 기사 가치가 사라졌다.
     보낼 수도 없고 되살려도 철 지난 글이 나오는데, 이 자는 「보냈나」만 보므로
     **두 시간마다 영영 운다.** 거짓 빨강이 쌓이면 진짜 빨강을 못 본다.
     ⇒ 사람이 「접음 …」 한 줄을 적으면 그것으로 끝난 것으로 센다.
     ⛔ 「접음」을 자가 혼자 적지 않는다 — 그것이 바로 「막고 잊는 것」이다.
     ⚠ 접은 것은 «없던 일»이 아니다. 따로 세어 ⬜ 로 적는다. */
  const 접음줄 = s.match(/^접음\s+(.+)$/m);
  return { 막혔나, 보냈나, 접었나: !!접음줄, 접은까닭: 접음줄 ? 접음줄[1].trim() : null,
    까닭: 까닭.trim(), 제목: 제목.trim(), 데스킹말 };
}

/** 오늘부터 며칠 전까지의 날짜 글. ⛔ toISOString 금지 — 이 PC 는 KST 다 */
export function 요즘날들(오늘 = new Date(), 날수 = 볼날수) {
  const 것 = [];
  for (let i = 0; i < 날수; i += 1) {
    const d = new Date(오늘.getFullYear(), 오늘.getMonth(), 오늘.getDate() - i);
    것.push(`${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`);
  }
  return 것;
}

/**
 * 막힌 채 버려진 기사를 찾는다.
 * ⛔ 자국방을 못 읽으면 null 이다. 빈 배열이 아니다.
 */
export function 막힌것(옵션 = {}) {
  const { 방 = 자국방, 읽기 = fs.readdirSync, 파일읽기 = fs.readFileSync, 오늘 = new Date() } = 옵션;
  let 목록;
  try { 목록 = 읽기(방); } catch { return null; }
  const 볼날 = new Set(요즘날들(오늘));
  const 것 = [];
  for (const f of 목록) {
    const 짝 = 날회차(String(f));
    if (!짝 || !볼날.has(짝.날)) continue;
    let 글 = '';
    try { 글 = String(파일읽기(path.join(방, String(f)), 'utf8')); } catch { continue; }
    const r = 자국읽기(글);
    /* ⛔ 접은 것은 여기 넣지 않는다 — 넣으면 영영 운다. 접은것() 이 따로 센다 */
    if (r.막혔나 && !r.보냈나 && !r.접었나) 것.push({ ...짝, ...r });
  }
  return 것.sort((a, b) => (a.날 + a.시).localeCompare(b.날 + b.시));
}

/**
 * 막혔다가 «사람이 접은» 기사를 찾는다.
 * ⚠ 이것은 「없던 일」이 아니다 — 보내지 못한 기사다. 세어서 눈에 보이게 둔다.
 */
export function 접은것(옵션 = {}) {
  const { 방 = 자국방, 읽기 = fs.readdirSync, 파일읽기 = fs.readFileSync, 오늘 = new Date() } = 옵션;
  let 목록;
  try { 목록 = 읽기(방); } catch { return null; }
  const 볼날 = new Set(요즘날들(오늘));
  const 것 = [];
  for (const f of 목록) {
    const 짝 = 날회차(String(f));
    if (!짝 || !볼날.has(짝.날)) continue;
    let 글 = '';
    try { 글 = String(파일읽기(path.join(방, String(f)), 'utf8')); } catch { continue; }
    const r = 자국읽기(글);
    if (r.막혔나 && !r.보냈나 && r.접었나) 것.push({ ...짝, ...r });
  }
  return 것.sort((a, b) => (a.날 + a.시).localeCompare(b.날 + b.시));
}

/* ── 자가시험 ─────────────────────────────────────────────── */
const 내가실행됐다 = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

if (내가실행됐다 && process.argv.includes('--자가시험')) {
  let 통 = 0; const 진 = [];
  const 본다 = (이름, 참) => { if (참) 통 += 1; else 진.push(이름); };

  본다('날·회차를 집는다', 날회차('2026-10-05_09시.txt')?.시 === '09');
  본다('⛔ 꼴이 다르면 null', 날회차('아무거나.txt') === null && 날회차(null) === null);

  const 막힌글 = '2026. 10. 5.\n[안보냄] [스포츠] 2026-10-05 09시 — 제목\n받는곳 (안 보냄)\n까닭 연합뉴스 사진이 없다\n';
  const r1 = 자국읽기(막힌글);
  본다('🔴 막힌 것을 가린다', r1.막혔나 === true && r1.보냈나 === false);
  본다('까닭을 집는다', r1.까닭.includes('사진'));
  /* 🔴 [2026-10-06 · 5번] 데스킹의 말을 자국에서 그대로 읽어 내는가 */
  본다('⬜ 옛 자국에는 데스킹말이 없다 — null 이지 \'\' 이 아니다',
    자국읽기(막힌글).데스킹말 === null);
  본다('🔴 데스킹말이 적혀 있으면 그대로 읽는다',
    자국읽기(막힌글 + '데스킹말 타 매체 인용 비중이 높아 미충족입니다\n').데스킹말
      === '타 매체 인용 비중이 높아 미충족입니다');
  본다('제목을 집는다', r1.제목.includes('제목'));
  /* 🔴 「받는곳 (안 보냄)」 때문에 보냄으로 잘못 읽으면 막힌 것을 통째로 놓친다 */
  본다('⛔ 「받는곳 (안 보냄)」을 보냄으로 읽지 않는다', r1.보냈나 === false);

  const 뒤에보낸글 = `${막힌글}\n[보냄] [스포츠] 2026-10-05 09시 — 제목\n`;
  본다('✅ 뒤에 보냈으면 막힌 것이 아니다', 자국읽기(뒤에보낸글).보냈나 === true);

  /* 🔴🔴 **보내는 쪽이 실제로 적는 꼴**이다 — `[보냄]` 머리가 «없다».
     이 자가 그 머리만 기다리다가, 다시 보낸 세 건을 계속 「버려졌다」고 울었다.
     ⛔ 자가 기다리는 꼴을 자가 지어내지 않는다. 보내는 쪽이 적는 것을 그대로 받는다. */
  const 진짜보낸글 = `${막힌글}\n2026. 10. 5. 오후 2:19:00\n`
    + '[스포츠] 2026-10-05 09시 — 카스트로 희생플라이, KIA 9회 역전승\n'
    + '받는곳 parkintaek2@gmail.com\n';
  본다('🔴🔴 진짜로 적히는 꼴(받는곳에 주소)을 보냄으로 읽는다', 자국읽기(진짜보낸글).보냈나 === true);
  본다('⛔ 받는곳이 「(안 보냄)」이면 그대로 막힌 것이다', 자국읽기(막힌글).보냈나 === false);

  본다('요즘 날이 사흘이다', 요즘날들(new Date(2026, 9, 5)).length === 3);
  본다('오늘이 맨 앞이다', 요즘날들(new Date(2026, 9, 5))[0] === '2026-10-05');
  본다('⛔ toISOString 을 안 쓴다 — 어제가 10-04 다', 요즘날들(new Date(2026, 9, 5))[1] === '2026-10-04');

  const 가짜 = {
    방: '/어디', 오늘: new Date(2026, 9, 5),
    읽기: () => ['2026-10-05_09시.txt', '2026-10-04_14시.txt', '2026-09-01_09시.txt', '아무거나.txt'],
    파일읽기: (p) => (String(p).includes('09-01') ? 막힌글 : 막힌글),
  };
  const 찾은것 = 막힌것(가짜);
  본다('🔴 요즘 것만 센다 — 9월 1일은 안 센다', 찾은것.length === 2);
  본다('날·회차 차례로 늘어놓는다', 찾은것[0].날 === '2026-10-04');
  본다('🔴 방을 못 읽으면 null — 빈 배열이 아니다',
    막힌것({ 읽기: () => { throw new Error('x'); } }) === null);

  /* 🔴 [2026-11-12 · 5번] 사람이 「접음」을 적으면 그것으로 끝난 것이다 */
  const 접은글 = `${막힌글}접음 2026-11-12 5번 — 경기가 이틀 지나 기사 가치가 없어졌다\n`;
  본다('🔴 접음 줄을 읽는다', 자국읽기(접은글).접었나 === true);
  본다('🔴 접은 까닭을 그대로 집는다',
    자국읽기(접은글).접은까닭 === '2026-11-12 5번 — 경기가 이틀 지나 기사 가치가 없어졌다');
  본다('⬜ 접음이 없으면 false 다 — null 로 뭉개지 않는다',
    자국읽기(막힌글).접었나 === false && 자국읽기(막힌글).접은까닭 === null);
  본다('🔴 접은 것은 「버려진 것」에서 뺀다',
    막힌것({ ...가짜, 파일읽기: () => 접은글 }).length === 0);
  본다('🔴 접은 것을 따로 센다 — 없던 일로 만들지 않는다',
    접은것({ ...가짜, 파일읽기: () => 접은글 }).length === 2);
  본다('⛔ 접음이 없으면 접은것 에 안 들어간다',
    접은것(가짜).length === 0);
  본다('🔴 접은것 도 방을 못 읽으면 null',
    접은것({ 읽기: () => { throw new Error('x'); } }) === null);
  /* ⛔ 자가 저 혼자 접으면 그것이 「막고 잊는 것」이다 — 적는 자리는 사람 손이어야 한다 */
  본다('⛔ 이 자는 「접음」을 적지 않는다 — 읽기만 한다',
    !new RegExp('append' + 'FileSync|write' + 'FileSync')
      .test(fs.readFileSync(fileURLToPath(import.meta.url), 'utf8')));

  console.log(진.length ? `🔴 ${진.length} 떨어졌다 —\n  ${진.join('\n  ')}` : `✅ 자가시험 ${통} 통과`);
  process.exit(진.length ? 1 : 0);
}

if (내가실행됐다) {
  const 것 = 막힌것();
  if (것 === null) {
    console.log('⬜ 자국방을 못 읽었다 — 0 으로 읽지 않는다');
    process.exit(0);
  }
  /* ⚠ 접은 것은 «없던 일»이 아니다 — 보내지 못한 기사다. 늘 함께 적는다 */
  const 접힌것 = 접은것() ?? [];
  const 접힌말 = 접힌것.length ? ` · 사람이 접은 것 ${접힌것.length}건(보내지 못한 기사다)` : '';
  if (!것.length) {
    console.log(`✅ 막힌 채 버려진 기사가 없다 (최근 ${볼날수}일)${접힌말}`);
    for (const x of 접힌것) console.log(`     ⬜ ${x.날} ${x.시}시  접음 ${x.접은까닭}`);
    process.exit(0);
  }
  console.log(`🔴 데스킹에 막힌 뒤 «그대로 버려진» 기사 ${것.length}건 (최근 ${볼날수}일) —`);
  for (const x of 것) {
    console.log(`     ${x.날} ${x.시}시  ${x.까닭}\n       ${x.제목.slice(0, 70)}`);
    /* ⛔ 세 칸으로 센다 — 적혀 있다 / 안 적혀 있다 / 집었는데 비었다 */
    if (x.데스킹말) console.log(`       데스킹말 ${x.데스킹말.slice(0, 120)}`);
    else console.log('       ⬜ 데스킹말이 자국에 없다 — 옛 자국이거나 못 집었다');
  }
  console.log('\n   ⛔ 막는 것은 옳다. **막고 잊는 것**이 흠이다 — 사장님은 그 기사를 못 받으셨다.');
  console.log('   ⭐ 까닭이 늘 같으면 «회차 지침»을 고친다 — 거두는 자가 아니라 쓰는 자를 고쳐야 끝난다.');
  console.log('     사진이 없어 막히면 회차에 「연합뉴스 사진이 있는 경기만 쓴다」를 넣는다.');
  process.exit(1);
}
