#!/usr/bin/env node
// jb-s2-xlsx.mjs — schedule 2 (2026-11-28): write the 105 target rows to one Excel sheet from the verification file.
import fs from 'node:fs';
import { 통만든다, 적는다 } from './lib/xlsx-쓴다.mjs';
import { 잰다 } from './lib/xlsx-읽어본다.mjs';

const 줄들 = JSON.parse(fs.readFileSync('docs/자국/중부매일-일정2-검수-20261128.json', 'utf8'));
const 분류 = (s) => (s ? [s.섹션1글, s.섹션2글, s.연재글 === '연재' ? '' : s.연재글].filter(Boolean).join(' > ') : '');
const 문화칼럼인가 = (s) => s && s.섹션1 === 'S1N7' && s.섹션2 === 'S2N149' && s.연재 === 'SRN552';

const 통 = 통만든다();
const s = 통.새장('일정2 목록');
s.너비([11, 12, 56, 30, 34, 40, 24, 24, 8, 18, 18, 58]);
s.틀고정('C2');
s.줄(['기사번호', '구분', '제목', '작업 전 분류', '지금 분류', '결과', '기자명', '기자메일', '승인', '작업 전 노출시간', '지금 노출시간', '기사 주소'].map((v) => ({ v, 꼴: '머리' })));
const 셈 = {};
for (const r of 줄들) {
  const 전 = r.전; const 뒤 = r.뒤;
  const 시각달라짐 = 전.노출날 + ' ' + 전.노출시각 !== 뒤.노출날 + ' ' + 뒤.노출시각;
  const 결과 = !문화칼럼인가(뒤) ? '변경하지 않음 (작업 중단)' : (시각달라짐 ? '변경 완료 · 노출시각이 2분 달라짐' : '변경 완료');
  셈[결과] = (셈[결과] || 0) + 1;
  const 빨강 = 시각달라짐 ? '빨강글' : '글왼쪽';
  s.줄([
    { v: Number(r.번호), 꼴: '수' }, { v: r.갈래, 꼴: '글' }, { v: 뒤.제목, 꼴: '글왼쪽' },
    { v: 분류(전), 꼴: '글왼쪽' }, { v: 분류(뒤), 꼴: '글왼쪽' }, { v: 결과, 꼴: 빨강 },
    { v: 뒤.기자명, 꼴: '글' }, { v: 뒤.기자메일, 꼴: '글왼쪽' }, { v: 뒤.승인 ? '승인' : '미승인', 꼴: '글' },
    { v: 전.노출날 + ' ' + 전.노출시각, 꼴: '글' }, { v: 뒤.노출날 + ' ' + 뒤.노출시각, 꼴: 시각달라짐 ? '빨강글' : '글' },
    { v: 'https://www.jbnews.com/news/articleView.html?idxno=' + r.번호, 꼴: '글왼쪽' },
  ]);
}
s.빈줄();
s.줄([{ v: '출처: 중부매일 CMS 기사 수정 화면 — 2026-11-28 06시대에 작업 전과 작업 뒤 두 번 읽었습니다.', 꼴: '주석' }]);
s.줄([{ v: '대상: 김성식 기자 2026.1.1~8.31 제목에 [창간 35주년 특별기획]·[창간 36주년 특별기획]이 있는 29건, 조혁연 기자 2026.1.1~9.2 기사 76건.', 꼴: '주석' }]);
s.줄([{ v: '기자 이름·제목·본문·사진은 바꾸지 않았습니다. 웹출판은 누르지 않았습니다.', 꼴: '주석' }]);
s.줄([{ v: '2건은 저장 직후 노출시각이 2분 앞당겨졌습니다(빨간 글씨). 원인을 확인하지 못해 나머지 78건은 바꾸지 않고 멈췄습니다.', 꼴: '빨강주석' }]);

const 낼곳 = 'docs/보고/중부매일-일정2-목록-20261128.xlsx';
적는다(통, 낼곳);
const { 탈 } = 잰다(낼곳);
if (탈.length) { for (const t of 탈) console.error('BAD ' + t); process.exit(1); }
console.log('wrote ' + 낼곳 + ' · ' + 줄들.length + ' rows · ' + JSON.stringify(셈));
