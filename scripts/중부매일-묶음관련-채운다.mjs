/** 이 PC 는 이미 KST 다. ⛔ toISO…() 로 돌리지 않는다 — 날이 하루 밀린다 */
export function 오늘글(이제 = new Date()) {
  return 이제.getFullYear() + '-'
    + String(이제.getMonth() + 1).padStart(2, '0') + '-'
    + String(이제.getDate()).padStart(2, '0');
}

/**
 * 자국을 날짜 → 기사번호로 읽는다.
 * ⛔ 「됐다」가 아닌 줄은 세지 않는다. 같은 날이 여러 줄이면 **마지막 줄**이 산다.
 */
export function 자국읽기(글) {
  const 표 = new Map();
  for (const 줄 of String(글 || '').split(/\r?\n/)) {
    if (!줄 || 줄.startsWith('#')) continue;
    const 칸 = 줄.split('\t');
    const 날 = (칸[0] || '').trim();
    if (!/^\d{4}-\d{2}-\d{2}$/.test(날)) continue;
    if ((칸[3] || '').trim() !== '됐다') continue;
    const 번호 = (String(칸[5] || '').split('idxno=')[1] || '').trim();
    if (!/^\d+$/.test(번호)) continue;
    표.set(날, 번호);
  }
  return 표;
}

/** 저장소에서 두 자국을 다 읽는다 */
export function 자국모두(뿌리 = 뿌리길) {
  const 모음 = {};
  for (const 종류 of 종류들) {
    const 길 = path.join(뿌리, 기록파일[종류]);
    모음[종류] = fs.existsSync(길) ? 자국읽기(fs.readFileSync(길, 'utf8')) : new Map();
  }
  return 모음;
}

/**
 * 🔴 그 기사가 **바라는** 묶음·관련 번호를 낸다.
 * @param {string} 날       기사 날짜
 * @param {string} 내종류   '띠별' | '별자리'
 * @param {string} 갈래     '묶음' | '관련'
 * @param {object} 자국     { 띠별: Map, 별자리: Map }
 * @param {string} 오늘     오늘 날짜 — ⛔ 아직 안 나간 기사는 창에 안 뜬다. 빼고 센다
 * @param {number} 몇건
 */
export function 바라는번호(날, 내종류, 갈래, 자국, 오늘, 몇건 = 1) {
  const 원하는종류 = 고를종류(내종류, 갈래);
  const 창 = 고를날들(날, 갈래);
  if (!원하는종류 || !창.length) return { 번호들: [], 아직: [] };
  const 표 = 자국?.[원하는종류] || new Map();
  const 번호들 = [];
  const 아직 = [];
  for (const 그날 of 창) {
    if (번호들.length >= 몇건) break;
    if (오늘 && 그날 > 오늘) { 아직.push(그날); continue; }   /* 아직 안 나갔다 */
    const 번호 = 표.get(그날);
    if (번호) 번호들.push(번호); else 아직.push(그날);
  }
  return { 번호들, 아직 };
}

/** 넣을 것과 뺄 것을 가른다. ⛔ 이미 맞는 줄은 건드리지 않는다 */
export function 무엇을할까(지금, 바람) {
  const 있는것 = (지금 || []).map((r) => String(r.번호));
  const 바라는것 = (바람 || []).map(String);
  return {
    뺄것: 있는것.filter((n) => !바라는것.includes(n)),
    넣을것: 바라는것.filter((n) => !있는것.includes(n)),
    그대로: 있는것.filter((n) => 바라는것.includes(n)),
  };
}

const 쉰다 = (밀리) => new Promise((끝) => setTimeout(끝, 밀리));

/** 기사 한 건의 한 갈래를 맞춘다 */
async function 한갈래정리(붙음, 설정) {
  const { 갈래, 내종류, 기사번호, 내날, 바람 } = 설정;
  const 표 = 갈래표[갈래];

  let 지금 = null;
  try { 지금 = JSON.parse(String(await 재기(붙음, 지금것글(표.서식칸), 20000))); } catch { 지금 = null; }
  /* 🔴 못 읽은 것을 「비었다」로 읽지 않는다 */
  if (지금 === null) return 갈래 + ' 🔴 지금 든 것을 못 읽었다 — 손대지 않는다';

  const 할일 = 무엇을할까(지금, 바람);
  const 말 = [갈래 + ' ' + 지금.length + '건'];

  if (할일.뺄것.length) {
    let 뺌 = { 누른것: [], 못찾음: [] };
    try { 뺌 = JSON.parse(String(await 재기(붙음, 지우기글(표.서식칸, 표.지움단추, 할일.뺄것), 25000))); }
    catch { /* 아래 되읽기에서 드러난다 */ }
    await 쉰다(2500);
    말.push('뺐다 ' + (뺌.누른것 || []).join(',') + ((뺌.못찾음 || []).length ? ' · 못 찾음 ' + 뺌.못찾음.join(',') : ''));
  }

  if (할일.넣을것.length) {
    말.push('넣기 ' + (await 한갈래넣기(붙음, {
      갈래, 내종류, 기사번호, 내날, 번호들: 할일.넣을것,
    })));
  }

  if (!할일.뺄것.length && !할일.넣을것.length) 말.push('이미 맞다');

  /* 🔴 「눌렀다」를 「됐다」로 읽지 않는다 — 서식에서 되읽는다 */
  let 뒤 = null;
  try { 뒤 = JSON.parse(String(await 재기(붙음, 지금것글(표.서식칸), 20000))); } catch { 뒤 = null; }
  const 뒤번호 = (뒤 || []).map((r) => String(r.번호));
  const 바람글 = (바람 || []).map(String);
  const 맞나 = 뒤 !== null && 뒤번호.length === 바람글.length
    && 뒤번호.every((n) => 바람글.includes(n));
  말.push((맞나 ? '✔' : '🔴') + ' 지금 [' + 뒤번호.join(',') + '] / 바람 [' + 바람글.join(',') + ']');
  return 말.join(' · ');
}

/** 기사 한 건을 맞춘다 */
export async function 한건정리(설정) {
  /* 🔴 [2026-11-20] 사장님 — 관련은 같은 날 반대 종류 «하나»다. 2건이 아니다 */
  const { 기사번호, 내종류, 내날, 자국, 오늘, 몇건 = 1 } = 설정;
  const 줄 = [];
  await 새탭에서(서식주소(기사번호), async (붙음) => {
    await 자리잡기(붙음, { 최대: 45000 });
    await 쉰다(4000);
    const 제목 = String(await 재기(붙음, '(document.querySelector("[name=title]")||{}).value || ""', 15000));
    줄.push('■ ' + 기사번호 + ' — ' + 제목);
    for (const 갈래 of ['묶음', '관련']) {
      const { 번호들, 아직 } = 바라는번호(내날, 내종류, 갈래, 자국, 오늘, 몇건);
      const 결과 = await 한갈래정리(붙음, { 갈래, 내종류, 기사번호, 내날, 바람: 번호들 });
      줄.push('   ' + 결과 + (아직.length ? ' · 아직 안 나간 날 ' + 아직.join(',') : ''));
      await 쉰다(2000);
    }
  });
  return 줄.join('\n');
}

