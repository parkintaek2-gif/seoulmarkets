/**
 * 🔴🔴 [2026-11-05 · 사장님] 「**이메일에 건방지게 반말을 써**」
 * ─────────────────────────────────────────────────────────────────────
 * 이 자에는 **반말 규칙이 아예 없었다.** 낱말만 봤다(「지면」·「유입」 같은).
 * 그래서 「침입 시도를 **끊었다**」라는 제목의 메일이 사장님께 그대로 갔다.
 *
 * ⚠ `klifemap/scripts/check-나가는글은-존댓말인가.mjs` 와 **같은 규칙이다.**
 *   저장소가 달라 두 벌이다. 한쪽을 고치면 다른 쪽도 따라가야 한다.
 *
 * ⛔ 「> 」로 시작하는 줄은 봐준다 — 사장님 말씀 원문이고 우리가 고칠 수 없다.
 */
export function 평어인가(글) {
  const s = String(글 ?? '').trim();
  if (!s) return false;
  /* 평어가 가운데 있고 끝이 숫자인 제목을 놓치지 않는다 —
     「[보안] 침입 시도를 끊었다 — 3건」이 그 자리였다. 토막마다 끝을 본다. */
  for (const 토막 of s.split(/[—–·|•]+|\s+-\s+/)) {
    const 끝 = String(토막).trim().replace(/[\s.!?…)\]」』"'*_~]+$/u, '');
    if (!끝) continue;
    if (/(니다|니까|세요|셔요|십시오|시오|주세요)$/.test(끝)) continue;
    if (/[가-힣]다$/.test(끝)) return true;
    if (/(아라|어라|여라|러라|거라|너라|해라|하라|으라)$/.test(끝)) return true;
    if (/(^|\s)(해|봐|줘|놔|둬|가자|하자|보자)$/.test(끝)) return true;
    if (/(확인|점검|사용|시작|완료|실행|신청|결제|가입|탈퇴|수정|삭제|등록|조회|연락|문의)해$/.test(끝)) return true;
  }
  return false;
}

/** 글에서 평어 줄을 찾는다. ⛔ 인용(> )은 봐준다 */
export function 평어줄찾기(글) {
  if (typeof 글 !== 'string') return [];
  const 것 = [];
  const 줄들 = 글.split(/\r?\n/);
  for (let i = 0; i < 줄들.length; i += 1) {
    const 줄 = 줄들[i];
    if (/^\s*>/.test(줄)) continue;
    /* 표의 칸·목록 표시는 떼고 본다 */
    const 맨줄 = 줄.replace(/^[\s|>*\-#\d.]+/, '').replace(/\|$/, '').trim();
    if (평어인가(맨줄)) 것.push({ 줄번호: i + 1, 줄: 맨줄.slice(0, 70) });
  }
  return 것;
}

/** 글에서 걸린 말을 찾는다. ⛔ 못 읽으면 null — 「없다」가 아니다 */
export function 걸린말찾기(글, 목록 = 바꿀말) {
  if (typeof 글 !== 'string') return null;
  const 것 = [];
  const 줄들 = 글.split(/\r?\n/);
  for (let i = 0; i < 줄들.length; i += 1) {
    /* 🔴 [2026-10-11 · 5번] **인용문은 봐준다** — 사장님 말씀을 «원문 그대로» 옮긴 줄이다.
       사장님 지시에 「검색유입, ai 유입은…」처럼 그 말이 들어 있으면 우리가 고칠 수 없다.
       (회사 규칙 — 「사장님 말씀이 새로 나오면 원문 그대로 더한다. 요약해서 넣지 않는다」)
       ⚠ 다만 봐주는 것은 «> 로 시작하는 줄»뿐이다. 「」 안에 넣는 것만으로는 안 봐준다 —
          그렇게 봐주면 아무 말이나 따옴표에 넣어 자를 끌 수 있다.
       ⛔ check-마감은-ASAP 도 같은 길을 쓴다. 두 자가 같은 규칙이어야 헷갈리지 않는다. */
    if (/^s*>/.test(줄들[i])) continue;
    for (const w of 목록 ?? []) {
      if (줄들[i].includes(w.쓴다)) {
        것.push({ 줄번호: i + 1, 쓴다: w.쓴다, 대신: w.대신, 까닭: w.까닭, 줄: 줄들[i].trim().slice(0, 70) });
      }
    }
  }
  return 것;
}

