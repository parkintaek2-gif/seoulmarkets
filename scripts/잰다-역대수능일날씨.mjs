/** Date → 'YYYY-MM-DD' ⛔ toISOString() 금지 — 이 PC 가 KST 다 */
export function 날글(d = new Date()) {
  return d.getFullYear() + '-'
    + String(d.getMonth() + 1).padStart(2, '0') + '-'
    + String(d.getDate()).padStart(2, '0');
}

/** 그 날이 수능일인가 — 날은 'YYYY-MM-DD' */
export function 수능일인가(날) {
  return 수능일표.some((x) => x.날 === String(날));
}

/** 오늘보다 «앞선» 수능일을 최근 것부터 n개 — ⛔ 앞날은 넣지 않는다(관측값이 없다) */
export function 지난수능일들(오늘 = new Date(), 몇해 = 3) {
  const 오늘글 = 날글(오늘);
  return 수능일표
    .filter((x) => x.날 < 오늘글)
    .sort((a, b) => (a.날 < b.날 ? 1 : -1))
    .slice(0, Math.max(1, Math.min(10, 몇해)));
}

/** 숫자 칸 하나 — ⛔ 빈 칸·'-' 는 null 이다. 0 으로 읽지 않는다 */
export function 숫자(v) {
  if (v === null || v === undefined) return null;
  const s = String(v).trim();
  if (s === '' || s === '-') return null;
  const n = Number(s);
  return Number.isFinite(n) ? n : null;
}

/** 쪽지에서 고르개가 «고른 값»의 글자를 뽑는다 — 되읽어 맞춰 보는 데 쓴다 */
export function 고른값(쪽지, 이름) {
  const t = String(쪽지 ?? '');
  const i = t.indexOf('id="select-' + 이름 + '"');
  if (i < 0) return null;
  const 토막 = t.slice(i);
  const 끝 = 토막.indexOf('</select>');
  if (끝 < 0) return null;
  const m = 토막.slice(0, 끝).match(/<option[^>]*selected[^>]*>([^<]*)</);
  return m ? m[1].trim() : null;
}

/**
 * 🔴 달라고 한 것이 왔나. ⛔ 200 을 「맞게 왔다」로 읽지 않는다.
 *   지점 이름은 「청주(유)」처럼 꼬리가 붙어 오므로 «들었나»로 본다.
 */
export function 제대로왔나(쪽지, 지점이름, 해, 달) {
  const s = 고른값(쪽지, 'stn');
  const y = 고른값(쪽지, 'yy');
  const m = 고른값(쪽지, 'mm');
  if (!s || !y || !m) return false;
  return s.includes(지점이름) && y === String(해) + '년' && m === String(Number(달)) + '월';
}

/** 칸 글자 하나 → 그 날의 값 (예: '평균기온:12.5℃ 최고기온:15.6℃ …') */
export function 칸읽기(글) {
  const t = String(글 ?? '').replace(/\s+/g, ' ');
  const 집기 = (이름) => {
    const m = t.match(new RegExp(이름 + '\\s*:\\s*(-?[\\d.]+|-)'));
    return m ? 숫자(m[1]) : null;
  };
  const 최저 = 집기('최저기온');
  const 최고 = 집기('최고기온');
  if (최저 === null && 최고 === null) return null;
  const 비 = 집기('일강수량');
  return {
    최저,
    최고,
    평균: 집기('평균기온'),
    구름: 집기('평균운량'),
    비,                                    /* null 이면 「비가 안 왔다」 */
    비왔나: 비 !== null && 비 > 0,
  };
}

/**
 * 달력 표에서 «그 날짜» 칸을 집는다.
 * ⚠ 표는 「날짜 줄 → 값 줄」이 짝으로 이어진다. 빈 칸(지난달 자리)이 섞인다.
 */
export function 달표에서하루(쪽지, 날짜) {
  const t = String(쪽지 ?? '');
  const 표 = (t.match(/<table[^>]*class="[^"]*table-cal[^"]*"[\s\S]*?<\/table>/) || [''])[0];
  if (!표) return null;
  const 줄들 = [...표.matchAll(/<tr[\s\S]*?<\/tr>/g)].map((m) =>
    [...m[0].matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/g)].map((c) =>
      c[1].replace(/<[^>]*>/g, ' ').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim()));
  const 찾는글 = String(Number(날짜)) + '일';
  for (let i = 0; i < 줄들.length - 1; i += 1) {
    const 칸 = 줄들[i].findIndex((x) => x === 찾는글);
    if (칸 < 0) continue;
    const 값줄 = 줄들[i + 1];
    if (!값줄 || 값줄[칸] === undefined) continue;
    const 값 = 칸읽기(값줄[칸]);
    if (값) return 값;
  }
  return null;
}

/** 한 지점 하루치를 받는다 — ⛔ 막히거나 «딴 것»이 오면 null */
export async function 받는다(지점, 지점이름, 날) {
  const m = String(날 ?? '').match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!m) return null;
  const [, 해, 달, 일] = m;
  const 주소 = 가는곳 + '?stn=' + 지점 + '&yy=' + 해 + '&mm=' + Number(달) + '&obs=1';
  try {
    const r = await fetch(주소, {
      headers: { 'User-Agent': 'Mozilla/5.0' },
      signal: AbortSignal.timeout(25000),
    });
    if (!r.ok) return null;
    const 쪽지 = await r.text();
    /* 🔴 여기가 핵심이다 — 달라고 한 지점·해·달이 맞게 왔는지 되읽는다 */
    if (!제대로왔나(쪽지, 지점이름, 해, 달)) return null;
    return 달표에서하루(쪽지, 일);
  } catch (e) { return null; }
}

/** 한 도시 한 줄 — '청주 아침 최저 2.4도 · 낮 최고 13.1도 · 비 안 옴' */
export function 한줄(이름, 값) {
  if (!값) return null;
  const 조각 = [];
  if (값.최저 !== null) 조각.push('아침 최저 ' + 값.최저.toFixed(1) + '도');
  if (값.최고 !== null) 조각.push('낮 최고 ' + 값.최고.toFixed(1) + '도');
  if (!조각.length) return null;
  조각.push(값.비왔나 ? '강수 ' + 값.비.toFixed(1) + 'mm' : '비 안 옴');
  return 이름 + ' ' + 조각.join(' · ');
}

/** '2025-11-13' → '2025년 11월 13일' */
export function 한글날(날) {
  const m = String(날 ?? '').match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!m) return String(날 ?? '');
  return Number(m[1]) + '년 ' + Number(m[2]) + '월 ' + Number(m[3]) + '일';
}

/** 해의 수를 한국어로 — ⛔ 「2해」는 한국어가 아니다. 기사에 그대로 실렸다(아래 참조) */
export function 해세기(n) {
  const 이름 = ['영', '한', '두', '세', '네', '다섯', '여섯', '일곱', '여덟', '아홉', '열'];
  const i = Number(n);
  return Number.isInteger(i) && i >= 0 && i <= 10 ? 이름[i] + ' 해' : String(n) + '해';
}

/**
 * 세 해를 견주는 한 줄 — 청주 아침 최저만.
 * ⛔ 평균을 내어 「보통 이렇다」로 읽히게 쓰지 않는다. 매년 몇 도였는지 그대로 적는다.
 *
 * 🔴🔴 [2026-11-18 데스킹 · 5번] **이 한 줄이 기사에 틀린 사실을 넣었다.**
 * 처음에는 비 온 해를 «다섯 도시 아무 곳이나»로 셌다. 그런데 이 문장은 앞에서
 * 청주 기온만 말하고 있어서, 받는 쪽이 그대로 「청주 … 세 해 가운데 비가 온 날은
 * 2해였다」로 썼다. **청주에 비가 온 수능일은 한 해(2023년)뿐이다.**
 *   2025년 수능일 청주 비 안 옴 · 2024년 수능일 청주 비 안 옴 · 2023년 7.9mm
 * ⇒ 한 문장 안에서 **기준 도시를 바꾸지 않는다.** 청주를 말했으면 끝까지 청주다.
 * ⛔ 그리고 「2해」로 적지 않는다 — 한국어가 아니다. 그대로 기사에 실렸다.
 */
export function 요약한줄(쓸것) {
  const 수 = [];
  let 청주비온해 = 0;
  for (const h of 쓸것) {
    const 줄 = (h.줄들 ?? []).find((x) => x.startsWith('청주 '));
    if (!줄) continue;
    const m = 줄.match(/아침 최저 (-?[\d.]+)도/);
    if (m) 수.push({ 해: h.학년도, 값: Number(m[1]) });
    if (/강수 /.test(줄)) 청주비온해 += 1;
  }
  if (수.length < 2) return null;
  return '청주 아침 최저기온은 ' + 수.map((x) => x.해 + '학년도 ' + x.값.toFixed(1) + '도').join(', ')
    + '였다. ' + 해세기(쓸것.length) + ' 가운데 «청주에» 비가 온 수능일은 '
    + 해세기(청주비온해) + '다.';
}

/**
 * 받은 것을 기사에 넣을 사실 묶음으로.
 * ⛔ 꼭있어야할곳(청주·대전)이 없는 해는 뺀다. 한 해도 안 남으면 null — 덧말을 안 붙인다.
 */
export function 묶는다(해들) {
  const 쓸것 = (해들 ?? []).filter((h) => h && h.줄들 && h.줄들.length
    && 꼭있어야할곳.every((이) => h.줄들.some((x) => x.startsWith(이 + ' '))));
  if (!쓸것.length) return null;
  const 밖 = ['■ 지난 수능일 충청권 «실제» 날씨 (기상청 날씨누리 과거관측 일별자료)'];
  for (const h of 쓸것) {
    밖.push('');
    밖.push(h.학년도 + '학년도 수능 ' + 한글날(h.날) + ' — ' + h.줄들.join(' / '));
  }
  const 요약 = 요약한줄(쓸것);
  if (요약) { 밖.push(''); 밖.push(요약); }
  return 밖.join('\n');
}

