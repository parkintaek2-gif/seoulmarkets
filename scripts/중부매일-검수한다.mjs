/** 운세 — 노출날이 제목의 월·일과 맞고, 해가 앞으로 오고, 띠별 00:05 / 별자리 00:30, 승인 */
export function 운세재기(값, 오늘 = new Date()) {
  const 탈 = [];
  const d = 제목에서날짜(값.제목);
  if (!d) { 탈.push('제목에서 날짜를 못 집었다'); return 탈; }
  const m = String(값.노출날 || '').match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!m) { 탈.push('노출날 형식이 아니다 [' + 값.노출날 + ']'); return 탈; }
  if (Number(m[2]) !== d.월 || Number(m[3]) !== d.일) {
    탈.push('노출날이 제목과 다르다 — 제목 ' + d.월 + '월 ' + d.일 + '일 · 노출 ' + 값.노출날);
  }
  const 날 = new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]));
  const 오늘자 = new Date(오늘.getFullYear(), 오늘.getMonth(), 오늘.getDate());
  if (날.getTime() <= 오늘자.getTime()) 탈.push('🔴 노출날이 지났다 ' + 값.노출날 + ' — 바로 나간다');
  const 바랄시각 = 갈래집기(값.제목) === '별자리' ? '00:30' : '00:05';
  if (String(값.노출시각).slice(0, 5) !== 바랄시각) 탈.push('노출시각이 ' + 값.노출시각 + ' (바란 것 ' + 바랄시각 + ')');
  if (!값.승인) 탈.push('🔴 미승인이다');
  return 탈;
}

/**
 * 스포츠 — 아이디·이름·메일 **셋 다** 이지효여야 한다.
 * 🔴 user_id 를 재는 까닭 — 공개된 기사의 「기자 프로필 보기」 링크가
 *   `/news/articleList.html?sc_area=I&sc_word=<user_id>` 다.
 *   이름만 바꾸면 라이브에서 박인택 계정을 가리킨 채로 남는다(2026-11-25 실측).
 */
export function 스포츠재기(값) {
  const 탈 = [];
  if (값.기자id !== 이지효.id) 탈.push('🔴 user_id 가 [' + 값.기자id + '] — 라이브 프로필 링크가 어긋난다');
  if (값.기자명 !== 이지효.이름) 탈.push('기자명이 [' + 값.기자명 + ']');
  if (값.기자메일 !== 이지효.메일) 탈.push('기자메일이 [' + 값.기자메일 + ']');
  if (!값.승인) 탈.push('🔴 미승인이다');
  return 탈;
}

/** 분류 — 오피니언 > 외부칼럼 > (시민기자칼럼 | 문화칼럼) */
export function 분류재기(값, 바랄연재) {
  const 탈 = [];
  if (값.섹션1 !== 오피니언) 탈.push('1차가 [' + 값.섹션1글 + ' ' + 값.섹션1 + ']');
  if (값.섹션2 !== 외부칼럼) 탈.push('2차가 [' + 값.섹션2글 + ' ' + 값.섹션2 + ']');
  if (값.연재 !== 바랄연재) 탈.push('연재가 [' + 값.연재글 + ' ' + 값.연재 + ']');
  if (!값.승인) 탈.push('🔴 미승인이다');
  return 탈;
}

