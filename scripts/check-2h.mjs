export function 메일로보냈나(글, 날짜, 찾는말) {
  if (typeof 글 !== 'string' || !찾는말) return null;
  const 줄 = 글.split(/\r?\n/).find((x) => {
    if (!x.startsWith(날짜)) return false;
    const 뒤 = x[날짜.length];
    if (뒤 !== '\t' && 뒤 !== ' ') return false;
    return x.includes(찾는말);
  });
  if (!줄) return null;
  const 시각 = (줄.match(/\d{2}:\d{2}/) || [null])[0];
  return { 시각, 줄 };
}

