/**
 * 🔴🔴 [2026-10-06 08:3x · 5번] **자물쇠가 1번 커밋을 내 몫으로 잡았다.**
 *
 * 첫 판에서는 «검수 요청 커밋 자신»을 잡았고, 이번엔 «남의 유닛 커밋»을 잡았다.
 * 두 번 다 거짓 빨강이다. 거짓으로 우는 자물쇠는 결국 꺼진다.
 *
 * ⚠ 뿌리 — **모든 유닛이 같은 git 이름으로 커밋한다**(parkintaek2-gif).
 *   그래서 «지은이»로는 누구 것인지 가릴 수 없다. 가릴 수 없는 것을 가린 척하면 안 된다.
 * ⇒ 커밋 글 앞머리의 유닛 표시로 가른다. 그리고 **앞머리가 없으면 「모른다」**로 둔다.
 *   오늘 배운 그대로다 — 세는 칸을 둘로 두면 반드시 한쪽으로 거짓이 난다. 칸을 셋으로 둔다.
 *
 * @returns '내것' | '남의것' | '모른다'
 */
export function 누구것인가(커밋글) {
  const s = String(커밋글 ?? '').trim();
  if (/^\[?\s*5번/.test(s)) return '내것';
  if (/^\[?\s*[1234678]번/.test(s)) return '남의것';
  return '모른다';
}

/**
 * 자가 스스로 다는 커밋 — 사람이 한 일이 아니다.
 * ⛔ 이것을 검수에 올리라고 하면 자물쇠가 날마다 헛울린다.
 */
export const 자가다는것 = ['배포 도장', '매시 소통', '매시소통', '자물쇠 해제', '자동생성'];
export function 자가단것인가(커밋글) {
  const s = String(커밋글 ?? '');
  return 자가다는것.some((w) => s.includes(w));
}

/** 검수 요청 글을 찾는 표시 — 세션간 메모의 제목 꼴 */
export const 요청표시 = /^## \[5번 → .*\].*검수 요청/m;

/** 커밋 한 줄이 검색 일인가. ⛔ 눈으로 가르지 않는다 — 낱말로 가른다 */
export function 검색일인가(커밋글, 낱말 = 검색낱말) {
  const s = String(커밋글 ?? '');
  return 낱말.some((w) => s.includes(w));
}

/**
 * 마지막 검수 요청이 올라간 뒤의 검색 커밋들.
 * @param 커밋들 [{해시, 때, 글}] — 새것이 앞
 * @param 요청때 Date 또는 null (한 번도 안 걸었으면 null)
 */
/**
 * 🔴 [2026-10-06 07:5x · 5번] **자물쇠가 첫 판에 거짓으로 울었다.**
 *   「검수 요청」 커밋 «자신»을 「검수에 안 올린 검색 커밋」으로 잡았다 —
 *   그 커밋 글에 「검색」이 들었고, 커밋 시각(07:57)이 메모 머리 시각(07:50)보다 뒤이기 때문이다.
 * ⛔ 거짓으로 우는 자물쇠는 결국 꺼진다. 오늘만 세 번째로 겪는 자리다.
 */
export const 요청커밋표시 = '검수 요청';

/**
 * 밀린 것을 **셋으로 갈라** 돌려준다.
 * @returns { 내것: [], 모른다: [] }  — 남의 유닛 것은 아예 안 담는다
 */
export function 검수안건것(커밋들, 요청때) {
  const 걸린다 = (c) => {
    if (String(c.글 ?? '').includes(요청커밋표시)) return false;   /* 거는 커밋 자신 */
    if (자가단것인가(c.글)) return false;                          /* 자가 단 것 */
    if (!검색일인가(c.글)) return false;
    if (!요청때) return true;
    return c.때 > 요청때;
  };
  const 내것 = []; const 모른다 = [];
  for (const c of 커밋들 || []) {
    if (!걸린다(c)) continue;
    const 누구 = 누구것인가(c.글);
    if (누구 === '내것') 내것.push(c);
    else if (누구 === '모른다') 모른다.push(c);
    /* ⛔ '남의것'은 담지 않는다 — 남의 일을 내 밀린 일로 세지 않는다 */
  }
  return { 내것, 모른다 };
}

/** 세션간 메모에서 마지막 검수 요청 시각. ⛔ 못 읽으면 null — 「없다」가 아니다 */
export function 마지막요청때(글) {
  if (글 == null) return null;
  const 것 = [...String(글).matchAll(/^## \[5번 → [^\]]*\]\s*(\d{4}-\d{2}-\d{2})\s+(\d{2}:\d{2}).*검수 요청/gm)];
  if (!것.length) return { 없다: true };
  const m = 것[것.length - 1];
  return { 때: new Date(`${m[1]}T${m[2]}:00+09:00`) };   /* ⛔ 이 PC 는 KST 다 */
}

function 커밋읽기(몇 = 60) {
  try {
    const 글 = execFileSync('git', ['log', `-${몇}`, '--format=%h\u0001%cI\u0001%s'],
      { cwd: 뿌리, encoding: 'utf8' });
    return 글.split(/\r?\n/).filter(Boolean).map((줄) => {
      const [해시, 때, ...나머지] = 줄.split('\u0001');
      return { 해시, 때: new Date(때), 글: 나머지.join('\u0001') };
    });
  } catch { return null; }                 /* ⚠ git 을 못 읽으면 null — 0건이 아니다 */
}

