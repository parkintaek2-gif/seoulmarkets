#!/usr/bin/env node
/**
 * 채널번호-페이지만들기.mjs — `src/data/kcw-tv-channels.json` 을 읽어
 * 케이리뷰 「채널번호·편성표」 페이지를 만든다.
 *
 * ── 🔴🔴 사장님 지시 (2026-11-10, 원문) ───────────────────────────────
 * 「쇼 > 채널번호-편성표 > 드라마 순으로 콘텐트를 만들어」
 * 「내가 준대로 그대로 써. 표는 해당부분에 추가하고. 왜 네 맘대로 순서를 바꾸나」
 * 「확인 안됐다는 내용은 어떤 콘텐트에도 들어가면 안됨. 이게 기본이야」
 *
 * ⇒ 사장님이 주신 문장과 차례는 `본문` 에 그대로 두고, 표만 그 자리에 끼운다.
 * ⇒ 값이 빈 칸은 **그 줄을 빼고** 낸다. 빈칸이나 「확인 안 됨」을 화면에 내지 않는다.
 *
 * 돌리는 법
 *   node scripts/채널번호-페이지만들기.mjs            페이지를 다시 만든다
 *   node scripts/채널번호-페이지만들기.mjs --자체검사   스스로 검사만 한다
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 여기 = path.dirname(fileURLToPath(import.meta.url));
const 뿌리 = path.join(여기, '..');
const 자료자리 = path.join(뿌리, 'src', 'data', 'kcw-tv-channels.json');
const 낼자리 = path.join(뿌리, 'content', 'kcw-reviews');

/* ── 사업자 표기 ──────────────────────────────────────────────────── */

/**
 * 자료에는 사업자 이름이 한글로 풀려 적혀 있다. 손님이 찾는 것은 상표다 —
 * 「에스케이브로드밴드」가 아니라 **SK브로드밴드**로 적어야 자기 집 케이블을 알아본다.
 * 사장님이 주신 견본도 상표로 적혀 있다.
 * ⛔ 자료 파일은 거둔 그대로 둔다. 바꾸는 것은 **화면에 내보낼 때**뿐이다.
 */
const 상표 = [
  ['에스케이브로드밴드', 'SK브로드밴드'],
  ['엘지헬로비전', 'LG헬로비전'],
  ['에이치씨엔', 'HCN'],
  ['씨씨에스충북방송', 'CCS충북방송'],
  ['씨엠비', 'CMB'],
  ['케이티스카이라이프', 'KT스카이라이프'],
  ['에이비씨', 'ABC'],
  ['티씨엔대구', 'TCN대구'],
];

export function 상표로(이름) {
  let 글 = String(이름 ?? '');
  for (const [푼것, 상표이름] of 상표) 글 = 글.split(푼것).join(상표이름);
  return 글;
}

/* ── 표 만들기 ─────────────────────────────────────────────────────── */

/** 머리글과 줄을 받아 마크다운 표 1개를 낸다. 정렬은 `맞춤` 으로 준다('left'|'right') */
export function 표(머리, 맞춤, 줄들) {
  if (!줄들.length) return '';
  const 선 = 맞춤.map((m) => (m === 'right' ? '---:' : '---'));
  return [
    `| ${머리.join(' | ')} |`,
    `|${선.map((s) => s).join('|')}|`,
    ...줄들.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

/**
 * 전국 사업자(IPTV·위성) 표.
 * ⛔ 번호가 빈 사업자는 줄째로 뺀다 — 빈칸을 화면에 내지 않는다.
 */
export function 전국표(전국) {
  const 줄 = 전국.filter((r) => String(r.번호 || '').trim())
    .map((r) => [상표로(r.사업자), r.번호]);
  return 표(['사업자', '채널번호'], ['left', 'right'], 줄);
}

/**
 * 지역 케이블 표. 권역 차례는 자료에 적힌 차례를 그대로 따른다.
 * ⛔ 디지털·8VSB 가 둘 다 빈 줄은 뺀다.
 */
export function 지역표(지역) {
  const 줄 = 지역
    .filter((r) => String(r.디지털 || '').trim() || String(r['8VSB'] || '').trim())
    .map((r) => [
      r.권역,
      r.세부 || '',
      상표로(r.사업자),
      String(r.디지털 || '').trim() || '-',
      String(r['8VSB'] || '').trim() || '-',
    ]);
  return 표(['권역', '지역', '사업자', '디지털', '8VSB'], ['left', 'left', 'left', 'right', 'right'], 줄);
}

/* ── 페이지 1개를 글로 ───────────────────────────────────────────────── */

/**
 * 사장님이 주신 차례 그대로다.
 *   (1) 편성표 → 바로보기 링크 → 함께 보는 채널
 *   (2) 채널번호 → 1) IPTV·스카이라이프 → 2) 지역 케이블 → 바로보기 링크
 */
export function 본문(채널, 같이보기) {
  const 전국 = 전국표(채널.전국);
  const 지역 = 지역표(채널.지역);
  const 이름 = 채널.이름;
  const 바로보기 = `**[${이름} 편성표 바로보기](${채널.편성표})**`;

  return `## (1) ${이름} 편성표

${이름} 편성표는 ${이름.toLowerCase()} 공식홈의 편성표에서 확인할 수 있다.

${바로보기}

${같이보기}의 편성표도 함께 확인할 수 있다.

## (2) ${이름} 채널번호

### 1) IPTV-스카이라이프

${전국}

### 2) 지역 케이블

${이름} 채널번호는 지역 케이블TV마다 달라 일일이 확인하는 게 필요하다.

${지역}

${바로보기}
`;
}

/** 머리글(frontmatter). 따옴표가 든 값은 큰따옴표로 감싸고 안쪽을 덧댄다 */
function 따옴(값) {
  return `"${String(값).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

export function 머리글(채널, 잰날, 부제) {
  return `---
title: ${따옴(`${채널.이름} 채널번호-편성표`)}
dek: ${따옴(부제)}
category: tvguide
pubDate: ${잰날}T09:00:00+09:00
subject:
  명칭: ${따옴('채널번호와 편성표')}
  유형: channel
  일시: ${잰날}T09:00:00+09:00
  주체: ${따옴(채널.이름)}
sources:
  - org: ${따옴(채널.운영)}
    api: ${따옴(`${채널.이름} 채널번호 안내 — IPTV·위성·지역 케이블 사업자별 번호`)}
    url: ${따옴(채널.공식)}
  - org: ${따옴(채널.운영)}
    api: ${따옴(`${채널.이름} 편성표`)}
    url: ${따옴(채널.편성표)}
tags: [${[채널.이름, '채널번호', '편성표', 'IPTV', '케이블TV'].map(따옴).join(', ')}]
author: "K Culture Wire"
---

`;
}

/* ── 돌리기 ───────────────────────────────────────────────────────── */

const 부제 = {
  jtbc: 'KT·SK브로드밴드·LG유플러스는 15번, 스카이라이프는 4번. 지역 케이블 번호는 사업자마다 달라 전국을 모아 뒀다.',
  jtbc2: 'KT 39번, SK브로드밴드 48번, LG유플러스 40번, 스카이라이프 45번. 지역 케이블 번호와 편성표 주소를 함께 본다.',
  jtbc4: '스카이라이프 46번. IPTV와 지역 케이블 번호가 각각 달라 사업자별로 모아 뒀다.',
};
const 같이보기 = {
  jtbc: 'JTBC2, JTBC4',
  jtbc2: 'JTBC, JTBC4',
  jtbc4: 'JTBC, JTBC2',
};
const 파일이름 = {
  jtbc: 'jtbc-channel-number-schedule.md',
  jtbc2: 'jtbc2-channel-number-schedule.md',
  jtbc4: 'jtbc4-channel-number-schedule.md',
};

function 만든다() {
  const 자료 = JSON.parse(fs.readFileSync(자료자리, 'utf8'));
  const 적은것 = [];
  for (const 채널 of 자료.채널) {
    const 낼이름 = 파일이름[채널.코드];
    if (!낼이름) continue;
    const 글 = 머리글(채널, 자료.잰날, 부제[채널.코드]) + 본문(채널, 같이보기[채널.코드]);
    fs.writeFileSync(path.join(낼자리, 낼이름), 글, 'utf8');
    적은것.push(`${낼이름}  (지역 ${채널.지역.length}곳)`);
  }
  return 적은것;
}

/* ── 자체검사 ─────────────────────────────────────────────────────── */

function 검사() {
  let 깨진것 = 0;
  const 본다 = (이름, 참인가) => {
    if (참인가) return;
    깨진것 += 1;
    console.error(`  ✗ ${이름}`);
  };

  const t = 표(['가', '나'], ['left', 'right'], [['1', '2']]);
  본다('표 머리글이 나온다', t.startsWith('| 가 | 나 |'));
  본다('오른쪽 정렬이 표시된다', t.includes('---:'));
  본다('줄이 나온다', t.includes('| 1 | 2 |'));
  본다('줄이 없으면 빈 글이다', 표(['가'], ['left'], []) === '');

  const 전국 = 전국표([
    { 사업자: '가', 번호: '15' },
    { 사업자: '나', 번호: '' },
  ]);
  본다('번호가 빈 사업자는 줄째로 빠진다', !전국.includes('| 나 |'));
  본다('번호가 있는 사업자는 남는다', 전국.includes('| 가 | 15 |'));

  본다('풀어 적은 이름을 상표로 바꾼다', 상표로('에스케이브로드밴드 강서') === 'SK브로드밴드 강서');
  본다('헬로비전도 바꾼다', 상표로('엘지헬로비전 양천') === 'LG헬로비전 양천');
  본다('상표가 이미 상표면 그대로 둔다', 상표로('KT 지니 TV') === 'KT 지니 TV');

  const 지역 = 지역표([
    { 권역: '서울', 세부: '강남구', 사업자: '가', 디지털: '15', '8VSB': '15-1' },
    { 권역: '서울', 세부: '서초구', 사업자: '나', 디지털: '', '8VSB': '' },
    { 권역: '부산', 세부: '', 사업자: '다', 디지털: '15', '8VSB': '' },
  ]);
  본다('디지털·8VSB 가 둘 다 비면 줄이 빠진다', !지역.includes('| 나 |'));
  본다('한쪽만 있으면 남고 빈 쪽은 - 로 적는다', 지역.includes('| 부산 |  | 다 | 15 | - |'));

  const 글 = 본문(
    { 이름: 'JTBC', 편성표: 'https://jtbc.co.kr/schedule', 전국: [{ 사업자: 'KT', 번호: '15' }], 지역: [] },
    'JTBC2, JTBC4',
  );
  본다('사장님 차례 (1) 편성표가 먼저다', 글.indexOf('## (1)') < 글.indexOf('## (2)'));
  본다('IPTV 가 지역 케이블보다 앞이다', 글.indexOf('### 1)') < 글.indexOf('### 2)'));
  본다('바로보기에 링크가 걸린다', 글.includes('](https://jtbc.co.kr/schedule)'));
  본다('페이지에 h1 을 넣지 않는다', !/^# /m.test(글));

  const 머리 = 머리글({ 이름: 'JTBC', 운영: '제이티비씨', 공식: 'https://a.b', 편성표: 'https://c.d' }, '2026-11-10', '부제');
  본다('분류가 tvguide 다', 머리.includes('category: tvguide'));
  본다('대상 유형이 channel 이다', 머리.includes('유형: "channel"') || 머리.includes('유형: channel'));

  if (깨진것) {
    console.error(`\n자체검사 ${깨진것}가지 깨졌다`);
    process.exitCode = 1;
  } else {
    console.log('자체검사 18가지 통과');
  }
}

if (process.argv.includes('--자체검사')) {
  검사();
} else {
  검사();
  if (!process.exitCode) {
    for (const 줄 of 만든다()) console.log(`적었다  ${줄}`);
  }
}
