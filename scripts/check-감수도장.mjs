export function 내려둔것인가(파일, 있나) {
  const 이름 = String(파일 ?? '').split('/').pop();
  if (!이름 || !이름.endsWith('.astro')) return false;
  if (typeof 있나 !== 'function') return false;
  return Boolean(있나(`docs/내린지면/${이름}`));
}

export function 감수검사(대상들, 도장표, 읽기, 있나) {
  const 막을것 = [];
  (대상들 ?? []).forEach((파일) => {
    let 글 = null;
    try { 글 = 읽기(파일); } catch { 글 = null; }
    if (글 == null) {
      if (내려둔것인가(파일, 있나)) return;   /* 내려서 옮긴 것 — 감수할 것이 없다 */
      막을것.push({ 파일, 왜: '파일을 못 읽었다' });
      return;
    }

    const 도장 = 도장표 instanceof Map ? 도장표.get(파일) : (도장표 ?? {})[파일];
    if (!도장) { 막을것.push({ 파일, 왜: '감수 도장이 없다' }); return; }
    if (!통과인가(도장.판정)) {
      막을것.push({ 파일, 왜: `감수 판정이 「${도장.판정 || '빈칸'}」이다` + (도장.왜 ? ` — ${도장.왜}` : '') });
      return;
    }
    if (도장.해시 !== 해시내기(글)) {
      막을것.push({ 파일, 왜: `감수 뒤에 고쳤다 (도장 ${도장.해시} · 지금 ${해시내기(글)})` });
      return;
    }
    /* 🔴 [2026-09-16 · 사장님 「감수할 때는 반드시 눈으로 잴것」 · 「그리고 징검다리 3개도」]
       ⛔ 규칙이 생기기 «전»에 찍힌 도장까지 소급해서 막지 않는다.
         소급하면 오늘 배포가 통째로 잠기고, 잠긴 관문은 사람이 꺼 버린다.
         ⇒ 규칙은 «앞으로 찍는 것»에 건다. 옛 도장은 따로 다시 감수받게 한다(1번에게 넘겼다). */
    if (String(도장.판정 ?? '').trim() === 통과글 && 규칙뒤인가(도장.시각)) {
      const 눈 = 눈으로쟀나(도장.왜);
      if (!눈.잰다) {
        막을것.push({ 파일, 왜: '눈으로 잰 자취가 없다 — ' + 눈.빠진것.join(' · ') });
        return;
      }
      if (돈받는파일인가(파일)) {
        const 다리 = 징검다리밟았나(도장.왜);
        if (!다리.밟았다) {
          막을것.push({ 파일, 왜: '값을 받는 곳인데 징검다리를 안 밟았다 — 빠진 것: ' + 다리.빠진것.join('·') });
        }
      }
    }
  });
  return 막을것;
}

