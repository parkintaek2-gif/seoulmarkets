/**
 * 도장의 「왜」 칸에 «눈으로 잰 자취»가 있나.
 * ⛔ 「봤다」·「확인」 같은 말은 자취가 아니다. **어느 화면을 몇 px 로 봤는지**가 있어야 한다.
 */
export function 눈으로쟀나(왜) {
  const 글 = String(왜 ?? '');
  const 폭 = /\b(\d{3,4})\s*px\b/gi;
  const 본폭 = [...글.matchAll(폭)].map((m) => Number(m[1]));
  const 좁은것 = 본폭.some((n) => n <= 600);
  const 넓은것 = 본폭.some((n) => n >= 1000);
  const 어디 = /https?:\/\/|\/[a-z0-9-]/i.test(글);
  return {
    잰다: 좁은것 && 넓은것 && 어디,
    본폭,
    빠진것: [
      좁은것 ? null : '폰 크기(600px 이하)로 본 자취가 없다',
      넓은것 ? null : '데스크톱 크기(1000px 이상)로 본 자취가 없다',
      어디 ? null : '어느 화면을 봤는지가 없다 (주소나 경로)',
    ].filter(Boolean),
  };
}

/**
 * 「눈으로 잴것」 규칙이 선 때. 이보다 «먼저» 찍힌 도장에는 묻지 않는다.
 * ⛔ 규칙을 소급 적용하면 관문이 통째로 잠기고, 잠긴 관문은 사람이 꺼 버린다.
 *   ⇒ 옛 도장은 관문으로 막는 대신 «다시 감수받을 목록»으로 넘긴다.
 * ⚠ 이 PC 는 이미 KST 다. 9시간을 더하지 않는다.
 */
export const 규칙선때 = '2026-09-16 16:00';

export function 규칙뒤인가(시각, 선때 = 규칙선때) {
  const s = String(시각 ?? '').trim();
  if (!s) return false;                     /* 시각이 없으면 옛것으로 본다 — 안 막는다 */
  return s >= String(선때);                 /* 「YYYY-MM-DD HH:MM」 꼴이라 글자 비교로 맞다 */
}

/** 규칙이 서기 «전»에 통과로 찍혀 다시 감수받아야 하는 것 — 막지는 않고 알려만 준다 */
export function 다시감수받을것(대상들, 도장표) {
  const 낸다 = [];
  (대상들 ?? []).forEach((파일) => {
    const 도장 = 도장표 instanceof Map ? 도장표.get(파일) : (도장표 ?? {})[파일];
    if (!도장 || String(도장.판정 ?? '').trim() !== 통과글) return;
    if (규칙뒤인가(도장.시각)) return;
    if (!눈으로쟀나(도장.왜).잰다) 낸다.push({ 파일, 누구: 도장.누구, 시각: 도장.시각 });
  });
  return 낸다;
}

/** 돈 받는 곳인가 — 파일 경로로 가른다 */
export function 돈받는파일인가(파일, 목록 = 돈받는곳) {
  const p = String(파일 ?? '').toLowerCase().replace(/\\/g, '/');
  return (목록 ?? []).some((x) => p.includes(String(x).toLowerCase()));
}

