#!/usr/bin/env node
/**
 * 잰다-확인못한것이-지면에나갔나.mjs
 *   — **「확인하지 못했다」가 손님 화면에 나가 있나 잰다.**
 *
 * ── 🔴 왜 (2026-11-15 · 5번) ─────────────────────────────────────────
 * 사장님 2026-11-13 — 「**확인 안됐다는 내용은 어떤 콘텐트에도 들어가면 안됨. 이게 기본이야**」
 *
 * 그 지시를 받고 문서에만 적어 두었다. 그런데 오늘 케이리뷰를 열어 보니
 * **15편**에 「확인하지 못해 적지 않았다」 같은 문장이 그대로 나가 있었다.
 * 「확인하지 못한 것」이라는 소제목을 달고 한 칸을 통째로 내준 편도 있었다.
 *
 * ⇒ 못 잰 것은 **적지 말고 빼면 된다.** 못 쟀다고 적는 것은 저희끼리 보는
 *   보고에 쓰는 말이지 손님 화면에 쓰는 말이 아니다.
 * ⇒ 말로 둔 규칙은 잊힌다. 검사로 굳힌다.
 *
 * ⚠ 재는 곳은 «손님에게 나가는 글»뿐이다 — docs/ 는 우리끼리 보는 곳이라 안 잰다.
 *
 * 쓰는 법
 *   node scripts/잰다-확인못한것이-지면에나갔나.mjs            잰다 (걸리면 끝값 1)
 *   node scripts/잰다-확인못한것이-지면에나갔나.mjs --고친다    걸린 문장을 지운다
 *   node scripts/잰다-확인못한것이-지면에나갔나.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** 손님에게 나가는 글이 있는 곳 */
export const 재는곳 = ['content'];

/**
 * 손님 화면에 나가면 안 되는 말.
 * ⚠ 「확인」 한 낱말로 재면 「두 곳에서 확인했다」 같은 «옳은» 문장까지 걸린다.
 *   그래서 «못 쟀다»를 가리키는 꼴만 모은다.
 */
export const 걸리는말 = [
  '확인하지 못해',
  '확인하지 못했',
  '확인하지 못한',
  '확인되지 않았',
  '확인되지 않은',
  '확인할 수 없었',
  '확인이 안 됐',
  '확인 안 됐',
  '확인 못 한',
  '확인 못 했',
  '적지 않았다',
  '파악하지 못했',
  '알려지지 않았다',
];

/** 재지 않는 꼴 — 이 말이 같은 줄에 있으면 걸린 것으로 보지 않는다 */
export const 봐주는꼴 = [
  '아직 발표되지 않았다',   /* 공식이 아직 안 낸 것은 사실 서술이다 */
];

/** 한 줄이 걸리나 */
export function 줄이걸리나(줄, 말목록 = 걸리는말, 봐줄것 = 봐주는꼴) {
  const s = String(줄 ?? '');
  if (봐줄것.some((v) => s.includes(v))) return null;
  for (const 말 of 말목록) if (s.includes(말)) return 말;
  return null;
}

/** 머리말(frontmatter) 밖인가 — 머리말 안의 설명은 손님에게 안 보인다 */
export function 본문줄만(글) {
  const 줄들 = String(글 ?? '').split(/\r?\n/);
  if (줄들[0] !== '---') return 줄들.map((t, i) => ({ 번호: i + 1, 글: t }));
  const 끝 = 줄들.indexOf('---', 1);
  if (끝 < 0) return 줄들.map((t, i) => ({ 번호: i + 1, 글: t }));
  return 줄들.slice(끝 + 1).map((t, i) => ({ 번호: 끝 + 2 + i, 글: t }));
}

/** 글 하나를 잰다 */
export function 글을잰다(글) {
  const 걸림 = [];
  for (const { 번호, 글: 줄 } of 본문줄만(글)) {
    const 말 = 줄이걸리나(줄);
    if (말) 걸림.push({ 번호, 말, 줄: 줄.trim() });
  }
  return 걸림;
}

/**
 * 걸린 문장을 지운다.
 * ⛔ 줄 전체가 그 이야기뿐이면 줄을 지우고, 섞여 있으면 **그 문장만** 지운다.
 *   문단을 통째로 날리면 멀쩡한 사실까지 사라진다.
 */
export function 글을고친다(글) {
  const 줄들 = String(글 ?? '').split(/\r?\n/);
  const 머리끝 = 줄들[0] === '---' ? 줄들.indexOf('---', 1) : -1;
  let 고친수 = 0;
  const 나온것 = 줄들.map((줄, i) => {
    if (머리끝 >= 0 && i <= 머리끝) return 줄;
    if (!줄이걸리나(줄)) return 줄;
    /* 소제목이면 줄째로 지운다 */
    if (/^#{1,6}\s/.test(줄)) { 고친수 += 1; return null; }
    /* 문장 단위로 끊어 걸린 문장만 뺀다 */
    const 문장들 = 줄.split(/(?<=다\.)\s+/);
    const 남은것 = 문장들.filter((문장) => !줄이걸리나(문장));
    고친수 += 문장들.length - 남은것.length;
    const 합친것 = 남은것.join(' ').trim();
    return 합친것 === '' ? null : 합친것;
  });
  /* 지워져 빈 줄이 둘 이상 이어지면 하나로 줄인다 */
  const 추린것 = [];
  for (const 줄 of 나온것) {
    if (줄 === null) continue;
    if (줄.trim() === '' && 추린것.length && 추린것[추린것.length - 1].trim() === '') continue;
    추린것.push(줄);
  }
  return { 글: 추린것.join('\n'), 고친수 };
}

/** 잴 파일들을 모은다 */
export function 잴파일들(바탕 = 뿌리, 곳들 = 재는곳) {
  const 모은것 = [];
  for (const 곳 of 곳들) {
    const 방 = path.join(바탕, 곳);
    if (!fs.existsSync(방)) continue;
    const 쌓기 = (여기) => {
      for (const 이름 of fs.readdirSync(여기)) {
        const 길 = path.join(여기, 이름);
        const 상태 = fs.statSync(길);
        if (상태.isDirectory()) 쌓기(길);
        else if (/\.(md|mdx)$/i.test(이름)) 모은것.push(길);
      }
    };
    쌓기(방);
  }
  return 모은것.sort();
}

/* ────────────────────────── 자가시험 ────────────────────────── */
if (process.argv.includes('--자가시험')) {
  let 통과 = 0; let 탈 = 0;
  const 검 = (이름, 참) => { if (참) { 통과 += 1; console.log('✅ ' + 이름); } else { 탈 += 1; console.log('🔴 ' + 이름); } };

  검('못 쟀다는 말을 잡는다', 줄이걸리나('팀 기록은 확인하지 못해 적지 않았다.') !== null);
  검('소제목도 잡는다', 줄이걸리나('## 확인하지 못한 것') !== null);
  검('🔴 옳은 문장은 안 잡는다 — 두 곳에서 확인했다',
    줄이걸리나('이 글의 숫자는 두 곳에서 확인했다.') === null);
  검('🔴 옳은 문장은 안 잡는다 — 공식에서 확인한 값이다',
    줄이걸리나('KBL 공식 기록에서 확인한 값이다.') === null);
  검('봐주는 꼴은 넘긴다', 줄이걸리나('수상자는 아직 발표되지 않았다.') === null);
  검('⛔ null 에도 안 터진다', 줄이걸리나(null) === null);

  /* 머리말은 안 잰다 — 손님에게 안 보인다 */
  const 머리말있는글 = ['---', 'title: "확인하지 못한 것"', '---', '', '본문이다.'].join('\n');
  검('🔴 머리말 안은 재지 않는다', 글을잰다(머리말있는글).length === 0);
  const 머리말없는글 = ['본문이다.', '팀 기록은 확인하지 못해 적지 않았다.'].join('\n');
  검('머리말이 없어도 본문을 잰다', 글을잰다(머리말없는글).length === 1);
  검('줄 번호를 제대로 센다', 글을잰다(머리말없는글)[0].번호 === 2);

  /* 고치기 */
  const 섞인글 = ['BLG가 3대1로 이겼다. 결승 MVP는 확인하지 못해 적지 않았다.'].join('\n');
  const 고친것 = 글을고친다(섞인글);
  검('🔴 섞인 줄에서 걸린 문장«만» 지운다', 고친것.글.includes('BLG가 3대1로 이겼다.'));
  검('🔴 걸린 문장은 사라진다', !고친것.글.includes('확인하지 못해'));
  검('몇 개를 고쳤는지 센다', 고친것.고친수 === 1);

  const 줄째글 = ['앞 문단이다.', '', '## 확인하지 못한 것', '', '뒤 문단이다.'].join('\n');
  const 고친것2 = 글을고친다(줄째글);
  검('소제목은 줄째로 지운다', !고친것2.글.includes('## 확인하지 못한 것'));
  검('앞뒤 문단은 남는다',
    고친것2.글.includes('앞 문단이다.') && 고친것2.글.includes('뒤 문단이다.'));
  검('⛔ 빈 줄이 셋씩 이어지지 않는다', !/\n\n\n/.test(고친것2.글));

  검('머리말은 고치지 않는다', 글을고친다(머리말있는글).글.includes('title: "확인하지 못한 것"'));
  검('⛔ null 에도 안 터진다 — 고치기', 글을고친다(null).고친수 === 0);
  검('잴 파일을 모은다', Array.isArray(잴파일들()));
  검('⛔ 없는 곳을 줘도 안 터진다', 잴파일들(뿌리, ['없는방']).length === 0);

  console.log(`\n${탈 ? '🔴' : '✅'} ${탈}/${통과 + 탈} 떨어졌다`);
  process.exit(탈 ? 1 : 0);
}

/* ────────────────────────── 본 일 ────────────────────────── */
if (!process.argv.includes('--자가시험')) {
  const 고친다 = process.argv.includes('--고친다');
  const 파일들 = 잴파일들();
  let 걸린파일 = 0; let 걸린줄 = 0; let 고친파일 = 0; let 고친줄 = 0;

  console.log(`■ 손님에게 나가는 글 ${파일들.length}편을 잰다 — 「확인하지 못했다」가 나가 있나\n`);

  for (const 길 of 파일들) {
    const 글 = fs.readFileSync(길, 'utf8');
    const 걸림 = 글을잰다(글);
    if (!걸림.length) continue;
    걸린파일 += 1; 걸린줄 += 걸림.length;
    console.log(`🔴 ${path.relative(뿌리, 길)}`);
    for (const { 번호, 말, 줄 } of 걸림) {
      console.log(`   ${번호}줄  「${말}」  ${줄.slice(0, 70)}${줄.length > 70 ? ' …' : ''}`);
    }
    if (고친다) {
      const { 글: 새글, 고친수 } = 글을고친다(글);
      fs.writeFileSync(길, 새글, 'utf8');
      고친파일 += 1; 고친줄 += 고친수;
      console.log(`   ✅ ${고친수}곳을 지웠다`);
    }
    console.log('');
  }

  if (!걸린파일) {
    console.log('✅ 깨끗하다 — 못 쟀다는 말이 손님 화면에 없다.');
    process.exit(0);
  }

  console.log(`■ 걸린 글 ${걸린파일}편 · 걸린 줄 ${걸린줄}곳`);
  if (고친다) {
    console.log(`■ 고친 글 ${고친파일}편 · 지운 곳 ${고친줄}`);
    console.log('   ⭐ 고친 뒤에는 «열어서 본다.** 문장이 끊기지 않았는지 눈으로 확인한다.');
    process.exit(0);
  }
  console.log('   ⭐ --고친다 를 붙이면 걸린 문장만 지운다.');
  console.log('   ⛔ 못 잰 것은 «적지 말고 빼면 된다». 못 쟀다고 적는 것은 보고에 쓰는 말이다.');
  process.exit(1);
}
