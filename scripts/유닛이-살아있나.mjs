#!/usr/bin/env node
/**
 * 유닛이-살아있나.mjs — **「대장이 비었다」와 「그 유닛이 멈췄다」를 가른다.**
 *
 * ── 🔴🔴 왜 (2026-10-10 18:3x · 5번) ────────────────────────────────
 * `check-2h ⑭` 가 「2번 82시간째 조용하다」고 울었고 나는 그대로 사장님께 올렸다.
 * 그런데 재 보니 2번 세션 파일이 **18:28 까지** 쓰이고 있었다 —
 * `klifemap/public/saju.html` 의 `renderPalace` 를 만지는 중이었다.
 *
 * ```
 * 매시소통 대장   마지막 2026-10-07 08:08   ← 82시간 비었다
 * 세션 파일       마지막 2026-10-10 18:28   ← 지금도 돌고 있다
 * ```
 *
 * ⛔ **대장이 비었다 ≠ 그 유닛이 멈췄다.** 둘은 다른 물음이다.
 *   하나로 읽으면 「멈춘 유닛을 깨우러」 가서 아무것도 못 하고, 정작 해야 할 일
 *   —「소통을 왜 안 적나」— 는 안 한다. 오늘 내가 그랬다.
 * ⭐ 오늘 하루 **같은 모양을 일곱 번** 했다. 한 증거로 두 가지를 증명했다고 믿은 것이다.
 *
 * ⇒ 이 자가 **세션 파일이 마지막으로 쓰인 때**를 재서 「살아 있나」만 답한다.
 *   「소통을 적었나」는 매시소통 대장이 따로 답한다. **물음이 둘이면 재는 것도 둘이다.**
 *
 * ⛔ 남의 유닛 파일을 **읽기만** 한다. 고치지도 커밋하지도 않는다.
 * ⛔ 대화 «내용»을 읽지 않는다 — 파일이 언제 쓰였나만 본다. 그것으로 충분하다.
 * ⚠ 못 읽으면 「못 쟀다」다. 「멈췄다」로 만들지 않는다.
 *
 * 쓰는 법
 *   node scripts/유닛이-살아있나.mjs
 *   node scripts/유닛이-살아있나.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** 유닛 번호 → 그 유닛의 세션 설정 칸 */
export const 유닛칸 = (번호) => `C:\\Users\\USER\\.claude-u${번호}`;

/** 몇 시간 넘게 세션 파일이 안 쓰이면 「멈췄다」로 보나 */
export const 참는시간 = 6;

/**
 * 그 유닛의 세션 파일 가운데 **가장 최근에 쓰인 때**(ms). 못 읽으면 null.
 * ⛔ null 은 「멈췄다」가 아니라 「못 쟀다」다.
 */
export function 마지막움직인때(번호, { 바닥 = null, 읽는이 = 참으로읽는다 } = {}) {
  const 방 = 바닥 ?? path.join(유닛칸(번호), 'projects');
  try { return 읽는이(방); } catch { return null; }
}

function 참으로읽는다(방) {
  if (!fs.existsSync(방)) return null;
  let 가장최근 = null;
  for (const 갈래 of fs.readdirSync(방)) {
    const 안 = path.join(방, 갈래);
    let 목록;
    try { if (!fs.statSync(안).isDirectory()) continue; 목록 = fs.readdirSync(안); } catch { continue; }
    for (const 이름 of 목록) {
      if (!이름.endsWith('.jsonl')) continue;
      try {
        const t = fs.statSync(path.join(안, 이름)).mtimeMs;
        if (가장최근 === null || t > 가장최근) 가장최근 = t;
      } catch { /* 못 보면 못 본 것이다 */ }
    }
  }
  return 가장최근;
}

/**
 * 살아 있나를 판정한다.
 * @returns {{판정:'돈다'|'멈췄다'|'못잼', 지난시간:number|null}}
 */
export function 살아있나(마지막ms, 이제 = Date.now(), 참는 = 참는시간) {
  if (!Number.isFinite(마지막ms)) return { 판정: '못잼', 지난시간: null };
  const 시간 = (이제 - 마지막ms) / 3600000;
  if (시간 < 0) return { 판정: '못잼', 지난시간: null };   /* 미래 시각 — 시계가 어긋났다 */
  return { 판정: 시간 <= 참는 ? '돈다' : '멈췄다', 지난시간: Math.round(시간 * 10) / 10 };
}

/**
 * 「조용하다」를 두 갈래로 가른다 — 이것이 이 자를 만든 까닭이다.
 * @param {'돈다'|'멈췄다'|'못잼'} 삶   세션 파일로 잰 것
 * @param {number|null} 대장빈시간      매시소통 대장이 비어 있는 시간
 */
export function 무엇이문제인가(삶, 대장빈시간, 참는 = 20) {
  const 빔 = Number.isFinite(대장빈시간) && 대장빈시간 > 참는;
  if (!빔) return { 말: '대장도 차 있다', 무엇: '없음' };
  if (삶 === '돈다') {
    return {
      말: '유닛은 «돌고 있다» — 빈 것은 «소통 대장»이다. 깨울 일이 아니라 적으라 할 일이다',
      무엇: '소통안적음',
    };
  }
  if (삶 === '멈췄다') return { 말: '세션도 멈췄다 — 창이 닫혔을 수 있다', 무엇: '멈춤' };
  return { 말: '세션 파일을 못 읽었다 — 「멈췄다」로 치지 않는다', 무엇: '못잼' };
}

/* ── 자가시험 ─────────────────────────────────────────────────── */
function 자가시험() {
  let 통 = 0; let 탈 = 0;
  const 검 = (이름, 참) => { if (참) { 통++; console.log('✅', 이름); } else { 탈++; console.log('🔴', 이름); } };

  const 이제 = Date.parse('2026-10-10T18:40:00+09:00');
  const 아까 = (시간) => 이제 - 시간 * 3600000;

  검('방금 쓰였으면 돈다', 살아있나(아까(0.2), 이제).판정 === '돈다');
  검('여섯 시간까지는 돈다로 본다', 살아있나(아까(5.9), 이제).판정 === '돈다');
  검('🔴 여섯 시간 넘으면 멈췄다', 살아있나(아까(7), 이제).판정 === '멈췄다');
  검('⛔ 못 읽으면 「못잼」이다 — 「멈췄다」로 만들지 않는다',
    살아있나(null, 이제).판정 === '못잼' && 살아있나(NaN, 이제).판정 === '못잼');
  검('⛔ 미래 시각이면 못잼 — 시계가 어긋난 것이다', 살아있나(이제 + 99999, 이제).판정 === '못잼');
  검('지난 시간을 한 자리까지 낸다', 살아있나(아까(3.25), 이제).지난시간 === 3.3);

  /* 🔴🔴 오늘 당한 그 꼴 — 대장은 82시간 비었는데 세션은 12분 전에 쓰였다 */
  const 오늘 = 무엇이문제인가(살아있나(아까(0.2), 이제).판정, 82);
  검('🔴 대장만 비었으면 «소통을 안 적은 것»이라 말한다 — 오늘 이것을 「멈췄다」로 읽었다',
    오늘.무엇 === '소통안적음');
  검('🔴 그때 「깨울 일이 아니다」라고 적는다', 오늘.말.includes('적으라 할 일'));
  검('⛔ 세션도 멈췄으면 그대로 「멈춤」이다 — 덜 잡으면 진짜 사고를 놓친다',
    무엇이문제인가('멈췄다', 82).무엇 === '멈춤');
  검('⛔ 못 쟀으면 「못잼」이다', 무엇이문제인가('못잼', 82).무엇 === '못잼');
  검('⛔ 대장이 차 있으면 아무 말도 안 한다', 무엇이문제인가('돈다', 2).무엇 === '없음');
  검('⛔ 대장 시간을 못 읽어도 안 터진다', 무엇이문제인가('돈다', null).무엇 === '없음');

  /* 읽는이를 가짜로 바꿔 바깥을 안 보고 결을 잰다 */
  검('가짜 읽는이로 때를 받는다', 마지막움직인때(2, { 읽는이: () => 1234 }) === 1234);
  검('⛔ 읽다 터지면 null 이다', 마지막움직인때(2, { 읽는이: () => { throw new Error('x'); } }) === null);
  검('유닛 칸 이름이 번호를 따라간다', 유닛칸(2).endsWith('.claude-u2'));

  console.log(탈 ? `\n🔴 자가시험 ${탈}건 탈` : `\n✅ 자가시험 ${통} 통과`);
  process.exit(탈 ? 1 : 0);
}

if (process.argv.includes('--자가시험')) 자가시험();

/* ── 실제로 잰다 ─────────────────────────────────────────────── */
const 내가실행됐다 = process.argv[1]
  && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (내가실행됐다) {
  console.log('■ 유닛 세션이 살아 있나 — 파일이 «언제 쓰였나»만 본다 (내용은 안 읽는다)');
  const 이제 = Date.now();
  for (const n of [1, 2, 3, 4, 5, 6]) {
    const t = 마지막움직인때(n);
    const r = 살아있나(t, 이제);
    const 때 = Number.isFinite(t)
      ? new Date(t).toLocaleString('sv-SE').slice(0, 16)      /* ⛔ toISOString 금지 — KST 다 */
      : '못 읽었다';
    const 표 = { 돈다: '✅ 돈다', 멈췄다: '⬜ 멈췄다', 못잼: '⬜ 못 쟀다' };
    console.log(`   ${n}번  ${표[r.판정]}  마지막 ${때}`
      + (r.지난시간 === null ? '' : `  (${r.지난시간}시간 전)`));
  }
  console.log('\n⭐ 「대장이 비었다」와 「그 유닛이 멈췄다」는 다른 물음이다.');
  console.log('   소통을 적었나는 docs/매시소통.tsv 가 따로 답한다.');
}
