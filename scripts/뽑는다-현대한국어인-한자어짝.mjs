const 한자어의짝 = 거꾸로본다(고유어짝);
console.log('■ 재야 할 한자어 ' + 한자어의짝.size + '개 · 고유어 '
  + Object.keys(고유어짝).length + '개');

const 조각들 = fs.readdirSync(사전폴더).filter((f) => /\.xml$/i.test(f)).sort();
console.log('■ 사전 조각 ' + 조각들.length + '개를 읽는다');

const 판정 = {};                 /* 한자어 → { 고유어: [갈래…] } */
/* 🔴 모든 한자어 표제어의 쓰임을 센다 — 짝으로 나온 것만이 아니다.
 *   내가 «고른» 한자어가 현대 한국어인지 되물을 수 있어야 한다.
 *   사전이 적어 둔 짝(까닭→소이)이 현대 한국어가 아닐 때 내가 다른 말(이유)을 고르는데,
 *   그 고른 말이 현대 한국어인지 잴 자가 없으면 또 느낌으로 고르게 된다. */
const 쓰인수 = new Map();        /* 한자어 → 뜻풀이 말뭉치에서 낱말로 쓰인 횟수 */
let 최대길이 = 2;

const 고유어전부 = new Set();    /* 한자어 짝이 없어도 고유어이면 담는다 */
const 한자어표제어 = new Set();  /* 같은 소리의 한자어가 있으면 고유어로 몰지 않는다 */
let 읽은항목 = 0;
for (let i = 0; i < 조각들.length; i += 1) {
  const 글 = fs.readFileSync(path.join(사전폴더, 조각들[i]), 'utf8');
  for (const 항 of 항목을읽는다(글)) {
    읽은항목 += 1;
    if (항.어종 === '한자어' || 항.어종 === '혼종어') 한자어표제어.add(항.이름);
    if (잡을고유어인가(항)) {
      고유어전부.add(항.이름);
      /* 용언은 «어간»도 담는다 — 「간추리다」를 담아도 「간추립니다」가 안 잡힌다.
       * ⛔ 한 글자 어간은 담지 않는다. 「하」·「보」가 온갖 말에 걸려 오탐이 쏟아진다. */
      if (/다$/.test(항.이름) && 항.이름.length >= 4) 고유어전부.add(항.이름.slice(0, -1));
    }
    for (const 뜻 of 항.뜻들) {
      if (!뜻) continue;
      /* 갈래 — 그 한자어가 «그 고유어와 짝 지어진 뜻»에서 옛말인가 */
      const 짝인고유어들 = 한자어의짝.get(항.이름);
      if (!짝인고유어들) continue;
      const 갈래 = 뜻풀이갈래(뜻);
      for (const 고유어 of 짝인고유어들) {
        /* ⛔ 그 «고유어가 나오는 뜻»만 본다 — 동음이의어를 섞지 않는다 */
        if (!뜻.includes(고유어)) continue;
        if (!판정[항.이름]) 판정[항.이름] = {};
        if (!판정[항.이름][고유어]) 판정[항.이름][고유어] = [];
        판정[항.이름][고유어].push(갈래);
      }
    }
  }
  if ((i + 1) % 20 === 0) console.log('   … ' + (i + 1) + '/' + 조각들.length);
}
console.log('■ 읽은 항목 ' + 읽은항목.toLocaleString() + '개 · 뜻을 찾은 한자어 '
  + Object.keys(판정).length + '개 · 한자어 표제어 ' + 한자어표제어.size + '개');

/* ── 두 번째 훑기 — 한자어가 뜻풀이 말뭉치에 «낱말로» 몇 번 나오나 ────────────
 * 🔴 한자어 표제어를 다 모은 뒤라야 셀 키가 정해진다. 그래서 두 번 훑는다.
 * ⛔ 한자어마다 뜻풀이를 훑으면 수십만 × 수십만이라 끝나지 않는다 —
 *   뜻풀이 쪽에서 «덩어리 머리» 토막을 뽑아 표로 세는 것이 선형이다. */
for (const w of 한자어표제어) if (w.length >= 2 && w.length <= 6) 쓰인수.set(w, 0);
/* ⛔ 스프레드(...)로 최댓값을 구하지 않는다 — 키가 수십만이면 스택이 넘친다.
 *   2026-11-22 에 실제로 RangeError 로 멈췄다. */
for (const w of 쓰인수.keys()) if (w.length > 최대길이) 최대길이 = w.length;
console.log('■ 쓰임을 잴 한자어 ' + 쓰인수.size + '개 — 사전을 한 번 더 훑는다');

for (let i = 0; i < 조각들.length; i += 1) {
  const 글 = fs.readFileSync(path.join(사전폴더, 조각들[i]), 'utf8');
  for (const 항 of 항목을읽는다(글)) {
    for (const 뜻 of 항.뜻들) {
      if (!뜻) continue;
      for (const 덩이 of 뜻.match(/[가-힣]+/g) || []) {
        const 끝 = Math.min(최대길이, 덩이.length);
        for (let b = 2; b <= 끝; b += 1) {
          if (덩이.length - b > 3) continue;       /* 꼬리가 길면 다른 낱말이다 */
          const 토막 = 덩이.slice(0, b);
          if (쓰인수.has(토막)) 쓰인수.set(토막, 쓰인수.get(토막) + 1);
        }
      }
    }
  }
  if ((i + 1) % 20 === 0) console.log('   … ' + (i + 1) + '/' + 조각들.length);
}

const 최소출현 = Number(process.argv[4] || 5);
const { 남길것, 버린것 } = 짝을거른다(고유어짝, 판정, 쓰인수, 최소출현);
console.log('■ 남긴 짝 ' + Object.keys(남길것).length
  + '개 · 버린 짝 ' + Object.keys(버린것).length + '개');

const 머리 = [
  '/* 바꿀만한-짝.js — **한자어 쪽이 현대 한국어인 짝만** 남긴 표.',
  ' *',
  ' * 🔴 사장님 2026-11-22 — 「한자어가 현대 한국어가 아닌 지만 보면 되고」',
  ' *',
  ' * ⛔ 손으로 고치지 않는다. `scripts/뽑는다-현대한국어인-한자어짝.mjs` 가 다시 만든다.',
  ' * 표준국어대사전 짝 ' + Object.keys(고유어짝).length + '개 가운데',
  ' * 한자어 쪽이 현대 한국어인 ' + Object.keys(남길것).length + '개만 남겼다.',
  ' * 판정 — 그 한자어가 «그 고유어와 짝 지어진 뜻»에서',
  ' *        옛말·북한어·방언·잘못이면 뺐다. 뜻 단위로 보아 동음이의어를 섞지 않았다.',
  ' */',
  'export const 바꿀만한짝 = {',
].join('\n');
const 몸통 = Object.keys(남길것).sort()
  .map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(남길것[k]) + ',').join('\n');
fs.writeFileSync(낼길, 머리 + '\n' + 몸통 + '\n};\n', 'utf8');
console.log('✅ 냈다 — ' + 낼길);

/* 고유어 전체 목록 — 한자어 짝이 없어도 고유어는 고유어다.
 * 🔴 짝표만 쓰면 「간추림」·「사이」가 안 잡힌다. 사전이 그 말에 짝을 안 붙여서다.
 *   2026-11-22 에 사장님이 바로 그 둘을 짚으셨다. */
/* ⛔ 같은 소리의 «한자어»가 사전에 있으면 뺀다.
 *   2026-11-22 에 설기(洩氣)·매개(媒介)·양간(陽干)·이해(理解)를 고유어로 잡았다.
 *   한자어로 쓴 말을 고유어라 하면 바로 그 지시를 거스르는 셈이 된다. */
const 겹친것 = [...고유어전부].filter((w) => 한자어표제어.has(w));
for (const w of 겹친것) 고유어전부.delete(w);
console.log('■ 같은 소리의 한자어가 있어 뺀 말 ' + 겹친것.length + '개');

const 고유어길 = path.join(여기, '..', 'data', '사전-고유어-전부.js');
const 고유어머리 = [
  '/* 사전-고유어-전부.js — **표준국어대사전에서 어종이 고유어인 표제어 전부.**',
  ' *',
  ' * 🔴 사장님 2026-11-22 — 「한자어만 써. 조사 등 일부 품사만 순한글로 써」',
  ' *',
  ' * ⛔ 손으로 고치지 않는다. `scripts/뽑는다-현대한국어인-한자어짝.mjs` 가 다시 만든다.',
  ' * ⚠ 한자어 짝이 «없는» 것도 들어 있다 — 짝표(바꿀만한-짝.js)만으로는',
  ' *   「간추림」·「사이」 같은 말이 안 잡힌다. 바꿀 말은 내가 찾아 넣는다.',
  ' * ⛔ 조사·어미·접사·의존명사·감탄사와 한 글자 말은 뺐다.',
  ' */',
  'export const 사전고유어 = new Set([',
].join('\n');
fs.writeFileSync(고유어길,
  고유어머리 + '\n' + [...고유어전부].sort().map((w) => '  ' + JSON.stringify(w) + ',').join('\n')
  + '\n]);\n', 'utf8');
console.log('✅ 고유어 전부도 냈다 — ' + 고유어전부.size + '개 · ' + 고유어길);

/* 현대 한국어인 한자어 목록 — 내가 «고른» 말이 현대 한국어인지 되묻는 데 쓴다.
 * 🔴 사장님 2026-11-22 — 「한자어가 현대 한국어가 아닌 지만 보면 되고」
 *   사전이 적어 둔 짝(까닭→소이)을 그대로 쓰지 않고 내가 다른 말(이유)을 고를 때,
 *   그 고른 말을 느낌으로 정하지 않기 위해서다. */
const 성한한자어 = [...쓰인수.entries()].filter(([, n]) => n >= 최소출현).map(([w]) => w);
const 한자어길 = path.join(여기, '..', 'data', '현대한국어-한자어.js');
fs.writeFileSync(한자어길, [
  '/* 현대한국어-한자어.js — **지금도 쓰이는 한자어** 목록.',
  ' *',
  ' * 🔴 사장님 2026-11-22 — 「한자어가 현대 한국어가 아닌 지만 보면 되고」',
  ' *',
  ' * ⛔ 손으로 고치지 않는다. `scripts/뽑는다-현대한국어인-한자어짝.mjs` 가 다시 만든다.',
  ' * 표준국어대사전 한자어 표제어 ' + 한자어표제어.size + '개 가운데,',
  ' * 사전 뜻풀이 ' + 읽은항목.toLocaleString() + '항목에 «낱말로» ' + 최소출현
    + '번 이상 나오는 ' + 성한한자어.length + '개.',
  ' * ⚠ 사전 뜻풀이는 문어·한문투가 섞여 있다. 「소이」처럼 이 목록에 들어도',
  ' *   일상에 안 쓰는 말이 있다. 이 목록은 «걸러 내는 자»이지 «고르는 자»가 아니다.',
  ' */',
  'export const 현대한자어 = new Set([',
  성한한자어.sort().map((w) => '  ' + JSON.stringify(w) + ',').join('\n'),
  ']);',
].join('\n') + '\n', 'utf8');
console.log('✅ 현대 한국어 한자어도 냈다 — ' + 성한한자어.length + '개 · ' + 한자어길);

/* 몇 번 쓰였는지를 따로 낸다 — 문턱을 눈으로 정하기 위해서다 */
const 셈낼곳 = process.argv[5];
if (셈낼곳) {
  const 줄 = [...쓰인수.entries()].sort((a, b) => b[1] - a[1])
    .map(([w, n]) => n + '\t' + w).join('\n');
  fs.writeFileSync(셈낼곳, 줄 + '\n', 'utf8');
  console.log('   쓰인 횟수도 냈다 — ' + 셈낼곳);
}
