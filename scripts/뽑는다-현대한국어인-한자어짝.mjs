/** CDATA 와 붙임표·어깨번호를 걷어 낸 낱말 */
export function 다듬는다(날것) {
  return String(날것 ?? '')
    .replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, '$1')
    .replace(/[-^·\s]/g, '')
    .replace(/\d+$/, '')
    .trim();
}

/** CDATA 만 벗긴다 — 뜻풀이는 띄어쓰기를 살려야 「…의 옛말.」을 가려낸다 */
export function 속만꺼낸다(날것) {
  return String(날것 ?? '').replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, '$1').trim();
}

/**
 * 뜻풀이가 어느 갈래인가.
 * 표준국어대사전은 현대어가 아닌 뜻을 뜻풀이 안에서 그렇게 밝힌다.
 */
export function 뜻풀이갈래(뜻) {
  const 글 = String(뜻 ?? '');
  if (!글.trim()) return '모름';
  if (/옛말/.test(글)) return '옛말';
  if (/북한어/.test(글)) return '북한어';
  if (/방언/.test(글)) return '방언';
  if (/의\s*잘못/.test(글)) return '잘못';
  if (/옛 문헌|예전에|고어/.test(글)) return '옛말';
  return '보통';
}

/** 짝 하나에서 한자어 여럿을 끊어 낸다 — 사전이 「가 · 나 · 다」로 적어 둔다 */
export function 짝을쪼갠다(짝) {
  return String(짝 ?? '')
    .split('·')
    .map((x) => x.trim())
    .filter(Boolean);
}

/**
 * 뜻풀이 한 줄에서 그 한자어가 «낱말로» 몇 번 쓰였나 센다.
 *
 * ⛔ 그냥 includes 로 세면 안 된다 — 「추가토지」가 「가토」로 세어진다.
 *   2026-11-22 에 실제로 그렇게 오염되어 토끼·원숭이가 통과했다.
 *   한국어는 뒤에 조사가 붙으므로 «덩어리 머리»에서만 세고 꼬리는 세 글자까지 본다.
 */
export function 낱말로쓰였나(뜻, 한자어) {
  const 글 = String(뜻 ?? '');
  const w = String(한자어 ?? '');
  if (!글 || w.length < 2) return 0;
  let 수 = 0;
  const 덩이들 = 글.match(/[가-힣]+/g) || [];
  for (const 덩이 of 덩이들) {
    if (!덩이.startsWith(w)) continue;
    if (덩이.length - w.length <= 3) 수 += 1;   /* 꼬리는 조사·어미뿐이어야 한다 */
  }
  return 수;
}

/**
 * 그 짝이 쓸 만한가.
 *   갈래들 — 그 한자어가 «그 고유어와 짝 지어진 뜻»에서 받은 갈래 목록.
 *   쓰인수 — 사전 뜻풀이 말뭉치(436,578 항목)에서 그 한자어가 낱말로 쓰인 횟수.
 *
 * ① 짝 지어진 뜻이 옛말·북한어·방언·잘못뿐이면 못 쓴다.
 * ② 사전 뜻풀이는 현대 한국어로 적혀 있다. 거기에 낱말로 거의 안 나오는 한자어는
 *    현대 한국어로 치지 않는다. 사전이 표제어로 들고 있어도 마찬가지다 —
 *    「가토」는 집토끼의 한자어라 옛말 표시가 없지만 현대 한국어에 쓰이지 않는다.
 */
export function 쓸만한짝인가(갈래들, 쓰인수, 최소출현 = 5) {
  if (Array.isArray(갈래들) && 갈래들.length && !갈래들.includes('보통')) return false;
  if (!Number.isFinite(쓰인수)) return false;
  return 쓰인수 >= 최소출현;
}

/**
 * 그 고유어 표제어를 «글에서 잡을 말»로 셀 것인가.
 *
 * 🔴 사장님 2026-11-22 — 「한자어만 써. **조사 등 일부 품사만 순한글로 써.**
 *   명사 형용사 동사 대부분은 한자어잖아」
 * ⛔ 조사·어미·접사는 한자어로 바꿀 수 있는 말이 아니다. 세지 않는다.
 */
/* 🔴 사장님 — 「**명사 형용사 동사** 대부분은 한자어잖아」
 *   그 셋만 본다. 대명사·수사·부사·관형사는 한자어로 바꿀 수 있는 말이 아니다 —
 *   「그것」·「먼저」·「훨씬」을 한자어로 쓰라고 할 수는 없다. */
export const 안세는품사 = ['조사', '어미', '접사', '의존명사', '감탄사',
  '대명사', '수사', '부사', '관형사'];
export function 잡을고유어인가({ 어종, 품사들, 이름 } = {}) {
  if (어종 !== '고유어') return false;
  if (!이름 || 이름.length < 2) return false;            /* 한 글자는 조사·어미가 섞인다 */
  if (!/^[가-힣]+$/.test(이름)) return false;
  const 품 = Array.isArray(품사들) ? 품사들 : [];
  if (품.length && 품.every((p) => 안세는품사.includes(p))) return false;
  return true;
}

/** 한자어 → 그 한자어와 짝 지어진 고유어들 */
export function 거꾸로본다(짝표) {
  const 표 = new Map();
  for (const [고유어, 짝] of Object.entries(짝표 || {})) {
    for (const 한자어 of 짝을쪼갠다(짝)) {
      if (!표.has(한자어)) 표.set(한자어, new Set());
      표.get(한자어).add(고유어);
    }
  }
  return 표;
}

/**
 * 짝표를 거른다.
 *   판정 — { 한자어: { 고유어: [갈래…] } }
 *   한자어 여럿 가운데 쓸 만한 것만 남기고, 하나도 안 남으면 그 고유어를 뺀다.
 */
export function 짝을거른다(짝표, 판정, 쓰인수 = {}, 최소출현 = 5) {
  const 남길것 = {};
  const 버린것 = {};
  const 셈 = (w) => (쓰인수 instanceof Map ? 쓰인수.get(w) : 쓰인수[w]);
  for (const [고유어, 짝] of Object.entries(짝표 || {})) {
    const 성한것 = 짝을쪼갠다(짝)
      .filter((한자어) => 쓸만한짝인가(
        ((판정 || {})[한자어] || {})[고유어], 셈(한자어), 최소출현));
    if (성한것.length) 남길것[고유어] = 성한것.join(' · ');
    else 버린것[고유어] = 짝;
  }
  return { 남길것, 버린것 };
}

/** XML 조각에서 「표제어 · 어종 · 뜻풀이들」을 끊어 낸다 */
export function 항목을읽는다(글) {
  const 것 = [];
  const 재 = /<item>([\s\S]*?)<\/item>/g;
  let m;
  while ((m = 재.exec(String(글 ?? '')))) {
    const 속 = m[1];
    const 머리 = /<word_info>([\s\S]*?)(?:<pos_info>|<\/word_info>)/.exec(속);
    const 이름 = 다듬는다((/<word>([\s\S]*?)<\/word>/.exec(머리 ? 머리[1] : '') || [])[1]);
    const 어종 = 다듬는다((/<word_type>([\s\S]*?)<\/word_type>/.exec(속) || [])[1]);
    const 품사들 = [...속.matchAll(/<pos>([\s\S]*?)<\/pos>/g)].map((x) => 다듬는다(x[1]));
    const 뜻들 = [];
    const 뜻재 = /<definition>([\s\S]*?)<\/definition>/g;
    let d;
    while ((d = 뜻재.exec(속))) 뜻들.push(속만꺼낸다(d[1]));
    if (이름) 것.push({ 이름, 어종, 품사들, 뜻들 });
  }
  return 것;
}

