/** ⛔ 사장님 「너무 한번에 올리지마」 — 한 편 사이의 쉼 */
export const 편사이쉼 = 90 * 1000;

const 두자리 = (수) => String(수).padStart(2, '0');

/** 날짜를 글로 — ⛔ toISOString 을 쓰지 않는다. 이 PC 는 이미 한국시간이다 */
export function 날글(때) {
  return 때.getFullYear() + '-' + 두자리(때.getMonth() + 1) + '-' + 두자리(때.getDate());
}

/** 글을 날짜로. 꼴이 아니면 null — 지어내지 않는다 */
export function 날읽기(글) {
  const s = String(글 || '');
  if (s.length !== 10) return null;
  const 쪽 = s.split('-');
  if (쪽.length !== 3 || 쪽[0].length !== 4 || 쪽[1].length !== 2 || 쪽[2].length !== 2) return null;
  const 때 = new Date(Number(쪽[0]), Number(쪽[1]) - 1, Number(쪽[2]));
  if (Number.isNaN(때.getTime())) return null;
  if (날글(때) !== s) return null;   /* 2026-02-31 같은 날을 받아들이지 않는다 */
  return 때;
}

/** 시작일부터 며칠치의 날짜 목록 */
export function 날들(시작글, 며칠) {
  const 시작 = 날읽기(시작글);
  if (!시작 || !(며칠 > 0)) return [];
  const 모음 = [];
  for (let i = 0; i < 며칠; i += 1) {
    모음.push(날글(new Date(시작.getFullYear(), 시작.getMonth(), 시작.getDate() + i)));
  }
  return 모음;
}

/** 오늘 다음 날 */
export function 내일글(오늘 = new Date()) {
  return 날글(new Date(오늘.getFullYear(), 오늘.getMonth(), 오늘.getDate() + 1));
}

