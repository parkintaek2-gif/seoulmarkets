/**
 * 기록에서 **이미 올린 날**을 읽는다. 첫 칸이 날짜다.
 * ⛔ 파일이 없으면 빈 목록 — 「없다」와 「못 읽었다」를 섞지 않으려고 둘째 값으로 알린다.
 */
export function 올린날들(글) {
  const 날 = new Set();
  for (const 줄 of String(글 || '').split('\n')) {
    const 첫칸 = 줄.split('\t')[0];
    if (날읽기(첫칸)) 날.add(첫칸);
  }
  return [...날].sort();
}

/**
 * 🔴 **어디서부터 올릴 것인가.**
 *   이미 올린 마지막 날의 **다음 날**부터 간다. 그래야 같은 날을 두 번 내지 않는다.
 *   기록이 비어 있으면 내일부터.
 * ⛔ [2026-11-19] 이것이 없으면 토요일마다 돌면서 **이미 올려 둔 이레를 다시 올린다.**
 *   예약을 걸고 나서야 알았다 — 첫 회차가 11-21 인데 기사는 11-28 까지 올라가 있었다.
 */
export function 어디서부터(올린것, 오늘 = new Date()) {
  const 내일 = 내일글(오늘);
  const 쓸것 = (올린것 || []).filter((글) => 날읽기(글) && 글 >= 내일);
  if (!쓸것.length) return 내일;
  const 맨뒤 = 쓸것.slice().sort()[쓸것.length - 1];
  const 때 = 날읽기(맨뒤);
  return 날글(new Date(때.getFullYear(), 때.getMonth(), 때.getDate() + 1));
}

/** 올릴 차례를 만든다 — 날짜마다 두 편 */
export function 차례만들기(시작글, 며칠) {
  const 차례 = [];
  for (const 날 of 날들(시작글, 며칠)) {
    for (const 것 of 하루차림) 차례.push({ 날, ...것 });
  }
  return 차례;
}

/** 이미 올린 날은 건너뛴다 — 같은 날 기사를 두 번 내지 않는다 */
export function 빼고고른다(차례, 이미올린것) {
  const 있다 = new Set((이미올린것 || []).map((것) => 것.날 + '|' + 것.이름));
  return (차례 || []).filter((것) => !있다.has(것.날 + '|' + 것.이름));
}

/** 등록기 한 번 돌리기 */
function 돌린다(등록기, 인자들) {
  return new Promise((끝) => {
    const 아이 = spawn(process.execPath, [path.join(이폴더, 등록기), ...인자들], {
      cwd: path.dirname(이폴더), windowsHide: true,
    });
    let 글 = '';
    아이.stdout.on('data', (조각) => { 글 += String(조각); });
    아이.stderr.on('data', (조각) => { 글 += String(조각); });
    아이.on('close', (끝값) => 끝({ 끝값, 글 }));
    아이.on('error', (탈) => 끝({ 끝값: -1, 글: String(탈.message) }));
  });
}

/** 올라간 기사 번호를 로그에서 뽑는다 */
export function 번호뽑기(글) {
  const 줄 = String(글 || '').split('\n').find((한줄) => 한줄.includes('🟢 올라갔다'));
  if (!줄) return null;
  const 뒤 = 줄.split('idxno=')[1];
  if (!뒤) return null;
  const 번호 = 뒤.trim().split(' ')[0];
  return /^[0-9]{6,9}$/.test(번호) ? 번호 : null;
}

