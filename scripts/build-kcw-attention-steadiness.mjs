export function 띠(편수) {
  const n = 수로(편수);
  if (n === null) return null;
  if (n <= 1) return '1';
  if (n <= 3) return '2-3';
  if (n <= 6) return '4-6';
  return '7+';
}
export const 띠순서 = ['1', '2-3', '4-6', '7+'];
/** 한 띠의 흔들림 */
export function 흔들림(값들) {
  const v = 값들.filter((n) => n !== null && Number.isFinite(n));
  if (!v.length) return null;
  const q25 = 분위(v, 0.25), q50 = 분위(v, 0.5), q75 = 분위(v, 0.75);
  const 오른것 = v.filter((n) => n > 2).length;
  const 내린것 = v.filter((n) => n < 0.5).length;
  return {
    수: v.length,
    중간: +q50.toFixed(2),
    q25: +q25.toFixed(2),
    q75: +q75.toFixed(2),
    사분위폭: +(q75 - q25).toFixed(2),
    두배넘게오름: 오른것,
    절반아래로내림: 내린것,
    크게움직인비율: +((오른것 + 내린것) / v.length * 100).toFixed(1),
  };
}

export function 재기(배우들) {
  const 모음 = new Map(띠순서.map((k) => [k, []]));
  let 배수없는수 = 0, 편수없는수 = 0;
  for (const x of 배우들) {
    const k = 띠(x?.작품수);
    if (k === null) { 편수없는수 += 1; continue; }
    const b = 수로(x?.상승배수);
    /* ⬜ 앞 7일이 0 인 사람은 배수가 null 이다. 0 으로 채우지 않고 «세어서» 뺀다 */
    if (b === null) { 배수없는수 += 1; continue; }
    모음.get(k).push(b);
  }
  return {
    띠들: 띠순서.map((k) => ({ 띠: k, ...(흔들림(모음.get(k)) ?? { 수: 0 }) })),
    값들: 모음,                    /* 잡음 시험이 원래 값을 다시 뽑아야 한다 */
    배수없는수, 편수없는수,
  };
}

