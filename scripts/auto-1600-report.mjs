/** 오늘 날짜 — ⛔ toISOString() 금지. 이 PC 가 이미 KST 다 */
export function 오늘날짜(d = new Date()) {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

/**
 * 내가 오늘 16시 업무보고를 냈나 — 보낸메일 대장에서 찾는다.
 * ⚠ «내 것»만 센다. 2번이 낸 것을 내 것으로 세면 영영 안 낸다.
 */
export function 내가냈나(줄들, 날 = 오늘날짜()) {
  for (const 줄 of 줄들 ?? []) {
    const t = String(줄);
    if (!t.startsWith(날)) continue;
    if (!/업무보고/.test(t)) continue;
    /* 🔴🔴 [2026-10-22] 새벽 **00:45·00:58·01:06** 에 「[16시 업무보고]」가 나갔다.
       날짜만 보니 그것이 「오늘 16시 보고」로 셈해졌고, 16:00 에 이 자가 돌았을 때
       「이미 냈다」로 판정해 **진짜 16시 보고가 통째로 안 나갔다.**
       그 새벽 보고에는 그날 한 일이 하나도 없었다 — 어제 분량이었다.
       ⇒ **15시 이후에 나간 것만** 오늘 16시 보고로 본다.
       ⛔ 「제목에 16시라고 적혀 있다」를 「16시에 냈다」로 읽지 않는다. */
    const 시 = Number(t.slice(11, 13));
    if (!Number.isFinite(시) || 시 < 15) continue;
    /* 제목 칸에 「5번」이 들어야 내 것이다 */
    const 칸 = t.split('\t');
    const 제목 = 칸[3] ?? t;
    if (/5번/.test(제목)) return true;
  }
  return false;
}

/** 자동 보고를 이미 보냈나 — 같은 날 두 번 보내지 않는다 */
export function 자동을이미보냈나(줄들, 날 = 오늘날짜()) {
  return (줄들 ?? []).some((줄) => String(줄).startsWith(날) && /자동 작성/.test(String(줄)));
}

/** 16시가 지났나 — 그 전에는 «안 낸 것»이 아니다 */
export function 낼때인가(이제 = new Date(), 선 = 16) {
  if (!(이제 instanceof Date) || Number.isNaN(이제.getTime())) return false;
  return 이제.getHours() >= 선;
}

/** 오늘 내 커밋만 추린다 — 제목에 「5번」이 든 것 */
export function 내커밋만(줄들) {
  return (줄들 ?? []).map((x) => String(x).trim()).filter((x) => x && /\[5번\]/.test(x));
}

/** 마커 이름에서 「무슨 일을 몇 시에 했나」를 뽑는다 */
export function 마커풀기(이름) {
  const m = String(이름 ?? '').match(/^(\d{4}-\d{2}-\d{2})-(\d{1,2})시-(.+)\.txt$/);
  return m ? { 날: m[1], 시: m[2], 일: m[3] } : null;
}

/** 오늘 찍힌 마커를 「일 → 시각들」로 모은다 */
export function 오늘마커(이름들, 날 = 오늘날짜()) {
  const 모음 = new Map();
  for (const n of 이름들 ?? []) {
    const p = 마커풀기(n);
    if (!p || p.날 !== 날) continue;
    if (!모음.has(p.일)) 모음.set(p.일, []);
    모음.get(p.일).push(p.시);
  }
  return 모음;
}

/**
 * 🔴🔴 [2026-10-22 13:1x · 5번] **내가 메모에 쓴 보고가 있으면 «그것»을 보낸다.**
 *
 * 왜 — 아래 `보고글()` 은 커밋 목록과 메일 목록을 모아 낸다. 그런데 사장님은
 *   그 꼴을 두고 직접 이르셨다 — 「**했다며? 대체 뭘 한거지? 신뢰가 안간다**」.
 *   「무엇을 했다」가 아니라 **밖에서 난 결과**(방문자 수·색인된 지면 수)를 적어야 한다.
 * ⇒ 내가 정해진 양식으로 세션간 메모에 올려 둔 보고가 있으면 그것을 그대로 보낸다.
 *   커밋 목록은 그것이 «없을 때»의 마지막 받침이다.
 *
 * ⛔ 오늘 날짜가 붙은 것만 집는다 — 어제 보고를 오늘 것으로 보내면 거짓이 된다.
 * ⛔ 머리만 있고 알맹이가 없으면 안 쓴다 — 빈 보고를 보내느니 커밋 목록이 낫다.
 */
export function 메모에쓴보고(글, 날) {
  const s = String(글 ?? '');
  const 머리 = `## [업무보고] 5번 총괄 · ${날}`;
  const 시작 = s.lastIndexOf(머리);
  if (시작 < 0) return null;
  const 뒤 = s.slice(시작);
  /* 다음 「## [」 머리까지가 내 보고다 */
  const 끝 = 뒤.indexOf('\n## [', 1);
  const 토막 = (끝 > 0 ? 뒤.slice(0, 끝) : 뒤).trim();
  return 토막.length > 200 ? 토막 : null;
}

/**
 * 보고 글월을 만든다 — 사실만. 인용한 줄이 어디인지 같이 돌려준다.
 *
 * 🔴🔴 [2026-11-11 · 사장님] **이 보고가 이틀 연속 통째로 안 나갔다.**
 *   「**업무보고-오후, 밤 왜 직접 보내는 보고가 요즘들어 한 건도 없잖아.
 *     제대로 된 장치가 아니니까 그러겠지**」
 *
 *   11-10 「걷어내」·「내려앉」 · 11-11 「멈춰 선」 — 셋 다 **내가 보낸 메일 제목**이다.
 *   이 자는 오늘 나간 메일 제목을 표에 «그대로» 옮겨 적는다. 그 제목에 금지어가 들면
 *   보고 전체가 관문에 걸려 멈췄고, 멈춘 것을 아무도 못 봤다.
 *   로그에는 「⛔ 이 자의 틀을 고쳐야 한다」고 찍혀 있었다 — 찍히기만 했다.
 *
 * ⛔ 「무엇이 있었나」를 옮긴 줄은 **내가 지금 쓰는 글이 아니라 인용**이다.
 *   인용을 고치면 기록이 거짓이 되고, 인용 때문에 보고를 버리면 보고가 사라진다.
 * ⇒ «인용한 줄»이 몇 번째인지 같이 돌려준다. 관문은 그 줄을 빼고 잰다.
 *   ⚠ 빼고 쟀다는 것을 **반드시 화면에 적는다.** 조용히 빼면 그것이 새 구멍이다.
 *
 * @returns { 글, 인용줄 }  인용줄은 0부터 센 줄 번호의 Set
 */
export function 보고글과인용(재료) {
  const { 날, 커밋, 메일, 마커, 자료 } = 재료 ?? {};
  const 줄 = [];
  const 인용줄 = new Set();
  /**
   * 앞서 있었던 것을 «그대로» 옮기는 줄 — 내가 짓는 글이 아니다.
   *
   * 🔴🔴 [2026-11-11 23:4x · 사장님 「업무보고 아직도 장치가 개판이군」]
   *   순한글 관문은 이 줄을 빼고 쟀는데 **말투 관문은 그대로 쟀다.** 커밋 제목은
   *   「…고친다」로 끝나는 평어라서, 보고가 「반말이 들었다」며 또 멈췄다.
   *   ⛔ 관문 하나만 고치면 나머지 관문이 같은 자리에서 또 막는다.
   * ⇒ 옮겨 적는 줄은 **`> ` 를 붙여 인용으로 적는다.** 두 관문이 다 그 표시를 본다.
   *   (check-보고말투.mjs — 「⛔ 인용(> )은 봐준다」)
   */
  const 인용 = (s) => { 인용줄.add(줄.length); 줄.push('> ' + s); };
  줄.push(`# [16시 업무보고] ${날} · 5번(총괄)`);
  줄.push('');
  줄.push('⚠ **이 보고는 자가 «자동으로» 썼습니다.** 제가 때맞춰 보고를 못 내서,');
  줄.push('빠뜨리지 않으려고 걸어 둔 자가 오늘 한 일을 사실만 모아 냈습니다.');
  줄.push('판단과 계획은 들어 있지 않습니다 — 그것은 제가 따로 올립니다.');
  줄.push('');
  줄.push('---');
  줄.push('');
  줄.push('## Ⅰ. 오늘 한 일 (커밋)');
  줄.push('');
  if (커밋?.length) for (const c of 커밋) 인용(`- ${c}`);
  else 줄.push('- (오늘 제 이름으로 남은 커밋이 없습니다)');
  줄.push('');
  줄.push('## Ⅱ. 오늘 보낸 메일');
  줄.push('');
  if (메일?.length) {
    줄.push('| 시각 | 제목 |');
    줄.push('|---|---|');
    for (const m of 메일) 인용(`| ${m.시각} | ${m.제목} |`);
  } else 줄.push('- (오늘 보낸 메일이 없습니다)');
  줄.push('');
  줄.push('## Ⅲ. 오늘 돌아간 고정업무');
  줄.push('');
  if (마커?.size) {
    줄.push('| 하는 일 | 몇 번 | 시각 |');
    줄.push('|---|---:|---|');
    for (const [일, 시각들] of 마커) 인용(`| ${일} | ${시각들.length} | ${시각들.join('·')}시 |`);
  } else 줄.push('- (오늘 찍힌 마커가 없습니다)');
  줄.push('');
  줄.push('## Ⅳ. 자료가 언제까지 차 있나');
  줄.push('');
  if (자료?.length) {
    줄.push('| 자료 | 마지막 | 며칠 됐나 |');
    줄.push('|---|---|---:|');
    for (const d of 자료) 인용(`| ${d.이름} | ${d.마지막} | ${d.며칠} |`);
  } else 줄.push('- (잴 자료 폴더를 못 찾았습니다)');
  줄.push('');
  줄.push('---');
  줄.push('');
  줄.push('5번(총괄) · 자동 작성');
  return { 글: 줄.join('\n'), 인용줄 };
}

