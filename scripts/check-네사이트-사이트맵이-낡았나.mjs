    const 넉줄 = ['a', 'b', 'c', 'd'].map((n, k) => [n, '2026-10-13T1' + k + ':00', '1개'].join(탭)).join(엔) + 엔;
    본다('🔴 네 줄을 적으면 네 사이트로 읽힌다 — 줄바꿈이 빠지면 하나만 읽힌다', 다시낸때읽기(넉줄).size === 4);
    본다('   마지막 줄도 읽힌다 (끝 줄바꿈에 안 먹힌다)', 다시낸때읽기(넉줄).has('d'));
