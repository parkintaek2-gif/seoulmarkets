#!/usr/bin/env node
/**
 * 적어둔다-그날수치.mjs — 그날 아침 수치를 «그날 아침에» 적어 둔다
 * ─────────────────────────────────────────────────────────────────────────────
 * [왜 이것이 있나 · 2026-11-11]
 *   11월 12일자 날씨를 데스킹하면서 「전날인 11일 아침 최저기온」을 넣으려는데
 *   **다시 잴 길이 없었다.** 기상청 동네예보 RSS 의 day0 은 시간이 갈수록 앞쪽 시각이
 *   떨어져 나간다 — 오전 10시에 받으면 10시부터 시작한다. 새벽 3~6시가 이미 없다.
 *   날씨누리 「오늘의 최저기온」 칸은 11시 발표 뒤에도 가로줄(-)로 비어 있었다.
 *   ⇒ 그날 아침 수치는 **그날 아침에 받아 두지 않으면 영영 없다.** 소급이 안 된다.
 *
 *   ⛔ 그래서 사람에게 「원고에 받은 시각을 같이 적어 주세요」라고 부탁하지 않는다.
 *      사람이 기억해서 지키는 구조를 만들지 않는다 — 기계가 매일 적어 둔다.
 *
 * [무엇을 적나] 동네예보의 day0(오늘) 값이다. **예보값이지 관측값이 아니다.**
 *   그래서 갈래 칸에 「예보」라고 박아 둔다. 기사에 쓸 때 관측으로 둔갑하지 않게.
 *
 * 쓰는 법
 *   node scripts/적어둔다-그날수치.mjs           오늘 것을 받아 적는다 (이미 있으면 그냥 둔다)
 *   node scripts/적어둔다-그날수치.mjs --본다     적힌 것을 뒤에서부터 보여 준다
 *   node scripts/적어둔다-그날수치.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { 잴곳, 받아온다, 덩이들, 하루추린다, 값 } from './잰다-내일날씨.mjs';

/** 아침을 적어도 되는 때인가 — day0 덩이에 새벽 시각이 아직 남아 있나
 *  🔴 day0 는 시간이 갈수록 앞쪽 시각이 떨어져 나간다. 오전 11시에 받으면 11시부터
 *     시작하고, 그것으로 낸 「최저」는 «아침 최저»가 아니라 «남은 시각 중 최저»다.
 *     그 수를 적어 두면 내일 데스크가 그것을 아침 최저로 읽는다. 적지 않는 편이 낫다. */
export const 아침선 = 6;
export function 아침이들었나(덩이목록) {
  const 시각 = 덩이목록
    .filter((d) => 값(d, 'day') === '0')
    .map((d) => Number(값(d, 'hour')))
    .filter((수) => Number.isFinite(수));
  if (!시각.length) return false;
  return Math.min(...시각) <= 아침선;
}

const 여기 = path.dirname(fileURLToPath(import.meta.url));
const 뿌리 = path.join(여기, '..');
export const 적는곳 = path.join(뿌리, 'docs', '날씨-날마다수치.tsv');

const 머리 = ['날짜', '도시', '아침최저', '낮최고', '최대강수확률', '하늘', '받은시각', '갈래'].join('\t');

export function 오늘날짜(때 = new Date()) {
  /* 이 PC 가 이미 한국시간이다 — toISOString() 을 쓰면 9시간이 밀린다 */
  const ㄷ = (수) => String(수).padStart(2, '0');
  return `${때.getFullYear()}-${ㄷ(때.getMonth() + 1)}-${ㄷ(때.getDate())}`;
}

export function 때찍기(때 = new Date()) {
  const ㄷ = (수) => String(수).padStart(2, '0');
  return `${오늘날짜(때)} ${ㄷ(때.getHours())}:${ㄷ(때.getMinutes())}`;
}

export function 읽는다(글) {
  const 줄 = 글.split(/\r?\n/).filter((줄) => 줄.trim() && !줄.startsWith('#'));
  if (줄.length && 줄[0].startsWith('날짜\t')) 줄.shift();
  return 줄.map((줄) => {
    const 칸 = 줄.split('\t');
    return { 날짜: 칸[0], 도시: 칸[1], 아침최저: 칸[2], 낮최고: 칸[3], 최대강수확률: 칸[4], 하늘: 칸[5], 받은시각: 칸[6], 갈래: 칸[7] };
  });
}

export function 이미있나(적힌것, 날짜, 도시) {
  return 적힌것.some((ㅈ) => ㅈ.날짜 === 날짜 && ㅈ.도시 === 도시);
}

async function 돈다() {
  const 볼까 = process.argv.includes('--본다');
  const 있던글 = fs.existsSync(적는곳) ? fs.readFileSync(적는곳, 'utf8') : '';
  const 적힌것 = 읽는다(있던글);

  if (볼까) {
    const 뒤 = 적힌것.slice(-20);
    if (!뒤.length) { console.log('아직 적힌 것이 없다.'); return; }
    for (const ㅈ of 뒤) console.log(`${ㅈ.날짜}  ${ㅈ.도시}  아침 ${ㅈ.아침최저}도 · 낮 ${ㅈ.낮최고}도 · 비 ${ㅈ.최대강수확률}% · ${ㅈ.하늘}  (${ㅈ.받은시각} ${ㅈ.갈래})`);
    return;
  }

  const 날짜 = 오늘날짜();
  const 때 = 때찍기();
  const 더할것 = [];
  const 건너뛴것 = [];
  const 못받은것 = [];

  for (const [이름, 코드] of 잴곳) {
    if (이미있나(적힌것, 날짜, 이름)) { 건너뛴것.push(이름); continue; }
    let 추린것 = null;
    let 덩이 = null;
    try {
      덩이 = 덩이들(await 받아온다(코드));
      추린것 = 하루추린다(덩이, 0);
    } catch (오류) {
      못받은것.push(`${이름}(${오류.message})`);
      continue;
    }
    if (!추린것) { 못받은것.push(`${이름}(day0 덩이가 없다)`); continue; }
    if (!아침이들었나(덩이)) {
      못받은것.push(`${이름}(새벽 시각이 이미 떨어져 나갔다 — 남은 시각으로 낸 수는 아침 최저가 아니다)`);
      continue;
    }
    /* ⛔ 못 받은 칸을 0 으로 채우지 않는다 — 빈 칸으로 둔다 */
    더할것.push([날짜, 이름, 추린것.최저 ?? '', 추린것.최고 ?? '', 추린것.최대강수확률 ?? '', 추린것.하늘 ?? '', 때, '예보'].join('\t'));
  }

  if (더할것.length) {
    const 쓸것 = (있던글 ? (있던글.endsWith('\n') ? 있던글 : `${있던글}\n`) : `${머리}\n`) + `${더할것.join('\n')}\n`;
    fs.writeFileSync(적는곳, 쓸것, 'utf8');
  }

  console.log(`[날씨 그날수치] ${날짜} ${때}`);
  console.log(`  적었다 ${더할것.length}곳 · 이미 있어 건너뛴 것 ${건너뛴것.length}곳${건너뛴것.length ? ` (${건너뛴것.join(', ')})` : ''}`);
  if (못받은것.length) console.log(`  ⬜ 못 받았다 — ${못받은것.join(', ')}`);
  for (const 줄 of 더할것) {
    const 칸 = 줄.split('\t');
    console.log(`     ${칸[1]}  아침 ${칸[2] || '?'}도 · 낮 ${칸[3] || '?'}도 · 비 ${칸[4] || '?'}% · ${칸[5] || '?'}`);
  }
  if (못받은것.length && !더할것.length) process.exitCode = 1;
}

export function 자가시험() {
  const 잰것 = [];
  const 본다 = (이름, 참인가) => { 잰것.push([이름, 참인가]); };

  본다('날짜는 한국시간 그대로다', 오늘날짜(new Date(2026, 10, 11, 1, 30)) === '2026-11-11');
  본다('때찍기는 분까지 적는다', 때찍기(new Date(2026, 10, 11, 2, 40)) === '2026-11-11 02:40');

  const 글 = `${머리}\n2026-11-11\t청주\t0\t15\t20\t맑음\t2026-11-11 02:40\t예보\n`;
  const 읽힌것 = 읽는다(글);
  본다('머리줄은 자료로 세지 않는다', 읽힌것.length === 1);
  본다('칸을 제자리로 읽는다', 읽힌것[0].도시 === '청주' && 읽힌것[0].아침최저 === '0' && 읽힌것[0].갈래 === '예보');
  본다('같은 날 같은 도시는 이미 있다고 센다', 이미있나(읽힌것, '2026-11-11', '청주') === true);
  본다('다른 날은 없다고 센다', 이미있나(읽힌것, '2026-11-12', '청주') === false);
  본다('다른 도시는 없다고 센다', 이미있나(읽힌것, '2026-11-11', '대전') === false);
  본다('주석줄은 건너뛴다', 읽는다(`# 메모\n${글}`).length === 1);
  본다('빈 글은 빈 목록이다', 읽는다('').length === 0);

  const 덩이 = (날, 시) => `<day>${날}</day><hour>${시}</hour><temp>5</temp>`;
  본다('새벽이 남아 있으면 적어도 된다', 아침이들었나([덩이(0, '3'), 덩이(0, '12')]) === true);
  본다('6시까지는 아침으로 센다', 아침이들었나([덩이(0, '6'), 덩이(0, '20')]) === true);
  본다('7시부터 시작하면 적지 않는다', 아침이들었나([덩이(0, '7'), 덩이(0, '20')]) === false);
  본다('11시부터 시작하면 적지 않는다', 아침이들었나([덩이(0, '11'), 덩이(0, '24')]) === false);
  본다('내일 새벽은 오늘 아침이 아니다', 아침이들었나([덩이(1, '3'), 덩이(0, '15')]) === false);
  본다('day0 가 없으면 적지 않는다', 아침이들었나([덩이(1, '3')]) === false);

  const 깨진것 = 잰것.filter(([, 참인가]) => !참인가);
  for (const [이름, 참인가] of 잰것) console.log(`  ${참인가 ? '✅' : '🔴'} ${이름}`);
  console.log(`\n${잰것.length - 깨진것.length}/${잰것.length} 통과`);
  return 깨진것.length === 0;
}

if (process.argv.includes('--자가시험')) {
  process.exitCode = 자가시험() ? 0 : 1;
} else {
  await 돈다();
}
