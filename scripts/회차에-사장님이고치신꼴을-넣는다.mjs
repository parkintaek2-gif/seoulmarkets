/**
 * 아침에 잘못 넣은 「1,200자 바닥」 절을 통째로 걷어낸다.
 * ⛔ 자국 한 줄만 지우면 나머지 본문이 남아 회차가 그대로 믿는다 — 절 «전체»를 걷는다.
 */
export function 걷어내기(글) {
  let s = String(글 ?? '');
  for (const 머리 of 걷어낼머리들) {
    const 시작 = s.indexOf(머리);
    if (시작 < 0) continue;
    /* 다음 「### 」 머리까지가 그 절이다.
       ⚠ `#### ` 는 안 걸린다 — `###` 뒤가 공백이어야 머리다 */
    const 뒤 = s.slice(시작 + 5);
    const 끝 = 뒤.indexOf('\n### ');
    s = s.slice(0, 시작) + (끝 >= 0 ? 뒤.slice(끝 + 1) : '');
  }
  return s.replace(/\n{4,}/g, '\n\n\n');
}

/** 지침을 고친다 → {글, 바뀌었나, 까닭} */
export function 고치기(옛글) {
  const s0 = String(옛글 ?? '');
  if (!s0.trim()) return { 글: s0, 바뀌었나: false, 까닭: '빈 글이다 — 손대면 안 된다' };
  /* 🔴 [2026-10-22 저녁] **새 절이 이미 들어 있으면 손대지 않는다.**
     걷어낼머리들에 새 절의 머리도 들어 있어서, 이 줄이 없으면 돌릴 때마다
     걷었다 넣었다를 되풀이한다 — 자가시험이 잡았다. */
  if (s0.includes(자국)) return { 글: s0, 바뀌었나: false, 까닭: '이미 들어 있다' };
  const 걷었나 = s0.includes(걷어낼자국);
  const s = 걷어내기(s0);
  if (s.includes(자국)) {
    return { 글: s, 바뀌었나: 걷었나, 까닭: 걷었나 ? '옛 절만 걷어냈다' : '이미 들어 있다' };
  }
  const 머리 = 끼울머리.find((h) => s.includes(h));
  const 꼬리 = 걷었나 ? ' (옛 절은 걷어냈다)' : '';
  if (머리) {
    return { 글: s.replace(머리, 새절.trim() + '\n\n' + 머리), 바뀌었나: true, 까닭: `「${머리}」 앞에 끼웠다${꼬리}` };
  }
  return { 글: s.trimEnd() + '\n\n' + 새절.trim() + '\n', 바뀌었나: true, 까닭: `끼울 머리가 없어 맨 끝에 붙였다${꼬리}` };
}

