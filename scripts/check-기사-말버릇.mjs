export function 찾기(글) {
  const s = String(글 ?? '');
  const 걸린것 = [];
  for (const r of 말버릇) {
    for (const m of s.matchAll(r.꼴)) {
      const 둘 = 둘레(s, m.index, 24);
      /* 🔴 [2026-10-04] KLifeMap 에 돌렸더니 «지지 丑(축)»이 통째로 걸렸다 —
         「을축(乙丑) 일주 — 일간 을이 축을 딛고 선 자리」. 명리에서 축은 열두 지지다.
         ⛔ 헛것이 늘면 진짜가 묻힌다. 둘레에 간지 한자가 있으면 그 축은 지지다. */
      if (m[0].trim() === '축' && /[丑子寅卯辰巳午未申酉戌亥]|일주|지지|간지/.test(둘)) continue;
      걸린것.push({ 말: m[0].trim(), 대신: r.대신, 언제: r.언제, 어디: 둘 });
    }
  }
  for (const r of 잦으면걸리는말) {
    const 수 = [...s.matchAll(r.꼴)].length;
    if (수 > r.한도) {
      걸린것.push({ 말: `${r.꼴.source} ×${수}`, 대신: r.대신, 언제: '잦다', 어디: `${수}번 나온다` });
    }
  }
  return 걸린것;
}

/** 걸린 자리의 앞뒤를 보여 준다 — 어디를 고칠지 바로 알게 */
export function 둘레(글, 자리, 폭 = 18) {
  const s = String(글 ?? '');
  const a = Math.max(0, 자리 - 폭);
  const b = Math.min(s.length, 자리 + 폭);
  return `…${s.slice(a, b).replace(/\n/g, ' ')}…`;
}

