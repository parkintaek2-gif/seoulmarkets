/**
 * boss-orders.test.mjs — `boss-orders.mjs` 자가시험.
 * 쓰는 법  node scripts/lib/boss-orders.test.mjs
 *
 * ⛔ 여기서 제일 값이 나가는 것은 ⑨⑩ 이다 — **원문을 자르면 뜻이 바뀐다.**
 *   「업무분량의 50% 이상을…」이 「업무분량의 50%…」가 되면 다른 지시가 된다.
 */
import { 줄읽기, 지시들, 한줄, 브리핑, 대장길, 살았나, 모르는상태, 시각칸인가 } from './boss-orders.mjs';
import fs from 'node:fs';

let 셈 = 0; let 실패 = 0;
const 검 = (말, 참) => { 셈 += 1; if (!참) { 실패 += 1; console.log('🔴', 말); } };

const 줄 = (a) => a.join('\t');

검('① 지시 한 줄을 읽는다',
  줄읽기(줄(['2026-08-24', '상시', '산다', '올인해라', '이것이 바뀐다'])).원문 === '올인해라');
검('② 주석은 지시가 아니다', 줄읽기('#\t설명') === null);
검('③ 머리줄은 지시가 아니다', 줄읽기(줄(['날짜', '갈래', '상태', '원문', '바뀌는것'])) === null);
검('④ 빈 줄은 지시가 아니다', 줄읽기('') === null && 줄읽기('   ') === null);
검('⑤ 날짜 꼴이 아니면 안 읽는다', 줄읽기(줄(['어제', '상시', '산다', 'x', 'y'])) === null);
검('⑥ 칸이 모자라면 안 읽는다', 줄읽기(줄(['2026-08-24', '상시', '산다'])) === null);

const 가짜 = [
  줄(['2026-08-24', '상시', '산다', '살아 있는 것', 'A']),
  줄(['2026-08-25', '상시', '취소', '취소된 것', 'B']),
  줄(['2026-08-26', '목표', '산다', '목표인 것', 'C']),
].join('\n');
const 다 = 지시들('아무거나', () => 가짜);
검('⑦ 「산다」만 낸다 — 취소된 것은 안 보인다', 다.length === 2);
검('⑧ ⚠ 취소된 것은 «지운» 것이 아니라 «안 보이는» 것이다 — 파일에는 남는다',
  가짜.includes('취소된 것'));

/* 🔴🔴 원문을 자르지 않는다 */
const 긴것 = '업무분량의 50% 이상을 방문자늘리기에 써라';
const 한 = 한줄(0, [{ 날짜: '2026-08-26', 갈래: '상시', 상태: '산다', 원문: 긴것, 바뀌는것: '' }]);
검('⑨ 🔴 상태줄이 원문을 «통째로» 낸다 — 자르면 뜻이 바뀐다', 한.includes(긴것));
검('⑩ 몇 번째인지 알려 준다 — 다 보고 있는지 알 수 있게', /^\[1\/1\]/.test(한));

검('⑪ 부를 때마다 «다음» 것이 나온다', (() => {
  const x = [0, 1, 2].map((t) => 한줄(t, 다));
  return new Set(x).size === 2;   /* 둘뿐이라 셋째는 첫째로 돌아온다 */
})());
검('⑫ 음수·큰 수를 넣어도 안 죽는다', 한줄(-7, 다).length > 0 && 한줄(999999, 다).length > 0);

검('⑬ 🔴 못 읽으면 «없다고» 말한다 — 조용하면 고장과 구별이 안 된다',
  한줄(0, []).includes('못 읽었다'));
검('⑭ 🔴 파일을 못 열어도 빈 목록을 낸다 — 훅을 죽이지 않는다',
  지시들('없는파일', () => { throw new Error('없다'); }).length === 0);

const 브 = 브리핑(다);
검('⑮ 브리핑에 살아 있는 수가 있다', 브[0].includes('2건'));
검('⑯ 브리핑에 원문이 통째로 있다', 브.join('\n').includes('살아 있는 것'));
검('⑰ 브리핑에 취소된 것이 없다', !브.join('\n').includes('취소된 것'));
검('⑱ 목표가 상시보다 먼저 나온다', (() => {
  const s = 브.join('\n');
  return s.indexOf('수로 정해진 것') < s.indexOf('늘 지키는 것');
})());
검('⑲ 못 읽었을 때도 브리핑이 한 줄은 낸다', 브리핑([]).length === 1);

/* ⚠ 실물도 한 번 본다 — 자가시험이 통과해도 대장이 비어 있으면 뜻이 없다 */
if (fs.existsSync(대장길)) {
  const 실 = 지시들();
  검('⑳ ⭐ 실제 대장이 비어 있지 않다', 실.length > 0);
  검('㉑ ⭐ 실제 대장의 원문이 다 차 있다', 실.every((o) => o.원문.length > 3));
} else {
  console.log('⬜ 대장 파일이 없어 ⑳㉑ 은 못 쟀다');
}

/*
 * 🔴🔴 [2026-08-29] **같은 뜻의 다른 말이 «조용히» 걸러지고 있었다.**
 *   상태가 「산다」인 줄만 내고 있었는데 파일에는 「살아있음」으로 적힌 줄이 **넷** 있었다.
 *   그 넷이 상태줄에도 창에도 **한 번도 안 나왔다** — 하나는 사장님의
 *   「영상이 6번이 아니라, 텍스트가 6번이야」였다. 내가 그 지시를 오래 못 보고 있었다.
 * ⛔ 다시는 조용히 안 버리게 «수로» 못박는다.
 */
검('㉒ 🔴 「살아있음」도 산 것으로 센다', 살았나('살아있음') === true);
검('㉓ 「산다」는 당연히 산 것이다', 살았나('산다') === true);
검('㉔ 「취소」는 죽은 것이다', 살았나('취소') === false);
검('㉕ ⛔ 모르는 말은 살았다고도 죽었다고도 안 한다 — null', 살았나('알수없음') === null);
검('㉖ ⛔ 빈 것도 안 터진다', 살았나(undefined) === null && 살았나('') === null);

/* ⭐ 조용히 안 버린다 — 「살아있음」 줄이 «실제로» 목록에 실리는지 잰다 */
{
  const 가짜 = ['2026-08-29\t몫\t살아있음\t가나다\t라마바', '2026-08-29\t몫\t산다\t사아자\t차카타', '2026-08-29\t몫\t취소\t파하가\t나다라'].join('\n');
  const r = 지시들('x', () => 가짜);
  검('㉗ ⭐ 「살아있음」 줄이 목록에 «실린다»', r.some((o) => o.원문 === '가나다'));
  검('㉘ 「산다」 줄도 실린다', r.some((o) => o.원문 === '사아자'));
  검('㉙ ⛔ 「취소」 줄은 안 실린다', !r.some((o) => o.원문 === '파하가'));
}

/* ⭐ 모르는 상태는 «이름으로» 알려 준다 — 조용히 넘기지 않는다 */
{
  const 가짜 = '2026-08-29\t몫\t???\t마바사\t아자차';
  const u = 모르는상태('x', () => 가짜);
  검('㉚ ⭐ 모르는 상태를 세어서 알려 준다', u.length === 1 && u[0].원문 === '마바사');
  검('㉛ ⚠ 그래도 목록에서 «버리지는» 않는다 — 못 보여 주는 것이 더 나쁘다',
    지시들('x', () => 가짜).length === 1);
}

/* ⭐ 진짜 대장에 모르는 상태가 남아 있지 않은지도 본다 */
if (fs.existsSync(대장길)) {
  검('㉜ ⭐ 실제 대장에 모르는 상태로 적힌 줄이 없다', 모르는상태().length === 0);
}


/* 🔴🔴 [2026-11-11] 쓰는 쪽이 칸 짜임을 바꿨는데 읽는 쪽이 안 따라가,
   사장님이 10월 23일부터 이르신 스무 가지가 새 창 목록에서 통째로 빠져 있었다. */
{
  const 새꼴 = '2026-10-23\t14:3x\t날씨기사 지역 차례\t「청주 날씨를 먼저 보도」\t청주를 앞에 둔다';
  const o = 줄읽기(새꼴);
  검('㉝ 🔴 새 꼴(날짜·시각·제목·원문)을 읽는다', o !== null && o.원문.includes('청주'));
  검('㉞ 🔴 새 꼴은 상태 칸이 없다 — 「산다」로 본다', o.상태 === '산다');
  검('㉟ 🔴 새 꼴은 「늘 지키는 것」으로 본다', o.갈래 === '상시');
  검('㊱ 🔴 제목을 따로 집는다', o.제목 === '날씨기사 지역 차례');
  /* ⚠ 분을 x 로 가려 적은 것이 많다 — 그것도 시각이다 */
  검('㊲ 🔴 분을 x 로 가린 시각도 시각이다', 시각칸인가('14:3x') && 시각칸인가('08:5x'));
  검('㊳ 🔴 또렷한 시각도 시각이다', 시각칸인가('23:10') && 시각칸인가('9:05'));
  검('㊴ ⛔ 갈래 이름을 시각으로 보지 않는다',
    !시각칸인가('상시') && !시각칸인가('목표') && !시각칸인가(''));
  /* ⛔ 옛 꼴이 깨지면 안 된다 — 백예순 줄이 그 꼴이다 */
  const 옛 = 줄읽기('2026-08-22\t상시\t산다\t스스로 할 일을 찾아라\t확인만 했습니다로 넘기지 않는다');
  검('㊵ ⛔ 옛 꼴도 그대로 읽는다', 옛.갈래 === '상시' && 옛.상태 === '산다' && 옛.원문.includes('스스로'));
  /* ⭐ 진짜 대장에서 10-23 뒤 것이 하나도 안 빠지는지 */
  if (fs.existsSync(대장길)) {
    const 뒤엣것 = 지시들().filter((x) => x.날짜 >= '2026-10-23');
    검('㊶ ⭐ 10-23 뒤 지시가 전부 「늘 지키는 것」으로 들어온다',
      뒤엣것.length >= 20 && 뒤엣것.every((x) => x.갈래 === '상시'));
  }
}

console.log(실패 ? `❌ boss-orders 자가시험 ${실패}개 실패 (${셈})` : `✅ boss-orders 자가시험 통과 (${셈})`);
process.exitCode = 실패 ? 1 : 0;
