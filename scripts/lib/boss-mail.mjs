/* ──────────────────────────────────────────────────────────────────────
   🔴🔴 [2026-11-13 · 5번] **오타 주소 확인 단계**

   2026-11-12 에 기사 편지 한 통이 `parintaek2@gmail.com` 으로 나갔다 —
   `parkintaek2@gmail.com` 에서 **k 한 글자가 빠진** 주소다.
   꼴은 멀쩡한 메일 주소라 「받을 만한 주소인가」 검사를 그대로 통과했고,
   받는 쪽이 없으니 아무 데도 안 닿았는데 우리 기록에는 「보냈다」로 남았다.

   ⛔ 한 글자 차이는 사람 눈으로 못 막는다. **글자 거리로 잰다.**
   ⇒ 전에 실제로 보낸 적 있는 주소와 «두 글자 이내»로 닮았는데
     그 주소 자체는 **한 번도 쓴 적이 없으면** 오타로 보고 세운다.
   ⚠ 아주 새로운 주소(거리가 먼 것)는 막지 않는다 — 새 거래처가 막히면 안 된다.
   ────────────────────────────────────────────────────────────────────── */

/** 두 글자열을 같게 만드는 데 드는 최소 손질 수 (레벤슈타인) */
export function 글자거리(a, b) {
  const x = String(a ?? '');
  const y = String(b ?? '');
  if (x === y) return 0;
  if (!x.length || !y.length) return Math.max(x.length, y.length);
  let 앞줄 = Array.from({ length: y.length + 1 }, (_, i) => i);
  for (let i = 1; i <= x.length; i++) {
    const 이줄 = [i];
    for (let j = 1; j <= y.length; j++) {
      이줄[j] = Math.min(
        앞줄[j] + 1,
        이줄[j - 1] + 1,
        앞줄[j - 1] + (x[i - 1] === y[j - 1] ? 0 : 1),
      );
    }
    앞줄 = 이줄;
  }
  return 앞줄[y.length];
}

/**
 * 🔴🔴 [2026-11-13 · 두 번째 판] **「전에 보낸 적 있다」만으로는 못 거른다.**
 *   처음 만든 판이 바로 그 오타 주소를 통과시켰다 — 11-12 에 실제로 한 번 나갔으니
 *   대장에 「써 본 주소」로 남아 있었던 것이다. **샌 자국이 면죄부가 됐다.**
 *   ⇒ 횟수로 가른다. 여러 번 써 온 주소만 「든든한 주소」로 치고,
 *     한두 번뿐인 주소는 그 자체가 오타일 수 있으니 견주는 쪽에 넣지 않는다.
 */
export const 든든한횟수 = 3;

/**
 * 오타 주소인가 — 든든한 주소와 닮았는데 정작 자기는 거의 안 써 본 주소일 때 참.
 * @param {string} 받는곳 이번에 보내려는 주소
 * @param {string[]} 보낸자국 전에 보낸 받는 주소들 (같은 주소가 여러 번 들어 있어도 된다)
 * @returns {{의심:boolean, 닮은것?:string, 거리?:number, 까닭?:string}}
 */
export function 오타의심(받는곳, 보낸자국 = []) {
  const 이번 = String(받는곳 ?? '').trim().toLowerCase();
  if (!이번) return { 의심: false };

  /* ① 없는 줄 아는 주소는 바로 세운다 — 자국이 있든 없든 */
  if ([...옛주소, ...없는주소].map((a) => a.toLowerCase()).includes(이번)) {
    return { 의심: true, 닮은것: 사장님메일, 거리: 글자거리(이번, 사장님메일), 까닭: '안 쓰기로 한 주소다' };
  }

  /* 🔴 [2026-11-13] **우리 집 주소는 견주지 않는다.**
     유닛 주소는 u1@·u2@·u5@ 처럼 «한 글자»로 갈린다 — 그대로 두면 u1 로 보내는 것이
     u5 의 오타로 읽혀 막힌다(실제로 대장의 u1 두 통이 그렇게 걸렸다).
     우리 도메인은 우리가 쥐고 있으니 오타여도 바로 드러난다. 도메인이 다르면 그대로 잰다. */
  if (/@klifedesign\.net$/i.test(이번)) return { 의심: false, 까닭: '우리 도메인이다' };

  const 셈 = new Map();
  for (const a of 보낸자국) {
    const k = String(a ?? '').trim().toLowerCase();
    if (!k) continue;
    셈.set(k, (셈.get(k) ?? 0) + 1);
  }
  /* ② 여러 번 써 온 주소만 견주는 쪽에 넣는다. 사장님 주소는 늘 든든한 것으로 친다 */
  const 든든 = [...new Set([사장님메일.toLowerCase(),
    ...[...셈.entries()].filter(([, n]) => n >= 든든한횟수).map(([a]) => a)])];
  if (든든.includes(이번)) return { 의심: false, 까닭: '든든한 주소다' };

  let 닮은것 = null;
  let 가장가까움 = Infinity;
  for (const a of 든든) {
    const d = 글자거리(이번, a);
    if (d < 가장가까움) { 가장가까움 = d; 닮은것 = a; }
  }
  if (닮은것 && 가장가까움 > 0 && 가장가까움 <= 2) {
    return { 의심: true, 닮은것, 거리: 가장가까움, 까닭: `든든한 주소와 ${가장가까움}글자 차이다` };
  }
  return { 의심: false, 닮은것, 거리: 가장가까움 };
}
