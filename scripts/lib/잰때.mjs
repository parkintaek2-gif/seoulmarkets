/**
 * 잰때.mjs — **잰 시각을 한 꼴로 적는다.**
 *
 * ── 🔴🔴 왜 생겼나 (2026-11-14 · 5번) ────────────────────────────────────
 * 영문 지면 `idols-on-netflix` 꼬리말에 이렇게 나가고 있었다 —
 *
 * ```
 * Counted 2026. 10. 4. 오후 6:37:05.
 * ```
 *
 * 「오후」는 한국어다. **영어권 손님에게 내는 지면이다**(사장님 2026-08-05 —
 * 「네가 할 일은 영어뉴스+데이터가공이다. k팝 등에 관심이 많은 해외대상이다」).
 * 까닭은 `new Date().toLocaleString('ko-KR')` 하나였고, **같은 줄이 빌더 26곳**에 있었다.
 *
 * ⭐ 벌을 늘리지 말고 **정본을 하나 두고 불러다 쓴다.** 베껴 적으면 한 곳을 고쳐도
 *   나머지 스물다섯이 그대로 남는다.
 *
 * ── 어떤 꼴로 적나 ──────────────────────────────────────────────────────
 * ```
 * 2026-10-04 18:37 KST
 * ```
 * · 영어권이 읽어도 뜻이 흔들리지 않는다 (AM/PM·달 이름·자리 순서가 나라마다 다르다)
 * · 「KST」를 적어 **어느 나라 시계인지**를 숨기지 않는다
 * · 기계가 다시 읽기 쉽다 — 앞 열 자가 그대로 날짜다
 *
 * ⛔ `toISOString()` 을 쓰지 않는다. UTC 라 아홉 시간이 어긋난다 (CLAUDE.md).
 * ⛔ 아홉 시간을 «더하지»도 않는다. 이 PC 가 이미 KST 다 — 더하면 두 번 더한 값이 된다.
 *
 * 쓰는 법   node scripts/lib/잰때.mjs --자가시험
 */

/** 두 자리로 맞춘다 */
const 두자리 = (n) => String(n).padStart(2, '0');

/**
 * 잰 시각 — `2026-10-04 18:37 KST`.
 * @param {Date} [때] 안 주면 지금. ⚠ 이 PC 가 KST 다. 시차를 손으로 더하지 않는다.
 */
export function 잰때문자(때 = new Date()) {
  /* ⛔ null 을 `new Date(null)` 에 넘기면 **1970년**이 나온다. 빈 것은 빈 것으로 둔다 */
  if (때 === null || 때 === '') return '';
  const d = 때 instanceof Date ? 때 : new Date(때);
  if (Number.isNaN(d.getTime())) return '';      /* ⛔ 못 읽은 것을 아무 값으로 채우지 않는다 */
  return `${d.getFullYear()}-${두자리(d.getMonth() + 1)}-${두자리(d.getDate())} `
    + `${두자리(d.getHours())}:${두자리(d.getMinutes())} KST`;
}

/** 날짜만 — `2026-10-04` */
export function 잰날문자(때 = new Date()) {
  const s = 잰때문자(때);
  return s ? s.slice(0, 10) : '';
}

/**
 * 옛 한국어 꼴(`2026. 10. 4. 오후 6:37:05`)을 새 꼴로 옮긴다.
 * 이미 쌓인 자료 파일을 고칠 때 쓴다. ⛔ 못 알아보면 빈 글을 준다 — 지어내지 않는다.
 */
export function 옛꼴을새꼴로(글) {
  const t = String(글 ?? '').trim();
  if (/^\d{4}-\d{2}-\d{2} \d{2}:\d{2} KST$/.test(t)) return t;   /* 이미 새 꼴이다 */
  const m = /^(\d{4})\.\s*(\d{1,2})\.\s*(\d{1,2})\.\s*(오전|오후)\s*(\d{1,2}):(\d{2})/.exec(t);
  if (!m) return '';
  let 시 = Number(m[5]) % 12;
  if (m[4] === '오후') 시 += 12;
  return `${m[1]}-${두자리(m[2])}-${두자리(m[3])} ${두자리(시)}:${m[6]} KST`;
}

/* ── 자가시험 ──────────────────────────────────────────────────────── */
const 내가진입점 = (process.argv[1] || '').replace(/\\/g, '/').endsWith('/lib/잰때.mjs');
if (내가진입점 && (process.argv.includes('--자가시험') || process.argv.includes('--selftest'))) {
  let 통과 = 0; const 진 = [];
  const 참 = (이름, 값) => { if (값) 통과 += 1; else 진.push(이름); };

  const 때 = new Date(2026, 9, 4, 18, 37, 5);      /* 2026-10-04 18:37:05 */
  참('꼴이 맞다', 잰때문자(때) === '2026-10-04 18:37 KST');
  참('한 자리 달·날을 두 자리로 맞춘다', 잰때문자(new Date(2026, 0, 2, 3, 4)) === '2026-01-02 03:04 KST');
  참('날짜만도 준다', 잰날문자(때) === '2026-10-04');
  참('🔴 ⛔ 한국어가 섞이지 않는다', !/[가-힣]/.test(잰때문자(때)));
  참('🔴 ⛔ 오전·오후를 쓰지 않는다 — 열두 시 넘는 수로 적는다',
    잰때문자(new Date(2026, 0, 1, 13, 0)).includes('13:00'));
  참('🔴 ⛔ 못 읽는 값은 빈 글이다 — 지어내지 않는다', 잰때문자('그냥 글') === '');
  참('KST 를 숨기지 않는다', 잰때문자(때).endsWith('KST'));

  참('옛 꼴을 옮긴다 (오후)', 옛꼴을새꼴로('2026. 10. 4. 오후 6:37:05') === '2026-10-04 18:37 KST');
  참('옛 꼴을 옮긴다 (오전)', 옛꼴을새꼴로('2026. 1. 2. 오전 9:05:00') === '2026-01-02 09:05 KST');
  참('🔴 낮 열두 시는 12 다', 옛꼴을새꼴로('2026. 5. 5. 오후 12:30:00') === '2026-05-05 12:30 KST');
  참('🔴 밤 열두 시는 00 이다', 옛꼴을새꼴로('2026. 5. 5. 오전 12:30:00') === '2026-05-05 00:30 KST');
  참('이미 새 꼴이면 그대로 둔다', 옛꼴을새꼴로('2026-10-04 18:37 KST') === '2026-10-04 18:37 KST');
  참('🔴 못 알아보면 빈 글이다', 옛꼴을새꼴로('언젠가') === '');
  참('⛔ 빈 값에도 안 죽는다', 옛꼴을새꼴로(null) === '' && 잰때문자(null) === '');

  /* ⛔ 이 파일이 toISOString 이나 아홉 시간 더하기로 돌아가지 않는지 스스로 지킨다 */
  참('⛔ toISOString 을 쓰지 않는다', !잰때문자.toString().includes('toISOString'));

  console.log(진.length ? `🔴 ${진.length}개 실패 (통과 ${통과})` : `✅ 자가시험 ${통과} 통과`);
  for (const x of 진) console.log('   🔴 ' + x);
  process.exit(진.length ? 1 : 0);
}
