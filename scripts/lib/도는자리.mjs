/** 그 자리가 지금 도나 */
export function 도나(자리) {
  return 도는자리.includes(String(자리 ?? '').trim());
}

/** 목록에서 도는 자리만 남긴다 — «차례»는 그대로 두고 없는 자리만 뺀다.
 *  사장님 규칙 「중간에 빠진 세션이 있으면 그 다음 세션이 이어받는다」(2026-09-13) 가 이것이다. */
export function 살아있는것만(목록) {
  return (Array.isArray(목록) ? 목록 : []).filter((자리) => 도나(자리));
}

/** 자리 이름을 고르게 만든다 — '5', 5, '5번' 을 다 '5번' 으로 */
export function 자리이름(값) {
  const 글 = String(값 ?? '').trim();
  if (!글) return null;
  const m = 글.match(/^(\d+)\s*번?$/);
  return m ? m[1] + '번' : 글;
}
