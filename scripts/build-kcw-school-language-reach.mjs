#!/usr/bin/env node
/**
 * build-kcw-school-language-reach.mjs — **학교마다, 그 학교 사람이 몇 개 언어판에 실렸나.**
 * (5번 · 2026-09-04)
 *
 * ── 왜 이 자가 생겼나 ────────────────────────────────────────
 * `check-visitor-walk.mjs` 가 「본문에 나가는 길이 하나도 없는 기사 9편」을 잡아 줬다.
 * 그 아홉이 «어느 지면으로 가야 하나»를 재 보니, 여섯 편은 **갈 지면이 아예 없었다** —
 * 기사가 내세운 수가 어느 지면 표 칸에도 없었다.
 *
 * 그 가운데 하나가 `arts-high-school-beats-sky-universities` 다. 머리글이 이렇게 말한다 —
 *   「School of Performing Arts Seoul put **58.4%** of its **125** alumni into ten or more
 *    language editions. Yonsei managed **16.0%** of **75**.」
 * ⛔ 그런데 `/school` 지면은 «학교 이름과 사람 수»만 싣고 있었다. 58.4 도 16.0 도 없었다.
 *   ⇒ 카드마다 박는 「every figure has a table behind it」이 이 기사에서 거짓이었다.
 *
 * ⭐ 그리고 자료는 **8월부터 있었다**(`src/data/kcw-school-pipeline.json`, 학교 1,519곳).
 *   못 잰 것이 아니라 «싣지 않은 것»이었다.
 *
 * ── ⛔ 이 자가 지키는 것 ─────────────────────────────────────
 * ⛔ **사람이 적은 학교의 %를 그냥 내지 않는다.** 다섯 명 가운데 셋이면 60% 인데, 그 60% 는
 *   「이 학교가 낫다」가 아니라 「셋이 그랬다」다. 그래서 **윌슨 구간을 같이 낸다.**
 *   ⭐ 이것이 강령의 「평균이 아니라 분포」이고, 셋째 자리(리스크관리)가 하는 일이다.
 * ⛔ **순위표로 만들지 않는다.** 몫이 높은 순으로 세우면 그 자체가 「좋은 학교」로 읽힌다.
 *   구간이 겹치는 것끼리는 «가를 수 없다»고 적는다.
 * ⛔ 못 잰 사람을 0 으로 채우지 않는다. 언어판을 못 잰 사람 수를 학교마다 따로 적는다.
 * ⚠ 「언어판이 많다」는 «널리 읽힌다»가 아니다. 문서가 여러 언어에 있다는 것뿐이다.
 *
 * 쓰는 법  node scripts/build-kcw-school-language-reach.mjs --자가시험
 *          node scripts/build-kcw-school-language-reach.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { 윌슨구간, 겹치나 } from './lib/noise-test.mjs';
/* 🔴 [2026-11-14] 영문 지면에 「오후」가 나갔다 — 잰 시각은 한 꼴로 적는다 */
import { 잰때문자 } from './lib/잰때.mjs';

const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const 원자료 = path.join(뿌리, 'src/data/kcw-school-pipeline.json');
const 낼자료 = path.join(뿌리, 'src/data/kcw-school-language-reach.json');

/**
 * 몫을 낼 최소 인원.
 * ⚠ 이 값을 왜 20 으로 뒀나 — 다섯 명이면 윌슨 구간이 거의 0~100% 로 벌어져 아무 말도
 *   못 한다. 스물이면 구간 폭이 대략 ±20%p 로 좁아져 «가장 넓은 학교»와 «중간»은 갈린다.
 * ⛔ 이 값을 낮추면 표가 길어지는 대신 «가를 수 없는 줄»이 늘어난다. 길이가 목적이 아니다.
 */
export const 몫낼최소인원 = 20;

/* ── 판단하는 함수들. 여기만 자가시험한다 ────────────────────── */

/** 한 학교를 잰다. ⛔ 못 잰 사람을 0 으로 채우지 않는다 */
export function 학교재기(s) {
  const 사람수 = Number(s?.사람수);
  const 잰사람 = Number(s?.언어판잰사람수);
  const 열개이상 = Number(s?.열개이상);
  if (!Number.isFinite(사람수) || !Number.isFinite(잰사람) || !Number.isFinite(열개이상)) return null;
  if (잰사람 <= 0) return null;
  const 구간 = 윌슨구간(열개이상, 잰사람);
  return {
    학교: s.학교,
    사람수,
    잰사람,
    못잰사람: Number(s.언어판못잰사람수) || 0,
    중간언어판: Number(s.언어판중간값) || 0,
    열개이상,
    몫: Math.round((열개이상 / 잰사람) * 1000) / 10,
    구간아래: Math.round(구간.아래 * 1000) / 10,
    구간위: Math.round(구간.위 * 1000) / 10,
    /* 몫을 «말할 수 있나» — 인원이 적으면 수는 내되 「가를 수 없다」고 적는다 */
    몫을말할수있나: 잰사람 >= 몫낼최소인원,
    맨위: (s.맨위 ?? []).slice(0, 3).map((p) => ({ 이름: p.이름, 언어판: p.언어판 })),
  };
}

/**
 * 두 학교를 «가를 수 있나». 구간이 겹치면 못 가른다.
 * ⛔ 몫만 보고 「A 가 B 보다 낫다」고 하지 않는다 — 이 함수가 그것을 막는다.
 */
export function 가를수있나(a, b) {
  if (!a || !b) return false;
  if (!a.몫을말할수있나 || !b.몫을말할수있나) return false;
  return !겹치나({ 아래: a.구간아래, 위: a.구간위 }, { 아래: b.구간아래, 위: b.구간위 });
}

/* ── 자가시험 ─────────────────────────────────────────────── */
if (process.argv.includes('--자가시험')) {
  let 통 = 0; let 실 = 0;
  const 참 = (이름, 값) => { if (값) 통 += 1; else { 실 += 1; console.log(`   🔴 ${이름}`); } };

  const 큰 = 학교재기({ 학교: 'A', 사람수: 125, 언어판잰사람수: 125, 언어판못잰사람수: 0, 열개이상: 73, 언어판중간값: 12, 맨위: [] });
  참('몫을 낸다', 큰.몫 === 58.4);
  참('⭐ 기사가 말한 58.4% 와 같다 (73/125)', 큰.몫 === 58.4);
  참('구간이 몫을 감싼다', 큰.구간아래 < 큰.몫 && 큰.몫 < 큰.구간위);
  참('스물을 넘으면 몫을 말할 수 있다', 큰.몫을말할수있나 === true);

  const 작은 = 학교재기({ 학교: 'B', 사람수: 5, 언어판잰사람수: 5, 언어판못잰사람수: 0, 열개이상: 3, 언어판중간값: 9, 맨위: [] });
  참('작은 학교도 몫은 낸다', 작은.몫 === 60);
  참('⭐ 다만 「말할 수 있나」가 거짓이다', 작은.몫을말할수있나 === false);
  참('⭐ 작은 학교의 구간이 훨씬 넓다', (작은.구간위 - 작은.구간아래) > (큰.구간위 - 큰.구간아래));

  const 연세 = 학교재기({ 학교: 'Yonsei', 사람수: 75, 언어판잰사람수: 75, 언어판못잰사람수: 0, 열개이상: 12, 언어판중간값: 3, 맨위: [] });
  참('⭐ 기사가 말한 16.0% 와 같다 (12/75)', 연세.몫 === 16);
  참('⭐ 58.4% 와 16.0% 는 «가를 수 있다»', 가를수있나(큰, 연세) === true);
  참('작은 학교와는 못 가른다 (인원이 적다)', 가를수있나(큰, 작은) === false);
  참('자기와는 못 가른다', 가를수있나(큰, 큰) === false);

  참('⛔ 못 잰 사람을 0 으로 채우지 않는다',
    학교재기({ 학교: 'C', 사람수: 30, 언어판잰사람수: 20, 언어판못잰사람수: 10, 열개이상: 5, 언어판중간값: 2, 맨위: [] }).못잰사람 === 10);
  참('⛔ 몫은 «잰 사람»으로 나눈다 — 사람수로 나누지 않는다',
    학교재기({ 학교: 'C', 사람수: 30, 언어판잰사람수: 20, 언어판못잰사람수: 10, 열개이상: 5, 언어판중간값: 2, 맨위: [] }).몫 === 25);
  참('⛔ 잰 사람이 0 이면 아무 말도 안 한다',
    학교재기({ 학교: 'D', 사람수: 3, 언어판잰사람수: 0, 언어판못잰사람수: 3, 열개이상: 0, 언어판중간값: 0 }) === null);
  참('⛔ 수가 아니면 버린다', 학교재기({ 학교: 'E', 사람수: 'x' }) === null);
  참('⛔ 빈 값에도 안 죽는다', 학교재기(null) === null);
  참('맨위를 셋까지만 싣는다',
    학교재기({ 학교: 'F', 사람수: 30, 언어판잰사람수: 30, 열개이상: 10, 언어판중간값: 5, 맨위: [1, 2, 3, 4, 5].map((n) => ({ 이름: `n${n}`, 언어판: n })) }).맨위.length === 3);
  참('최소인원이 스물이다', 몫낼최소인원 === 20);

  console.log(`\n학교별 언어판 도달을 재는 자 — 자가시험 ${통} 통과 · ${실} 실패`);
  process.exit(실 ? 1 : 0);
}

/* ── 실제로 낸다 ──────────────────────────────────────────── */
if (!process.argv.includes('--자가시험')) {
  if (!fs.existsSync(원자료)) { console.log(`🔴 원자료가 없다 — ${path.relative(뿌리, 원자료)}`); process.exit(1); }
  const 원 = JSON.parse(fs.readFileSync(원자료, 'utf8'));
  const 잰것 = (원.학교들 ?? []).map(학교재기).filter(Boolean);
  const 말할수있는것 = 잰것.filter((x) => x.몫을말할수있나);

  /* ⛔ 몫 순으로 세우지 않는다 — 인원 순으로 센다. 몫 순은 그 자체가 순위표로 읽힌다.
     ⭐ 다만 «가장 넓은 곳»과 «가장 좁은 곳»은 따로 뽑아 둔다. 그 둘은 구간이 안 겹칠 때만 쓴다. */
  const 인원순 = [...말할수있는것].sort((a, b) => b.잰사람 - a.잰사람);
  const 몫순 = [...말할수있는것].sort((a, b) => b.몫 - a.몫);
  const 가장넓은 = 몫순[0] ?? null;
  const 가장좁은 = 몫순[몫순.length - 1] ?? null;

  const 전체잰사람 = 잰것.reduce((a, b) => a + b.잰사람, 0);
  const 전체열개이상 = 잰것.reduce((a, b) => a + b.열개이상, 0);
  const 전체구간 = 전체잰사람 ? 윌슨구간(전체열개이상, 전체잰사람) : null;

  const 낼것 = {
    잰때: 잰때문자(),
    무엇인가: 'For each school, the share of its counted alumni who appear in ten or more '
      + 'Wikipedia language editions. Built from Wikidata (school property and sitelink counts).',
    '⛔아닌것': [
      '순위표가 아니다. 몫이 높은 것이 「좋은 학교」라는 뜻이 아니다.',
      '「언어판이 많다」는 「널리 읽힌다」가 아니다 — 문서가 여러 언어에 있다는 것뿐이다.',
      '학교를 아는 사람만 셌다. 모르는 사람은 없는 것이 아니라 모르는 것이다.',
    ],
    못재는것: 원.못재는것 ?? [],
    몫낼최소인원,
    셈: {
      /* ⛔ 이 수를 지면에 손으로 박지 않는다 — 원자료가 바뀌면 지면이 거짓이 된다.
         ⚠ 「학교가 적힌 사람 수」와 「학교-사람 이음 수」는 «다르다». 한 사람이 학교를
           둘 다니면 이음이 둘이다. 4,535 대 5,907 이 그 차이다. 둘을 따로 낸다. */
      학교적힌사람: Number(원.셈?.학교자료) || null,
      학교전체: (원.학교들 ?? []).length,
      잰학교: 잰것.length,
      몫을말할수있는학교: 말할수있는것.length,
      전체잰사람,
      전체열개이상,
      전체몫: 전체잰사람 ? Math.round((전체열개이상 / 전체잰사람) * 1000) / 10 : null,
      전체구간아래: 전체구간 ? Math.round(전체구간.아래 * 1000) / 10 : null,
      전체구간위: 전체구간 ? Math.round(전체구간.위 * 1000) / 10 : null,
    },
    가장넓은,
    가장좁은,
    '가장넓은곳과가장좁은곳을가를수있나': 가를수있나(가장넓은, 가장좁은),
    학교들: 인원순,
  };
  fs.writeFileSync(낼자료, JSON.stringify(낼것, null, 1));

  console.log(`학교 ${낼것.셈.학교전체}곳 중 잰 것 ${낼것.셈.잰학교}곳 · 몫을 말할 수 있는 곳 ${낼것.셈.몫을말할수있는학교}곳 (사람 ${몫낼최소인원}명 이상)`);
  console.log(`전체 — 잰 사람 ${전체잰사람.toLocaleString('en-US')}명 중 열 개 이상 언어판 ${전체열개이상.toLocaleString('en-US')}명 = ${낼것.셈.전체몫}% (${낼것.셈.전체구간아래}~${낼것.셈.전체구간위})`);
  if (가장넓은 && 가장좁은) {
    console.log(`가장 넓은 곳 — ${가장넓은.학교} ${가장넓은.몫}% (${가장넓은.구간아래}~${가장넓은.구간위}) · 잰 사람 ${가장넓은.잰사람}명`);
    console.log(`가장 좁은 곳 — ${가장좁은.학교} ${가장좁은.몫}% (${가장좁은.구간아래}~${가장좁은.구간위}) · 잰 사람 ${가장좁은.잰사람}명`);
    console.log(낼것['가장넓은곳과가장좁은곳을가를수있나']
      ? '✅ 두 곳은 구간이 안 겹친다 — 가를 수 있다'
      : '⬜ 두 곳의 구간이 겹친다 — «가를 수 없다»고 적어야 한다');
  }
  console.log(`\n냈다 — ${path.relative(뿌리, 낼자료)}`);
  console.log('⚠ 이 수를 지면에 실을 때 «구간»을 같이 실으십시오. 몫만 실으면 순위표가 됩니다.');
}
