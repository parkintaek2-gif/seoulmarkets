import { fileURLToPath } from 'node:url';

const 여기 = path.dirname(fileURLToPath(import.meta.url));
/* ⛔ 들여온 쪽에서 내 명령줄이 돌면 안 된다 — 관문이 나를 들여오면 출력이 통째로 바뀐다 */
const 내가진입점 = process.argv[1]
  && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

/** 재지 않을 곳을 지운다 */
export function 잴글만남긴다(글) {
  return String(글 ?? '')
    .replace(/```[\s\S]*?```/g, ' ')        /* 묶음 칸 */
    .replace(/^>.*$/gm, ' ')                /* 인용 줄 — 한문 원문 */
    .replace(/[一-鿿]+/g, ' ')      /* 한자 본문 */
    .replace(/「[^」]*」/g, ' ')             /* 낫표 안은 인용이다 */
    .replace(/<[^>]+>/g, ' ');              /* 표시 글자 */
}

/**
 * 덩어리 하나에서 고유어를 집어낸다.
 *   덩어리 «머리»에서만 찾고 꼬리는 세 글자까지 본다 — 한국어는 뒤에 조사·어미가 붙는다.
 *   ⛔ 가운데에서 찾으면 「추가토지」가 「가토」로 잡힌다.
 *   가장 «긴» 것을 잡는다 — 「나머지」를 「나무」로 잡으면 안 된다.
 */
export function 덩어리에서찾는다(덩이, 아는말) {
  const d = String(덩이 ?? '');
  if (!아는말 || d.length < 2) return null;
  const 끝 = Math.min(d.length, 12);
  for (let b = 끝; b >= 2; b -= 1) {
    if (d.length - b > 3) continue;          /* 꼬리가 길면 다른 낱말이다 */
    const 토막 = d.slice(0, b);
    if (아는말.has(토막)) return 토막;
  }
  return null;
}

/**
 * 바꿀 말을 고른다.
 * 🔴 겪으며 쌓은 대체표를 «사전 짝보다 앞»에 둔다.
 *   사전이 적는 짝은 한문투일 때가 있다 — 까닭의 짝을 사전은 「소이」라 적지만
 *   우리는 사장님 지적을 받아 「이유 · 원인」으로 바꾸어 왔다.
 *   사전은 빠진 말을 메우는 자이지 우리가 정한 말을 덮는 자가 아니다.
 */
export function 바꿀말(말, 겪은표, 짝표) {
  const 겪은것 = (겪은표 || {})[말];
  if (겪은것) return { 짝: 겪은것, 어디서: '겪은표' };
  const 사전것 = (짝표 || {})[말];
  if (사전것) return { 짝: 사전것, 어디서: '사전' };
  return null;
}

/** 글을 잰다 */
export function 잰다(글, { 짝표 = {}, 고유어 = new Set(), 겪은표 = {} } = {}) {
  const 잴것 = 잴글만남긴다(글);
  const 바꿀것 = new Map();      /* 말 → { 수, 짝, 자리 } */
  const 짝없는것 = new Map();
  for (const 덩이 of 잴것.match(/[가-힣]+/g) || []) {
    const 찾음 = 덩어리에서찾는다(덩이, 고유어);
    if (!찾음) continue;
    const 고를것 = 바꿀말(찾음, 겪은표, 짝표);
    const 통 = 고를것 ? 바꿀것 : 짝없는것;
    if (!통.has(찾음)) {
      통.set(찾음, { 수: 0, 짝: 고를것 ? 고를것.짝 : '', 어디서: 고를것 ? 고를것.어디서 : '', 자리: [] });
    }
    const 칸 = 통.get(찾음);
    칸.수 += 1;
    if (칸.자리.length < 2 && 덩이 !== 찾음) 칸.자리.push(덩이);
  }
  const 줄세운다 = (통) => [...통.entries()]
    .map(([말, 칸]) => ({ 말, ...칸 }))
    .sort((a, b) => b.수 - a.수);
  return { 바꿀것: 줄세운다(바꿀것), 짝없는것: 줄세운다(짝없는것) };
}

/* ── 자가시험 ───────────────────────────────────────── */
if (내가진입점 && process.argv.includes('--자가시험')) {
  let 통과 = 0; let 탈 = 0;
  const 본다 = (이름, 참) => { if (참) { 통과 += 1; } else { 탈 += 1; console.log('🔴 ' + 이름); } };
  const 아는말 = new Set(['간추림', '나머지', '가토', '다투', '사이']);
  const 짝표 = { 나머지: '여분' };

  본다('① 덩어리 머리에서 찾는다', 덩어리에서찾는다('나머지를', 아는말) === '나머지');
  본다('⛔ 가운데에서는 안 찾는다 — 「추가토지」는 「가토」가 아니다',
    덩어리에서찾는다('추가토지를', 아는말) === null);
  본다('② 가장 긴 것을 잡는다', (() => {
    const 말 = new Set(['나무', '나머지']);
    return 덩어리에서찾는다('나머지', 말) === '나머지';
  })());
  본다('③ 꼬리가 길면 다른 낱말이다',
    덩어리에서찾는다('사이버공간에서', 아는말) === null);
  본다('④ 활용형을 어간으로 잡는다', 덩어리에서찾는다('다투던', 아는말) === '다투');
  본다('⑤ 빈 값에 안 터진다',
    덩어리에서찾는다('', 아는말) === null && 덩어리에서찾는다(null, null) === null);

  본다('⑥ 묶음 칸과 인용 줄은 재지 않는다', (() => {
    const r = 잴글만남긴다('글\n```\n간추림\n```\n> 간추림\n');
    return !r.includes('간추림');
  })());
  본다('⑦ 한자 원문은 재지 않는다', 잴글만남긴다('祿劫用財').trim() === '');
  본다('⛔ 낫표 안은 인용이라 세지 않는다 — 보고가 제 보고에 걸린다',
    !잴글만남긴다('「간추림」이 걸렸다').includes('간추림'));

  본다('⑧ 짝이 있는 것과 없는 것을 가른다', (() => {
    const r = 잰다('나머지를 간추림 한다', { 짝표, 고유어: 아는말 });
    return r.바꿀것.length === 1 && r.바꿀것[0].말 === '나머지' && r.바꿀것[0].짝 === '여분'
      && r.짝없는것.length === 1 && r.짝없는것[0].말 === '간추림';
  })());
  본다('⑨ 횟수를 센다', (() => {
    const r = 잰다('나머지 나머지를 나머지가', { 짝표, 고유어: 아는말 });
    return r.바꿀것[0].수 === 3;
  })());
  본다('⛔ 겪은표가 사전 짝보다 앞이다 — 까닭은 소이가 아니라 이유다', (() => {
    const r = 바꿀말('까닭', { 까닭: '이유 · 원인' }, { 까닭: '소이' });
    return r.짝 === '이유 · 원인' && r.어디서 === '겪은표';
  })());
  본다('⛔ 겪은표에 없으면 사전 짝을 쓴다', (() => {
    const r = 바꿀말('나머지', {}, { 나머지: '여분' });
    return r.짝 === '여분' && r.어디서 === '사전';
  })());
  본다('⛔ 둘 다 없으면 짝이 없다', 바꿀말('간추림', {}, {}) === null);
  본다('⑫ 겪은표로도 바꿀 것이 잡힌다', (() => {
    const r = 잰다('간추림이 끝났다', { 짝표: {}, 고유어: 아는말, 겪은표: { 간추림: '요약' } });
    return r.바꿀것.length === 1 && r.바꿀것[0].짝 === '요약';
  })());
  본다('⑩ 깨끗한 글은 아무것도 안 낸다', (() => {
    const r = 잰다('본서는 원문의 용법을 준수한다.', { 짝표, 고유어: 아는말 });
    return r.바꿀것.length === 0 && r.짝없는것.length === 0;
  })());
  본다('⑪ 빈 글에 안 터진다', (() => {
    const r = 잰다(null, {});
    return r.바꿀것.length === 0 && r.짝없는것.length === 0;
  })());

  console.log(탈 ? '🔴 자가시험 ' + 탈 + '건 탈' : '✅ 자가시험 ' + 통과 + '가지 통과');
  process.exit(탈 ? 1 : 0);
}

/* ── 실제로 잰다 ──────────────────────────────────────
 * ⛔ 아래는 «내가 진입점일 때»만 돈다.
 *   그러지 않으면 다른 자가 이 파일을 들여올 때 제 명령줄이 같이 돌아 버린다 —
 *   2026-11-22 에 관문이 이 자를 들여오자 관문의 출력이 통째로 사라졌다. */
if (!내가진입점) {
  /* 들여온 쪽은 위의 함수만 쓴다 */
} else {
const { 바꿀만한짝 } = await import('file:///'
  + path.join(여기, '..', 'data', '바꿀만한-짝.js').replace(/\\/g, '/'));
const { 사전고유어 } = await import('file:///'
  + path.join(여기, '..', 'data', '사전-고유어-전부.js').replace(/\\/g, '/'));
const { 현대한자어 } = await import('file:///'
  + path.join(여기, '..', 'data', '현대한국어-한자어.js').replace(/\\/g, '/'));
const { 금지어 } = await import('file:///'
  + path.join(여기, '순한글-금지어.mjs').replace(/\\/g, '/'));

/* 겪으며 쌓은 대체표 — 사장님이 짚어 주신 말이 여기 쌓여 있다 */
const 겪은표 = {};
for (const x of 금지어) if (x && x.말 && x.대신) 겪은표[x.말] = x.대신;

/* 🔴 사장님 2026-11-22 — 「한자어가 현대 한국어가 아닌 지만 보면 되고」
 *   사전 짝을 그대로 쓰지 않고 내가 다른 말을 고를 때 되묻는 자리다. */
if (process.argv.includes('--한자어')) {
  const 볼것 = process.argv.slice(process.argv.indexOf('--한자어') + 1)
    .filter((x) => !x.startsWith('--'));
  if (!볼것.length) {
    console.log('쓰는 법: node scripts/잰다-한자어로-썼나.mjs --한자어 <낱말…>');
    process.exit(2);
  }
  let 걸림 = 0;
  for (const w of 볼것) {
    const 성하다 = 현대한자어.has(w);
    const 고유어다 = 사전고유어.has(w);
    if (!성하다 || 고유어다) 걸림 += 1;
    console.log('   ' + (성하다 && !고유어다 ? '✅' : '🔴') + ' ' + w.padEnd(8)
      + (고유어다 ? '고유어다 — 한자어가 아니다'
        : 성하다 ? '현대 한국어 한자어다' : '한자어이나 지금은 쓰이지 않는다'));
  }
  process.exit(걸림 ? 1 : 0);
}

const 길 = process.argv[2];
if (!길 || 길.startsWith('--')) {
  console.log('쓰는 법: node scripts/잰다-한자어로-썼나.mjs <파일> [--짝없는것도]');
  console.log('        node scripts/잰다-한자어로-썼나.mjs --한자어 <낱말…>');
  process.exit(1);
}

const 잰것 = 잰다(fs.readFileSync(길, 'utf8'),
  { 짝표: 바꿀만한짝, 고유어: 사전고유어, 겪은표 });
const 곳수 = (줄) => 줄.reduce((s, x) => s + x.수, 0);

console.log('■ ' + path.basename(길));
console.log('  국립국어원 표준국어대사전으로 쟀다 — 고유어 ' + 사전고유어.size
  + '개 · 바꿀 수 있는 짝 ' + Object.keys(바꿀만한짝).length + '개');

if (잰것.바꿀것.length) {
  console.log('\n🔴 바꿀 수 있는 고유어 — ' + 잰것.바꿀것.length + '가지 '
    + 곳수(잰것.바꿀것) + '곳');
  for (const x of 잰것.바꿀것) {
    console.log('   ' + x.말.padEnd(8) + x.수 + '번  → ' + x.짝
      + (x.자리.length ? '   (' + x.자리.join(', ') + ')' : ''));
  }
} else {
  console.log('\n✅ 바꿀 수 있는 고유어가 없다');
}

if (process.argv.includes('--짝없는것도')) {
  console.log('\n⚠ 한자어 짝이 사전에 없는 고유어 — ' + 잰것.짝없는것.length + '가지 '
    + 곳수(잰것.짝없는것) + '곳 (바꿀 말은 내가 찾는다)');
  for (const x of 잰것.짝없는것) {
    console.log('   ' + x.말.padEnd(8) + x.수 + '번'
      + (x.자리.length ? '   (' + x.자리.join(', ') + ')' : ''));
  }
} else if (잰것.짝없는것.length) {
  console.log('\n⚠ 짝이 사전에 없는 고유어가 ' + 잰것.짝없는것.length + '가지 더 있다'
    + ' — `--짝없는것도` 로 본다');
}

process.exit(잰것.바꿀것.length ? 1 : 0);
}
