  검('⚠ 오늘 23시 전에는 밤 몫을 안 센다', 아직이른가('2026-11-11', 밤, 낮) === true);
  검('⛔ 어제 몫은 지금이 몇 시든 센다', 아직이른가('2026-11-10', 밤, 낮) === false);
