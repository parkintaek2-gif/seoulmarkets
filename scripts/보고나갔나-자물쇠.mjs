/**
 * 보고나갔나-자물쇠.mjs — **오후·밤 보고가 실제로 «나갔나». 안 나갔으면 배포를 잠근다.**
 * ═══════════════════════════════════════════════════════════════════════════
 * 🔴🔴 [2026-11-11 · 사장님] **「업무보고-오후, 밤 왜 직접 보내는 보고가 요즘들어
 *    한 건도 없잖아. **제대로 된 장치가 아니니까 그러겠지**」**
 *
 * [재 보니 사장님 말씀 그대로였다]
 *   ```
 *   오후(16시)  11-10 안 나감 · 11-11 안 나감   — 둘 다 «금지어 관문»에 걸려 멈췄다.
 *               걸린 글은 내가 보낸 메일 제목을 표에 그대로 옮긴 줄이었다.
 *               로그에 「⛔ 이 자의 틀을 고쳐야 한다」가 찍혀 있었다 — 찍히기만 했다.
 *   밤(23시)    11-02 뒤로 **한 건도 없다.** 보내는 자(auto-2300-report.mjs)도 있고
 *               감싸는 .cmd 도 11-02 에 만들어 뒀는데 **예약을 안 걸었다.**
 *               .cmd 머리글에는 「이 작업을 지우려면 schtasks /delete …」까지
 *               적혀 있었다 — 걸지도 않은 작업을 지우는 법만 적어 둔 것이다.
 *   ```
 *
 * [왜 아무도 몰랐나 — 여기가 뿌리다]
 *   업무보고 자물쇠는 **「세션간 메모에 보고를 적었나」**를 본다.
 *   그런데 사장님이 받으시는 것은 메모가 아니라 **메일**이다.
 *   메모에 적고 메일이 안 나가면 자물쇠는 초록인데 사장님 손에는 아무것도 없다.
 *   ⇒ 이 자는 **보낸메일 대장**을 본다. 「적었나」가 아니라 「나갔나」를 잰다.
 *
 * ⛔ 「만들었다」를 「나갔다」로 읽지 않는다. 「예약을 적어 뒀다」를 「예약이 걸렸다」로도.
 *   그래서 이 자는 **예약이 실제로 걸려 있는지까지** 같이 본다.
 *
 * ⚠ 오늘 몫은 그 시각이 지나야 센다 — 「아직 안 온 것」과 「안 나간 것」은 다르다.
 *
 * 쓰는 법
 *   node scripts/보고나갔나-자물쇠.mjs            지난 이레 중 빠진 날
 *   node scripts/보고나갔나-자물쇠.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const 뿌리 = path.resolve(import.meta.dirname, '..');
export const 대장길 = path.join(뿌리, 'docs', '보낸메일.tsv');

/**
 * 봐야 하는 보고 두 가지.
 * ⚠ 「언제까지 나갔어야 하나」를 분으로 적는다 — 그 시각 전에는 안 센다.
 */
export const 볼보고 = [
  { 이름: '오후(16시)', 무늬: /16시\s*업무보고/, 늦어도: 16 * 60, 예약: 'SeoulMarkets-Auto1600Report' },
  { 이름: '밤(23시)', 무늬: /23시\s*업무보고/, 늦어도: 23 * 60, 예약: 'SeoulMarkets-Auto2300Report' },
];

/** 며칠치를 보나 */
export const 볼날수 = 7;

/** ⛔ toISOString() 을 쓰지 않는다 — 이 PC 가 이미 KST 다 */
export function 날글(d) {
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

export function 지난날들(이제 = new Date(), 몇 = 볼날수) {
  const 것 = [];
  for (let i = 몇 - 1; i >= 0; i -= 1) {
    const d = new Date(이제);
    d.setDate(d.getDate() - i);
    것.push(날글(d));
  }
  return 것;
}

/**
 * 그 날 그 보고가 나갔나.
 * ⚠ **제목에 「23시」라고 적혀 있다고 23시에 낸 것이 아니다** — 16시판이 새벽에 나간 적이 있다.
 *   그래서 «보낸 시각»도 같이 본다. 적어도 그 시각 두 시간 전부터만 센다.
 */
export function 나갔나(줄들, 날, 보고) {
  for (const 줄 of 줄들 ?? []) {
    const t = String(줄);
    if (!t.startsWith(날)) continue;
    const 시 = Number(t.slice(11, 13));
    const 분 = Number(t.slice(14, 16));
    if (!Number.isFinite(시) || !Number.isFinite(분)) continue;
    const 때 = 시 * 60 + 분;
    if (때 < 보고.늦어도 - 120) continue;      /* 너무 이른 것은 그 회차가 아니다 */
    const 제목 = t.split('\t')[3] ?? t;
    if (보고.무늬.test(제목)) return true;
  }
  return false;
}

/** 그 날 그 회차를 «아직 셀 때가 아닌가» */
export function 아직이른가(날, 보고, 이제 = new Date()) {
  if (날 !== 날글(이제)) return false;
  return 이제.getHours() * 60 + 이제.getMinutes() < 보고.늦어도;
}

/**
 * 예약이 실제로 걸려 있나. ⛔ 「없다」와 「못 쟀다」를 가른다.
 * @returns true | false | null(못 쟀다)
 */
export function 예약이걸렸나(이름) {
  try {
    const 글 = execFileSync('schtasks', ['/query', '/tn', 이름],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
    return String(글).includes(이름);
  } catch (e) {
    /* 작업이 없으면 schtasks 가 끝값 1 로 떨어진다 — 그것은 「없다」다 */
    if (e && e.status === 1) return false;
    return null;                                  /* 아예 못 불렀다 */
  }
}

/** 빠진 것을 모은다 */
export function 빠진것(줄들, 이제 = new Date(), 몇 = 볼날수) {
  const 결 = [];
  for (const 날 of 지난날들(이제, 몇)) {
    for (const 보고 of 볼보고) {
      if (아직이른가(날, 보고, 이제)) continue;
      if (!나갔나(줄들, 날, 보고)) 결.push({ 날, 이름: 보고.이름 });
    }
  }
  return 결;
}

/**
 * 배포를 «막는» 것은 아직 손쓸 수 있는 것만.
 *
 * 🔴 [2026-11-11 · 5번] 처음에 이레치를 전부 막게 했더니 **이레 내내 배포가 잠겼다.**
 *   11-05~11-10 에 빠진 것은 이제 와서 보낼 수가 없다 — 그날 한 일을 지금 지어낼 수는 없다.
 *   ⛔ **고칠 수 없는 빨강은 며칠이면 아무도 안 보는 빨강이 된다.**
 *     그러면 그 속에 오늘의 진짜 빨강이 묻힌다. 같은 자리를 전에도 겪었다.
 * ⇒ 막는 것은 **오늘 몫**이다. 오늘 한 일은 지금 손에 있으니 언제나 메울 수 있다.
 *   ⚠ 어제 것도 막게 해 봤는데, 11-10 밤 보고는 **원고가 없어 지금 메울 수가 없었다.**
 *     그날 한 일을 지금 지어내는 것은 보고가 아니라 거짓이다.
 *     ⇒ 메울 길이 없는 것을 막는 자리에 두면 그 빨강은 영영 안 꺼진다.
 *   더 오래된 것은 **지워지지 않고 목록에 남지만 막지는 않는다.** 빠진 것은 빠진 것으로 둔다.
 */
export const 막는날수 = 1;

export function 막을것(줄들, 이제 = new Date()) {
  const 최근 = new Set(지난날들(이제, 막는날수));
  return 빠진것(줄들, 이제).filter((x) => 최근.has(x.날));
}

