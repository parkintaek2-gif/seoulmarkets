function 주다() {
  if (process.argv.includes('--자가시험')) return 자가시험();

  const 줄들 = fs.existsSync(대장길)
    ? fs.readFileSync(대장길, 'utf8').split(/\r?\n/).filter(Boolean) : null;

  console.log('■ 오후·밤 보고가 실제로 «나갔나» (보낸메일 대장 기준)');
  console.log('   🔴 사장님 (2026-11-11): 「업무보고-오후, 밤 왜 직접 보내는 보고가');
  console.log('      요즘들어 한 건도 없잖아. 제대로 된 장치가 아니니까 그러겠지」\n');

  if (줄들 === null) {
    console.log('⚠ 못 쟀다 — 보낸메일 대장을 못 읽었다. 「나갔다」로도 「안 나갔다」로도 읽지 않는다');
    process.exit(1);
  }

  /* ① 예약이 걸려 있나 — 「자를 만들어 뒀다」는 「돈다」가 아니다 */
  let 예약빵꾸 = 0;
  for (const 보고 of 볼보고) {
    const r = 예약이걸렸나(보고.예약);
    if (r === true) console.log(`   ✅ ${보고.이름} 보내는 예약이 걸려 있다 — ${보고.예약}`);
    else if (r === false) { 예약빵꾸 += 1; console.log(`   🔴 ${보고.이름} 보내는 예약이 **없다** — ${보고.예약}`); }
    else console.log(`   ⚠ ${보고.이름} 예약을 못 쟀다 — ${보고.예약}`);
  }
  console.log('');

  /* ② 실제로 나갔나 */
  const 빠짐 = 빠진것(줄들);
  const 막힘 = 막을것(줄들);
  if (!빠짐.length && !예약빵꾸) {
    console.log(`✅ 지난 ${볼날수}일 동안 오후·밤 보고가 다 나갔다.`);
    process.exit(0);
  }
  if (빠짐.length) {
    const 지난것 = 빠짐.filter((x) => !막힘.some((y) => y.날 === x.날 && y.이름 === x.이름));
    if (막힘.length) {
      console.log(`🔴🔴 지금 메울 수 있는데 안 나간 보고 ${막힘.length}건 — **배포를 막는다**`);
      for (const x of 막힘) console.log(`   · ${x.날}  ${x.이름}`);
      console.log('   ⇒ 그 몫을 지금 보낸다:');
      console.log('      node scripts/auto-1600-report.mjs --send');
      console.log('      node scripts/auto-2300-report.mjs --send');
    }
    if (지난것.length) {
      console.log(`\n⚠ 이미 지나가 못 메우는 것 ${지난것.length}건 — 막지는 않는다`);
      for (const x of 지난것) console.log(`   · ${x.날}  ${x.이름}`);
      console.log('   ⛔ 그날 한 일을 지금 지어내지 않는다. 안 나간 것은 안 나간 것으로 둔다.');
    }
    console.log('');
    console.log('   ⛔ 「메모에 적었다」는 「사장님께 갔다」가 아니다. 이 자는 메일 대장만 본다.');
  }
  if (예약빵꾸) {
    console.log('\n   ⛔ 예약이 빠진 것이 더 나쁘다 — 내일도 안 나간다. 먼저 건다.');
  }
  process.exit(1);
}

