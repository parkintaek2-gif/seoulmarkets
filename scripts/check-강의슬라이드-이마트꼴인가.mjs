/* ───────────────────────────── zip 읽기 ───────────────────────────── */

export function 집목록(묶음) {
  const 것 = [];
  for (let i = 0; i < 묶음.length - 4; i++) {
    if (묶음.readUInt32LE(i) !== 0x04034b50) continue;
    const 이름길 = 묶음.readUInt16LE(i + 26);
    것.push(묶음.slice(i + 30, i + 30 + 이름길).toString());
  }
  return 것;
}

export function 집에서꺼내기(묶음, 이름) {
  for (let i = 0; i < 묶음.length - 4; i++) {
    if (묶음.readUInt32LE(i) !== 0x04034b50) continue;
    const 압축 = 묶음.readUInt16LE(i + 8);
    const 크기 = 묶음.readUInt32LE(i + 18);
    const 이름길 = 묶음.readUInt16LE(i + 26);
    const 더 = 묶음.readUInt16LE(i + 28);
    if (묶음.slice(i + 30, i + 30 + 이름길).toString() !== 이름) continue;
    const z = 묶음.slice(i + 30 + 이름길 + 더, i + 30 + 이름길 + 더 + 크기);
    return (압축 === 8 ? zlib.inflateRawSync(z) : z).toString('utf8');
  }
  return null;
}

/** 슬라이드 XML 한 장에서 손님이 보는 글자만 뽑는다 */
export function 글자뽑기(xml) {
  return [...String(xml ?? '').matchAll(/<a:t>([^<]*)<\/a:t>/g)].map((m) => m[1]).join('');
}

/**
 * 🔴 한문 원문인가 — 한자가 이어서 넷 넘게 나오면 원문으로 본다.
 * ⛔ 한자 한둘은 용어 병기(甲木·正財)라 원문이 아니다. 그것까지 집으면 가짜가 는다.
 */
export function 한문원문인가(글) {
  const s = String(글 ?? '');
  return /[\u4e00-\u9fff]{5,}/.test(s);
}

/**
 * 🔴🔴 **이 장이 사주명반인가** — 도형으로 그린 것도 「그림」이다.
 *
 * [2026-10-03] 그림 비율이 6% 로 빨갛게 떠 있었다. 그런데 명반은 «이미 27장» 있었다.
 *   이 자가 `<p:pic>`(사진)만 세고 있어서 **도형으로 그린 명반을 한 장도 못 봤다.**
 *   이마트 1권은 만세력 «화면 사진»을 붙였고(=`<p:pic>`), 우리는 같은 것을 도형으로 그린다.
 *   둘은 같은 것이다 — 화면에 글자 대신 명반이 떠 있다.
 *
 * ⛔ 자를 내 쪽에 유리하게 바꾸는 것이 아니다. 사장님이 말씀하신 것은
 *   「대부분 예시 사주명반을 넣어」이지 「사진을 붙여라」가 아니다. 재는 것을 바로잡는 것이다.
 * ⚠ 기둥 이름 넷이 다 있을 때만 명반으로 본다. 「일주」 한 낱말이 본문에 나온 것까지
 *   세면 숫자가 부풀어 다시 못 믿을 자가 된다.
 */
export const 기둥이름들 = [['時柱', '시주'], ['日柱', '일주'], ['月柱', '월주'], ['年柱', '연주']];
export function 명반인장인가(xml) {
  const 글 = 글자뽑기(xml);
  if (!글) return false;
  return 기둥이름들.every(([한자, 한글]) => 글.includes(한자) || 글.includes(한글));
}

export function 꾸러미재기(파일) {
  if (!fs.existsSync(파일)) return null;              /* 못 쟀다 —  */
  const 묶음 = fs.readFileSync(파일);
  const 것들 = 집목록(묶음);
  const 장이름 = 것들.filter((n) => /^ppt\/slides\/slide\d+\.xml$/.test(n));
  const 글자수 = [];
  const 본문글자수 = [];      /* 🔴 명반 장을 뺀 것 — 아래 머리말 참고 */
  let 표있는장 = 0;
  let 그림있는장 = 0;
  let 명반있는장 = 0;
  for (const n of 장이름) {
    const x = 집에서꺼내기(묶음, n) || '';
    글자수.push(글자뽑기(x).length);
    /* 🔴🔴 [2026-10-04 · 5번] **명반 이름표를 본문 글과 같이 세고 있었다.**
       명반 한 장에는 「時柱 시주 日柱 일주 月柱 월주 年柱 연주」와 간지 독음이 들어간다.
       그것만으로 42자다 — 그리고 그 글자는 «줄일 수 없다». 명반을 읽는 데 필요하다.
       우리 2권은 명반이 81장이라 그 42자가 가운데값을 통째로 끌고 다녔다.
       (명반 장 가운데값 42 · 본문 장 가운데값 48 · 전체 42)
       ⛔ 줄일 수 없는 글자로 빨강을 켜면 그 빨강은 영영 안 꺼진다. 그리고 옆의
         진짜 빨강까지 같이 묻는다.
       ⚠ 이마트 1권은 명반이 «한 장»이라 이 흠이 안 보였다. 기준이 되는 쪽에
         없는 병이라 비교로도 안 드러난다.
       ⇒ 가운데값은 «본문 장»으로 재고, 명반 장은 따로 적는다. */
    if (!명반인장인가(x)) 본문글자수.push(글자뽑기(x).length);
    if (/<a:tbl>/.test(x)) 표있는장++;
    if (/<p:pic>/.test(x)) 그림있는장++;
    if (명반인장인가(x)) 명반있는장++;
  }
  /* 노트에 한문 원문이 들어갔나 */
  const 노트이름 = 것들.filter((n) => /^ppt\/notesSlides\/notesSlide\d+\.xml$/.test(n));
  let 원문든노트 = 0;
  for (const n of 노트이름) {
    const 글 = 글자뽑기(집에서꺼내기(묶음, n) || '');
    if (한문원문인가(글)) 원문든노트++;
  }
  const 정렬 = [...글자수].sort((a, b) => a - b);
  return {
    장수: 장이름.length,
    글자가운데값: 정렬.length ? 정렬[Math.floor(정렬.length / 2)] : null,
    /* ⭐ 판정은 이 값으로 한다 — 명반 이름표를 뺀, 「줄일 수 있는 글」의 가운데값 */
    본문글자가운데값: (() => {
      const s = [...본문글자수].sort((p, q) => p - q);
      return s.length ? s[Math.floor(s.length / 2)] : null;
    })(),
    본문장수: 본문글자수.length,
    가장많은장: 정렬.length ? 정렬[정렬.length - 1] : null,
    긴장: 글자수.filter((v) => v > 긴장기준).length,
    표있는장, 그림있는장, 명반있는장,
    /* ⭐ 「화면에 글자 말고 «볼 것»이 떠 있나」 — 사진이든 도형 명반이든 같다.
       ⛔ 한 장에 둘 다 있으면 두 번 세지 않는다. 그래서 장을 다시 돈다. */
    볼것있는장: (() => {
      let n = 0;
      for (const 이름 of 장이름) {
        const x = 집에서꺼내기(묶음, 이름) || '';
        if (/<p:pic>/.test(x) || 명반인장인가(x)) n++;
      }
      return n;
    })(),
    노트수: 노트이름.length,
    원문든노트,
  };
}

export function 비율(위, 아래) { return 아래 ? Math.round((위 / 아래) * 100) : null; }

