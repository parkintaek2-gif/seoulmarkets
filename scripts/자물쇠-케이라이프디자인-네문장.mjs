/**
 * 자물쇠-케이라이프디자인-네문장.mjs
 * ─────────────────────────────────────────────────────────────────
 * 케이라이프디자인 한 페이지 홈페이지에 들어가는 **네 문장**은 전부 사장님 문장이다.
 *
 *   사장님 2026-11-22 — 「내가 쓴 적 없다. 너희가 지은 말이다. 모든 곳에서 삭제해라」
 *   사장님 2026-11-23 — 「케이라이프디자인 홈페이지 내 사이트 설명 중 두 가지 추가로 수정함. 반영해」
 *
 * ⛔ 한 글자도 고치지 않는다. 조사·띄어쓰기·마침표까지 그대로 쓴다.
 * ⛔ 「임시」 문장을 다시 만들지 않는다. 네 문장이 다 왔으므로 임시는 없다.
 *
 * 쓰는 법
 *   node scripts/자물쇠-케이라이프디자인-네문장.mjs
 *   node scripts/자물쇠-케이라이프디자인-네문장.mjs --자가시험
 *
 * 끝값 0 = 초록불, 1 = 빨간불
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const 저장소 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * 카드 이름 — 사장님 2026-11-23 「서울마켓츠 > S마켓츠 또는 에스마켓츠 로 수정하고」
 * 「S마켓츠」와 「에스마켓츠」 둘을 주셨고 「에스마켓츠」로 골랐다.
 * 까닭 — 사장님이 평소 쓰시는 표기가 「에스마켓츠」이고(CLAUDE.md 원문),
 *        옆 카드가 「케이라이프맵에이아이」라 한글 표기로 결이 맞는다.
 * ⛔ 주소는 seoulmarkets.com 그대로다. 바꾸는 것은 «화면에 적는 이름»뿐이다.
 */
const 카드이름 = ['케이라이프맵에이아이', '백년지도', '에스마켓츠'];

/** 카드 이름으로 되살아나면 안 되는 옛 이름 */
const 옛카드이름 = '서울마켓츠';

/** 사장님 문장 — 여기를 고치려면 사장님 말씀이 있어야 한다 */
const 네문장 = [
  '인생을 그리는 데 도움을 줄 수 있는 지도와 내비게이션 세 가지를 제공합니다.',
  '사주, 별자리, 궁합. 택일 등 인생에 필요한 지도를 그려 드립니다.',
  '0세부터 100세까지, 궁금한 것을 안내하는 인생 내비게이션입니다.',
  '아시아와 걸프 지역의 금융시장 데이터를 영어로 볼 수 있습니다.',
];

/** 정본 — 여기에는 네 문장이 반드시 그대로 있어야 한다 */
const 정본 = 'docs/계획-케이라이프디자인-홈페이지-최종.md';

/** 지면 — 아직 안 지었으면 건너뛴다(못 쟀다고 적는다). 지으면 여기도 잰다 */
const 지면후보 = [
  'src/pages/klifedesign/index.astro',
  'src/pages/klifedesign.astro',
  'src/pages/company/index.astro',
];

function 읽는다(상대길) {
  const 길 = path.join(저장소, 상대길);
  if (!fs.existsSync(길)) return null;
  return fs.readFileSync(길, 'utf8');
}

function 잰다(글, 어디) {
  const 깨진것 = [];
  if (글 === null) return { 못쟀다: true, 어디, 깨진것 };
  네문장.forEach((문장, n) => {
    if (!글.includes(문장)) 깨진것.push(`${어디} — ${n + 1}번 문장이 그대로 있지 않다: 「${문장}」`);
  });
  카드이름.forEach((이름) => {
    if (!글.includes(이름)) 깨진것.push(`${어디} — 카드 이름 「${이름}」이 없다`);
  });
  return { 못쟀다: false, 어디, 깨진것 };
}

/**
 * 셋째 카드가 옛 이름으로 적혀 있나
 *   ⛔ 주소 seoulmarkets.com 은 옳다 — 세지 않는다. 바뀐 것은 화면에 적는 이름뿐이다
 *   ⛔ 낫표(「」) 안은 사장님 말씀 원문이거나 「이렇게 적지 않는다」는 설명이다 — 세지 않는다
 *      ⚠ 2026-11-23 에 이 자물쇠가 제가 적은 인용 두 줄을 잡아 거짓 빨간불을 냈다.
 *        재는 자가 설명문을 카드로 오인하면 고칠 거리가 아닌 것을 고치게 된다.
 */
function 옛이름이카드로남았나(글, 어디) {
  const 깨진것 = [];
  글.split('\n').forEach((줄, n) => {
    const 인용밖 = 줄.replace(/「[^」]*」/g, '');
    if (!인용밖.includes(옛카드이름)) return;
    깨진것.push(`${어디}:${n + 1} — 옛 카드 이름 「${옛카드이름}」이 남아 있다`);
  });
  return 깨진것;
}

function 전부잰다() {
  const 깨진것 = [];
  const 못잰것 = [];

  const 정본글 = 읽는다(정본);
  if (정본글 === null) {
    깨진것.push(`정본이 없다 — ${정본}`);
  } else {
    깨진것.push(...잰다(정본글, 정본).깨진것);
    깨진것.push(...옛이름이카드로남았나(정본글, 정본));
    /* 임시 문장이 되살아나지 않았나 */
    if (/임시[:：]/.test(정본글) || /문장 대기/.test(정본글)) {
      깨진것.push(`${정본} — 「임시」 문장이나 「문장 대기」가 되살아났다. 네 문장은 다 왔다`);
    }
  }

  const 지면길 = 지면후보.find((p) => fs.existsSync(path.join(저장소, p)));
  if (!지면길) {
    못잰것.push('지면을 아직 안 지었다 — 지으면 그 지면도 이 자물쇠가 잰다');
  } else {
    const 지면글 = 읽는다(지면길);
    깨진것.push(...잰다(지면글, 지면길).깨진것);
    깨진것.push(...옛이름이카드로남았나(지면글, 지면길));
  }

  return { 깨진것, 못잰것 };
}

/** 자가시험 — 일부러 틀린 글을 지어 넣으면 이 자물쇠가 정말 빨간불을 내나 */
function 자가시험() {
  const 성한글 = [...네문장, ...카드이름].join('\n');
  const 시험들 = [
    {
      이름: '성한 글은 그냥 지나간다',
      글: 성한글,
      바라는것: 0,
    },
    {
      이름: '문장에서 글자 하나를 비틀면 잡는다 (내비게이션 → 네비게이션)',
      글: 성한글.replace('인생 내비게이션입니다', '인생 네비게이션입니다'),
      바라는것: 1,
    },
    {
      이름: '카드 이름이 사라지면 잡는다',
      글: 성한글.replace('에스마켓츠', ''),
      바라는것: 1,
    },
    {
      이름: '옛 카드 이름이 되살아나면 잡는다 (서울마켓츠)',
      글: 성한글 + '\n| 서울마켓츠 | ... |',
      바라는것: 1,
      옛이름도잰다: true,
    },
    {
      이름: '낫표 안의 사장님 말씀 원문은 안 잡는다',
      글: 성한글 + '\n사장님 — 「서울마켓츠 > S마켓츠 또는 에스마켓츠 로 수정하고」',
      바라는것: 0,
      옛이름도잰다: true,
    },
    {
      이름: '주소 seoulmarkets.com 은 안 잡는다',
      글: 성한글 + '\n| 에스마켓츠 | ... | https://seoulmarkets.com |',
      바라는것: 0,
      옛이름도잰다: true,
    },
  ];

  let 틀린것 = 0;
  시험들.forEach((시험) => {
    const 센것 = 잰다(시험.글, '(자가시험)').깨진것.length
      + (시험.옛이름도잰다 ? 옛이름이카드로남았나(시험.글, '(자가시험)').length : 0);
    const 됐나 = 센것 === 시험.바라는것;
    if (!됐나) 틀린것 += 1;
    console.log(`  ${됐나 ? '✅' : '🔴'} ${시험.이름} — ${센것}건 (바란 것 ${시험.바라는것}건)`);
  });

  console.log(틀린것
    ? `🔴 자가시험이 ${틀린것}가지 실패했다 — 이 자물쇠를 믿으면 안 된다`
    : `✅ 자가시험 — ${시험들.length}가지 다 통과했다. 이 자물쇠는 잡을 것만 잡는다`);
  return 틀린것 ? 1 : 0;
}

if (process.argv.includes('--자가시험')) {
  process.exitCode = 자가시험();
} else {
  const { 깨진것, 못잰것 } = 전부잰다();
  못잰것.forEach((m) => console.log(`⚠ ${m}`));
  if (깨진것.length) {
    console.log(`🔴 케이라이프디자인 네 문장 — ${깨진것.length}건이 어긋났다`);
    깨진것.forEach((m) => console.log(`   ${m}`));
    process.exitCode = 1;
  } else {
    console.log('✅ 케이라이프디자인 네 문장이 사장님 문장 그대로다');
  }
}
