/** SSE 스트림에서 답 글자만 이어 붙인다 */
export function 스트림에서답뽑기(쌓임) {
  const 글자 = [];
  for (const 줄 of String(쌓임 ?? '').split('\n')) {
    const t = 줄.trim();
    if (!t.startsWith('data:')) continue;
    try {
      const j = JSON.parse(t.slice(5).trim());
      if (j?.type === 'content_block_delta' && typeof j?.delta?.text === 'string') 글자.push(j.delta.text);
    } catch { /* 스트림 조각은 깨진 줄이 섞인다 — 넘어간다 */ }
  }
  return 글자.join('');
}

/**
 * 데스킹 답을 «수정 요약»과 «최종 기사»로 가른다.
 *
 * 프로젝트 지침이 정한 꼴 — ① 📌 데스킹 수정 요약  ② 📰 수정된 최종 기사  ③ 추천 키워드
 * ⛔ 표지를 못 찾으면 «가르지 않는다». 반만 가른 기사를 내보내느니 통째로 넘긴다.
 */
export function 데스킹답가르기(답) {
  const 글 = String(답 ?? '').trim();
  if (!글) return { 요약: '', 기사: '', 갈랐나: false };

  /* ① 1차 답의 꼴 — 「2. 📰 수정된 최종 기사」 */
  const i = 글.indexOf(기사표지);
  if (i >= 0) {
    const 요약 = 글.slice(0, i).trim();
    /* 기사 표지 줄 자체는 떼어 낸다 — 「📰 수정된 최종 기사」는 기사 본문이 아니다 */
    const 뒤 = 글.slice(i);
    const 줄바꿈 = 뒤.indexOf('\n');
    const 기사 = (줄바꿈 < 0 ? '' : 뒤.slice(줄바꿈 + 1)).trim();
    if (기사) return { 요약, 기사, 갈랐나: true };
  }

  /* ② 🔴 2차 답에는 📰 가 없다 (2026-09-26 실측).
     「미뤘던 항목 처리 결과 … --- … **[제목]**」 꼴로 온다.
     ⇒ 📰 가 없으면 «[제목] 줄»을 기사의 첫머리로 본다. */
  const m = 글.match(/\n\s*\**\s*\[제목\]/);
  if (m && m.index > 0) {
    const 요약 = 글.slice(0, m.index).replace(/\n-{3,}\s*$/, '').trim();
    const 기사 = 글.slice(m.index).trim();
    if (기사) return { 요약, 기사, 갈랐나: true };
  }

  return { 요약: '', 기사: 글, 갈랐나: false };
}

/**
 * 데스킹이 낸 기사에서 제목을 집는다 — 메일 제목에 쓴다.
 *
 * 🔴 [2026-09-26 실측] 지침은 `[제목] …` 이라고 적혀 있지만 데스킹은 **다음 줄**에 쓴다 —
 *   ```
 *   [제목]
 *   '무릎' 배재민, 아시안게임 격투게임 결승 진출
 *   ```
 *   같은 줄만 보다가 제목으로 「*」를 집었다. ⇒ 두 꼴을 다 받는다.
 */
export function 데스킹제목뽑기(기사) {
  const 줄들 = String(기사 ?? '').split('\n');
  for (let i = 0; i < 줄들.length; i++) {
    const m = 줄들[i].match(/^\s*\**\s*\[제목\]\s*\**\s*(.*?)\s*\**\s*$/);
    if (!m) continue;
    /* ① 같은 줄에 있으면 그것 */
    const 같은줄 = 다듬기(m[1]);
    if (같은줄) return 같은줄;
    /* ② 없으면 다음 «빈 줄이 아닌» 줄.
       ⛔ 다른 표지([부제목] 등)를 만나면 거기서 멈춘다 — 그 아래는 남의 칸이다. */
    for (let j = i + 1; j < Math.min(i + 4, 줄들.length); j++) {
      const 날것 = String(줄들[j] ?? '').trim().replace(/^\**\s*|\s*\**$/g, '').trim();
      if (/^\[[^\]]+\]/.test(날것)) return '';        /* 다음 칸이 시작됐다 */
      const 다음 = 다듬기(줄들[j]);
      if (다음) return 다음;
    }
    return '';
  }
  return '';
}

/** 굵게 표시와 군더더기를 떼어 낸다 */
function 다듬기(줄) {
  const t = String(줄 ?? '').trim().replace(/^\**\s*/, '').replace(/\s*\**$/, '').trim();
  /* 「*」 하나만 남은 것, 표지 줄은 제목이 아니다 */
  if (!t || /^[*#\-–—]+$/.test(t) || /^\[[^\]]+\]$/.test(t)) return '';
  return t;
}

