/**
 * 🔴🔴 [2026-11-01 · 사장님] **기사 본문이 1,000자를 넘나.**
 *
 * 사장님 — 「중부매일계정에 기사는 1,000자를 넘어야 한다고 지시해」
 *   「넘 데스킹한다는 놀이 기사량도 체크를 안하나?」
 *
 * ⛔ 내 데스킹은 말투·팩트·사진·제목·바이라인을 다 재면서 «기사인가»를 안 쟀다.
 *   세 문장짜리 여자배구 기사가 그대로 나갔다. 재는 자가 없으면 안 재는 것이다.
 *
 * 세는 법 — 제목·부제목·사진 설명·근거 표·추천 키워드는 «기사 몸통이 아니다». 빼고 센다.
 *   공백과 줄바꿈도 빼고 센다. 줄을 많이 띄워 길어 보이게 하는 길을 막는다.
 */
export function 본문글자수(기사) {
  const g = String(기사 ?? '');
  if (!g.trim()) return 0;
  /* [본문] 표지가 있으면 그 아래부터, 없으면 글 전체를 본다 */
  const 시작 = g.indexOf('[본문]');
  let 몸 = 시작 >= 0 ? g.slice(시작 + '[본문]'.length) : g;
  /* 몸통이 끝나는 자리 — 먼저 나오는 표지에서 끊는다 */
  for (const 표 of ['[추천 키워드]', '[해시태그]', '[자료 출처', '[데스킹', '■ 근거', '■ 자가', '추천 키워드']) {
    const i = 몸.indexOf(표);
    if (i >= 0) 몸 = 몸.slice(0, i);
  }
  /* 바이라인과 사진 줄은 기사 몸통이 아니다 */
  몸 = 몸.replace(/\[중부매일[^\]]*\]/g, ' ');
  몸 = 몸.split(/\r?\n/).filter((l) => !/^\s*(사진 제목|사진 설명|사진 주소)\s*:/.test(l)).join('\n');
  return 몸.replace(/\s+/g, '').length;
}

