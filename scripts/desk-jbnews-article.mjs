  /* ⚠ `검색도구` 는 브라우저 «안»에서 쓰이므로 반드시 인자로 넘긴다 —
     바깥 스코프 변수는 evaluate 안에서 보이지 않는다. 빠뜨리면 그 자리에서 터진다. */
  const 만듦 = await 대화만들기(page, 이름);
  if (!만듦.됐나) return { 됐나: false, 까닭: `대화를 못 만들었다 (${만듦.상태})`, 대화: 만듦.대화 };

