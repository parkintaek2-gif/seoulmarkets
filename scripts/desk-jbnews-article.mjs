/**
 * 🔴🔴 [2026-10-06 · 5번] **막은 까닭을 «데스킹의 말 그대로» 뽑는다.**
 *
 * 오늘 「자체기사 미충족」으로 두 건이 막혔는데 자국에는 그 다섯 글자뿐이었다.
 * «무엇이 모자라서» 미충족인지 알려면 내가 기사 본문을 읽고 추측해야 했다.
 * ⛔ 추측은 기록이 아니다. 데스킹이 한 말을 그대로 남겨야 다음 사람이 안 헤맨다.
 *
 * ⚠ 답 «전문»을 쏟지 않는다 — 자국이 커지면 아무도 안 읽는다. 걸린 줄만 집는다.
 * ⚠ 못 집으면 '' 를 준다. ⛔ 빈 글을 「까닭이 없다」로 읽지 않는다 — 「못 집었다」다.
 */
export function 막은까닭전문(답, 최대 = 400) {
  const 글 = String(답 ?? '');
  if (!글.trim()) return '';
  const 결 = [
    /[^\n]*자체\s*기사[^\n]*/g,
    /[^\n]*미충족[^\n]*/g,
    /[^\n]*게재\s*보류[^\n]*/g,
    /[^\n]*보류\s*사유[^\n]*/g,
  ];
  const 줄들 = [];
  for (const 재 of 결) {
    for (const m of 글.matchAll(재)) {
      const 줄 = m[0].replace(/\s+/g, ' ').trim();
      if (줄 && !줄들.includes(줄)) 줄들.push(줄);
    }
  }
  if (!줄들.length) return '';
  const 한글 = 줄들.join(' / ');
  return 한글.length > 최대 ? 한글.slice(0, 최대) + '…' : 한글;
}

