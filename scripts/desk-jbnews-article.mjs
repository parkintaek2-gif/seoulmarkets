  /* 제목이 「프로배구」로만 되어 있으면 어느 부인지 본문으로 가른다 */
  if (/배구/.test(제목) && !/여자/.test(제목)
    && 남자배구팀.filter((t) => g.includes(t)).length >= 2) return '남자배구';
