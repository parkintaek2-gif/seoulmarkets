/**
 * 그 대화에 한 마디 보내고 답을 다 받는다.
 * @param 부모 이어 말할 때 쓰는 앞 메시지 번호. 없으면 대화의 첫 마디다.
 */
export async function 한마디보내기(page, 대화, 프롬프트, 부모 = null) {
  return page.evaluate(async (조직, conv, 프롬프트, 부모, 검색도구) => {
    const r = await fetch(`/api/organizations/${조직}/chat_conversations/${conv}/completion`, {
      method: 'POST',
      headers: { accept: 'text/event-stream', 'content-type': 'application/json' },
      body: JSON.stringify({
        prompt: 프롬프트,
        parent_message_uuid: 부모 || '00000000-0000-4000-8000-000000000000',
        timezone: 'Asia/Seoul',
        attachments: [],
        files: [],
        rendering_mode: 'messages',
        tools: 검색도구,          /* 🔴 이것이 없으면 데스킹이 «검색 없이» 답한다 */
      }),
    });
    if (!r.ok) return { 됐나: false, 상태: r.status, 글: (await r.text()).slice(0, 200) };

    /* 스트림을 끝까지 읽는다. 데스킹은 웹 검색을 하므로 오래 걸린다 */
    const 읽개 = r.body.getReader();
    const 디 = new TextDecoder();
    let 쌓임 = '';
    while (true) {
      const { done, value } = await 읽개.read();
      if (done) break;
      쌓임 += 디.decode(value, { stream: true });
      if (쌓임.length > 4_000_000) break;   /* 터무니없이 길면 끊는다 */
    }
    /* 이어 말하려면 «이번 답»의 번호가 필요하다 — message_start 에 들어 있다 */
    let 이번번호 = null;
    for (const 줄 of 쌓임.split('\n')) {
      const t = 줄.trim();
      if (!t.startsWith('data:')) continue;
      try {
        const j = JSON.parse(t.slice(5).trim());
        if (j?.type === 'message_start' && j?.message?.uuid) { 이번번호 = j.message.uuid; break; }
      } catch { /* 넘어간다 */ }
    }
    return { 됐나: true, 스트림: 쌓임, 번호: 이번번호 };
  }, 조직, 대화, 프롬프트, 부모, 검색도구);
}

