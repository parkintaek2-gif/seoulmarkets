export function 수로(v) {
  if (v === null || v === undefined || v === '') return null;
  const n = Number(v);
  return Number.isFinite(n) ? n : null;
}

/**
 * 두 판을 이름으로 «하나만» 남기고 합친다.
 * ⛔ 값이 다르면 조용히 하나를 고르지 않는다 — 다른 것을 세어서 알린다.
 */
export function 합치기(판들) {
  const 표 = new Map();
  let 겹친수 = 0, 값이다른수 = 0;
  for (const { 판, 항목들 } of 판들) {
    for (const x of 항목들) {
      const n = String(x?.이름 ?? '').trim();
      if (!n) continue;
      if (!표.has(n)) { 표.set(n, { ...x, 판: [판] }); continue; }
      겹친수 += 1;
      const 있던것 = 표.get(n);
      if (수로(있던것.하루평균) !== 수로(x.하루평균)) 값이다른수 += 1;
      있던것.판.push(판);
    }
  }
  return { 사람들: [...표.values()], 겹친수, 값이다른수 };
}

/**
 * 바닥(하루평균 최소값)을 주면 그 위에서 «상승배수 1위»가 누구인가.
 * @returns {{바닥:number, 셈수:number, 맨위:object[]}|null}
 */
export function 바닥으로재기(사람들, 바닥) {
  const v = 사람들
    .filter((x) => (수로(x.하루평균) ?? -1) >= 바닥 && 수로(x.상승배수) !== null)
    .sort((a, b) => 수로(b.상승배수) - 수로(a.상승배수));
  if (!v.length) return { 바닥, 셈수: 0, 맨위: [] };
  return {
    바닥,
    셈수: v.length,
    맨위: v.slice(0, 3).map((x) => ({
      이름: x.이름, 배수: 수로(x.상승배수), 하루: 수로(x.하루평균),
      최고조회: 수로(x.최고조회), 최고일: x.최고일 ?? null, 판: x.판,
      뒤7일: 수로(x.최근7일),
      /* ⭐ 분모를 «드러낸다». 배수만 보이면 「1회 → 654회」인지 「149회 → 5,424회」인지
         구별이 안 된다. 이 기사의 요점이 바로 그 분모다.
         앞7일 = 뒤7일 ÷ 배수 (수집기가 그렇게 만들었으니 되돌릴 수 있다) */
      앞7일: (수로(x.최근7일) !== null && 수로(x.상승배수) > 0)
        ? Math.round(수로(x.최근7일) / 수로(x.상승배수)) : null,
    })),
  };
}

/** 최근 7일이 30일 평균의 몇 배인가 — 「지금 오르고 있나」 */
export function 지금오르나(x) {
  const 최근 = 수로(x?.최근7일);
  const 하루 = 수로(x?.하루평균);
  if (최근 === null || 하루 === null || 하루 <= 0) return null;
  return +((최근 / 7) / 하루).toFixed(2);
}

