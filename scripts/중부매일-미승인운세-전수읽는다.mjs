import fs from 'node:fs';
import { 상태읽기 } from './중부매일-기사상태-읽는다.mjs';
import { 제목에서날짜, 갈래집기 } from './중부매일-미승인운세-읽는다.mjs';

export const 읽을곳 = 'docs/자국/중부매일-미승인운세-20261125.json';
export const 낼곳 = 'docs/자국/중부매일-미승인운세-상태-20261125.json';

/** 노출날이 제목의 월·일과 맞나 — 틀린 것이 「난리」의 원인이다 */
export function 노출날이제목과맞나(제목, 노출날) {
  const d = 제목에서날짜(제목);
  if (!d) return null;                       /* ⛔ 못 집으면 null — 맞다고도 틀리다고도 안 한다 */
  const m = String(노출날 ?? '').match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!m) return null;
  return Number(m[2]) === d.월 && Number(m[3]) === d.일;
}

function 직접실행인가() { return (process.argv[1] || '').includes('중부매일-미승인운세-전수읽는다'); }

if (직접실행인가() && process.argv.includes('--자가시험')) {
  const 잰다 = []; const 본다 = (이름, v) => 잰다.push([이름, !!v]);
  본다('제목과 노출날이 맞으면 참', 노출날이제목과맞나('[오늘의운세] 1월 2일', '2026-01-02') === true);
  본다('다르면 거짓', 노출날이제목과맞나('[오늘의운세] 1월 2일', '2026-11-24') === false);
  본다('해가 달라도 월·일만 본다', 노출날이제목과맞나('[오늘의운세] 1월 2일', '2027-01-02') === true);
  본다('⛔ 노출날이 비면 null — 거짓이 아니다', 노출날이제목과맞나('[오늘의운세] 1월 2일', '') === null);
  본다('⛔ 제목에 날짜가 없으면 null', 노출날이제목과맞나('[포토] 첫눈', '2026-01-02') === null);
  본다('⛔ 꼴이 다르면 null', 노출날이제목과맞나('[오늘의운세] 1월 2일', '2026/01/02') === null);
  const 진 = 잰다.filter(([, v]) => !v);
  for (const [이름, v] of 잰다) console.log((v ? '  ✅ ' : '  🔴 ') + 이름);
  console.log(진.length ? ('🔴 ' + 진.length + '가지 깨졌다') : ('✅ 자가시험 ' + 잰다.length + ' 통과'));
  process.exit(진.length ? 1 : 0);
}

if (직접실행인가() && !process.argv.includes('--자가시험')) {
  const 목록 = JSON.parse(fs.readFileSync(읽을곳, 'utf8'));
  const 결과 = [];
  let i = 0;
  for (const o of 목록) {
    i += 1;
    const r = await 상태읽기(o.번호);
    const 상태 = !r ? '못읽음' : (r.승인 ? '승인' : r.미승인 ? '미승인' : r.반려 ? '반려' : '모름');
    const 한줄 = {
      번호: o.번호, 제목: o.제목, 갈래: 갈래집기(o.제목),
      상태, 노출날: r ? r.노출날 : '', 노출시각: r ? r.노출시각 : '',
      제목날짜: 제목에서날짜(o.제목),
      날맞나: r ? 노출날이제목과맞나(o.제목, r.노출날) : null,
    };
    결과.push(한줄);
    console.log(i + '/' + 목록.length + '  ' + o.번호 + '  ' + 상태
      + '  노출 ' + (r ? (r.노출날 + ' ' + r.노출시각) : '?')
      + '  날맞나 ' + String(한줄.날맞나)
      + '  ' + String(o.제목).slice(0, 34));
    fs.writeFileSync(낼곳, JSON.stringify(결과, null, 1), 'utf8');
  }
  const 센다 = (f) => 결과.filter(f).length;
  console.log('');
  console.log('■ 전부 ' + 결과.length + '건');
  console.log('   승인 ' + 센다((x) => x.상태 === '승인')
    + ' · 미승인 ' + 센다((x) => x.상태 === '미승인')
    + ' · 반려 ' + 센다((x) => x.상태 === '반려')
    + ' · 못읽음 ' + 센다((x) => x.상태 === '못읽음'));
  console.log('   노출날이 제목과 맞는 것 ' + 센다((x) => x.날맞나 === true)
    + ' · 어긋난 것 ' + 센다((x) => x.날맞나 === false)
    + ' · 못 잰 것 ' + 센다((x) => x.날맞나 === null));
  console.log('■ 적었다 — ' + 낼곳);
}
