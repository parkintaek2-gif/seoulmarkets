/** 숫자만 뽑아 잇는다 — 같은 것을 두 꼴로 적었나를 재는 «뼈대»다 */
export function 숫자뼈대(글) { return String(글 ?? '').replace(/[^0-9]/g, ''); }

/**
 * **「두 꼴을 같이 쓴다」 — 같은 번호를 로마자 꼴로 «먼저» 적고 한국어 꼴을 뒤에 붙인 자리인가.**
 *
 * 🔴 [2026-09-11 · 사장님 지시] 「**두 개를 같이 써**…다국어 홈페이지는 영어를 앞에,
 *   한국어를 뒤에…백년지도만 한국어 앞에, 영어 뒤에」. 그래서 영문 꼬리말이 이렇게 됐다 —
 *     Mail-order licence 2026-Sejong-0591 (Sejong) · 2026-세종-0591 (세종특별자치시)
 *   앞 꼴이 곧 뒤 꼴의 뜻이다. 그런데 그 뜻이 «괄호»도 «줄표»도 아니라 **가운뎃점 건너**에
 *   있어서 옛 규칙이 못 봤고, 영문 지면 2,156장이 한꺼번에 빨강이 됐다.
 *
 * ⛔ 신고번호를 예외로 박지 않는다 — 2026-09-04 에 같은 유혹을 이미 물리쳤다(아래 주석).
 *   대신 규칙을 넓힌다: **가운뎃점 바로 앞에 «숫자뼈대가 같은» 로마자 꼴이 있으면 뜻이 있다.**
 *
 * ⭐ 울타리가 둘이다. 이것이 없으면 규칙이 아니라 구멍이 된다 —
 *   1. 가운뎃점 «바로 앞»의 한 토막만 본다. 창을 넓혀 아무 로마자나 짝으로 삼지 않는다
 *   2. 숫자뼈대가 «똑같아야» 한다. 그래서 `Distribution · 배급` 같은 목록은 통과하지 못한다
 *
 * ⚠ **로마자가 앞에 오는 것만 본다.** 한국어를 앞에 두는 꼴(`2026-세종-0591 … · … (Sejong)`)은
 *   백년지도 «한국어» 지면에만 쓰고, 이 자는 영문 지면만 잰다. 그러니 영문 지면에서 그 꼴을
 *   만나면 잡히는 것이 맞다 — 사장님 지시가 「다국어는 영어를 앞에」이기 때문이다.
 */
export function 두꼴병기인가(글, 자리, 낱말) {
  const 앞 = 글.slice(Math.max(0, 자리 - 70), 자리);
  /* 한국어 꼴의 «앞머리 숫자»까지 내 것으로 센다 — `2026-`세종`-0591` 처럼 앞에 붙는다 */
  const 앞머리 = /[0-9][0-9\s\-–—]{0,11}$/.exec(앞);
  const 나 = 숫자뼈대((앞머리 ? 앞머리[0] : '') + 낱말);
  if (!나) return false;              /* 숫자가 없는 꼴은 이 규칙으로 봐주지 않는다 */
  const 짝 = /([0-9A-Za-z][0-9A-Za-z\-.&]*[A-Za-z][0-9A-Za-z\-.&]*)\s*(?:\([^)]{0,40}\))?\s*[·|]\s*[0-9\s\-–—]{0,12}$/.exec(앞);
  return !!짝 && 숫자뼈대(짝[1]) === 나;
}

/**
 * 🔴🔴 [2026-11-14 · 5번] **이 자가 «한국어 지면»까지 재고 있었다.**
 *
 * 빨강 128장 가운데 120장 남짓이 `ko/…` — 케이리뷰의 **한국어** 지면이다.
 * 한국어로 쓰는 것이 맞는 자리인데 「한국어가 샜다」로 찍혀서, 진짜 샌 영문 지면
 * 여덟 장이 그 속에 묻혀 있었다. 그리고 이 검사가 **막는 검사**라 KCW 배포가 섰다.
 *
 * ⛔ 길 이름(`ko/`)으로 가르지 않는다 — 폴더는 언제든 바뀐다.
 * ⇒ **지면이 스스로 밝힌 말**(`<html lang="…">`)로 가른다. 그것이 손님 브라우저와
 *   구글이 읽는 것과 같은 값이다.
 * ⚠ lang 이 없는 지면은 «영어로 본다» — 못 밝힌 것을 봐주면 그쪽으로 다 빠져나간다.
 */
export function 영어지면인가(글) {
  const m = /<html[^>]*\blang\s*=\s*["']([^"']+)["']/i.exec(String(글 ?? ''));
  if (!m) return true;                       /* 안 밝혔으면 영어로 보고 잰다 */
  return !/^ko\b/i.test(m[1].trim());
}

/**
 * 🔴🔴 [2026-11-14 · 5번] **인용한 «원문»을 누출로 세고 있었다.**
 *
 * 빨강 다섯 장이 전부 같은 꼴이었다 — 한국 기사의 제목을 그대로 따 오고, 닫는
 * 따옴표 «바로 뒤»에 괄호로 영어 뜻을 붙인 자리다:
 *
 * ```
 *   '방탄소년단 진, 마이원픽 135주 연속 1위…' (BTS's Jin: 135th consecutive week at No. 1 …)
 *   Korean '민니 (가수)', Spanish 'Minnie (cantante)'
 *   …renders the name as 발타, which transliterates back as Balta.
 * ```
 *
 * ⭐ 이 자의 머리글이 처음부터 「출처를 밝히는 원문 병기는 정당하고 오히려 옳다」고
 *   적어 두었다. 다만 **짧은 낱말 짝**(`배급 (Distribution)`)만 알아보고,
 *   «문장을 통째로 딴 뒤 뜻을 붙인 꼴»은 못 알아봤다 — 따옴표 안이 길어서다.
 *
 * ⛔ 길이로 봐주지 않는다. **따옴표와 뜻을 둘 다 요구한다** — 하나만으로는 통과 못 한다.
 *   그래야 「그냥 길게 쓴 한국어」가 이 문으로 빠져나가지 못한다.
 */
export function 딴말에뜻이붙었나(글, 자리, 낱말) {
  const g = String(글 ?? '');
  const 뒤 = g.slice(자리 + 낱말.length, 자리 + 낱말.length + 400);
  const 앞 = g.slice(Math.max(0, 자리 - 400), 자리);

  /* ① 따 온 말 뒤에 괄호로 뜻을 붙였나 — …한국어…' (English …) */
  const 닫는따옴표 = /^[^'"“”‘’]{0,300}["'“”’]\s*[(（]\s*[^)）]{0,10}[A-Za-z]/.test(뒤);
  const 여는따옴표 = /["'“”‘’][^'"“”‘’]{0,300}$/.test(앞);
  if (여는따옴표 && 닫는따옴표) return true;

  /* ② 어느 말인지 영어로 «이름표»를 달고 딴 자리 — Korean '민니 (가수)' */
  if (/\b[A-Z][a-z]{2,}\s*[:：]?\s*["'“”‘’][^'"“”‘’]{0,40}$/.test(앞)) return true;

  /* ③ 뒤에서 «옮긴 말»이라고 말해 주는 자리 — transliterates back as Balta */
  if (/^[^.]{0,90}\b(transliterat\w*|romani[sz]\w*|spelled|rendered|reads?|means)\b[^.]{0,30}[A-Za-z]{2,}/i.test(뒤)) return true;

  return false;
}

/** 한국어 낱말 하나가 **뜻을 달고 있는가**. 앞뒤 어느 쪽이든 로마자 짝이 있으면 정당하다 */
export function 뜻이있나(글, 자리, 낱말) {
  const 뒤 = 글.slice(자리 + 낱말.length, 자리 + 낱말.length + 26);
  const 앞 = 글.slice(Math.max(0, 자리 - 90), 자리);
  /**
   * 🔴🔴 [2026-09-04 · 5번] **이 자가 2,796장 가운데 2,795장에서 빨강이었다.**
   *   ─────────────────────────────────────────────────────────────────────
   *   전부 한 가지 때문이었다 — 꼬리말의 법정 신고번호 **「Mail-order licence 2026-세종-0591 (Sejong)」**.
   *   「세종」 바로 뒤가 `-0591 (Sejong)` 이라, 옛 무늬(`한국어 뒤 곧바로 괄호`)에 안 걸렸다.
   *
   *   ⛔ **그래서 이 검사는 사실상 꺼져 있었다.** 모든 지면이 빨강이면 아무도 «새 빨강»을 못 본다.
   *     ⭐ 오늘 아침 표 약속 검사는 «우연히 통과»해서 아무것도 보증하지 못하고 있었다.
   *       이 자는 «전부 걸려서» 아무것도 보증하지 못하고 있었다. **반대인데 결과가 같다.**
   *   🔴 그 사이에 내가 실제로 한국어를 흘렸다 — `/surge-floor` 에 자료 파일의 우리말 메모
   *     세 줄(「왜 튀었나 …」)을 그대로 뿌렸다. 이 자가 초록이었다면 바로 잡혔을 것이다.
   *
   *   ✅ 고친 방식 — 신고번호를 «예외로 박지 않았다». 그것은 이 한 줄만 눈감는 것이고,
   *     같은 꼴이 또 나오면 또 못 잡는다. 대신 **「한국어와 로마자 뜻 사이에 숫자·붙임표가
   *     끼어도 뜻이 있는 것으로 본다」**로 규칙을 넓혔다. 신고번호가 바로 그 꼴이다.
   *   ⚠ 넓히면 느슨해진다. 그래서 여전히 **괄호나 줄표를 요구한다** — 「배급 Distribution」처럼
   *     그냥 이어 붙인 것은 통과되지 않는다. 아래 자가시험이 그 경계를 지킨다.
   */
  /* 🔴 [2026-09-07] 괄호와 글자 사이에 «따옴표»가 오는 것을 허용한다 —
     `갱신불가 (“cannot be updated”)` 꼴. 옮긴 말을 따옴표로 감싸는 것은 옳은 글쓰기이고,
     그것 때문에 검사가 서면 사람이 따옴표를 지우게 된다. 지울 것은 따옴표가 아니다. */
  if (/^[\s0-9)」\-–—]{0,12}[(–—-]\s*["'“”‘’]?\s*[A-Za-z]/.test(뒤)) return true;   // 원문 → (뜻)
  /**
   * ⭐ **괄호 안이면 통과다.** 「Content Industry Survey (한국콘텐츠진흥원 콘텐츠산업조사)」 처럼
   *   괄호 안에 원문이 **여러 낱말** 들어가는 것이 정상이다. 처음엔 괄호 바로 뒤 한 낱말만
   *   봐서, 둘째 낱말부터 빨강으로 셌다. ⛔ 자가 거칠면 옳은 것을 고치게 만든다.
   *   여는 괄호를 만나기 전에 닫는 괄호가 없으면 「아직 괄호 안」이다.
   */
  const 열림 = Math.max(앞.lastIndexOf('('), 앞.lastIndexOf('「'));
  const 닫힘 = Math.max(앞.lastIndexOf(')'), 앞.lastIndexOf('」'));
  if (열림 > 닫힘 && /[A-Za-z]/.test(앞.slice(0, 열림).slice(-40))) return true;
  /* 🔴 [2026-09-11] 가운뎃점 건너에 «같은 것의 로마자 꼴»이 있는 자리 (사장님 「두 개를 같이 써」) */
  if (두꼴병기인가(글, 자리, 낱말)) return true;
  /* 🔴 [2026-11-14] 따 온 원문에 뜻을 붙인 자리 — 이 자의 머리글이 「옳다」고 적어 둔 꼴이다 */
  if (딴말에뜻이붙었나(글, 자리, 낱말)) return true;
  return false;
}

/**
 * 한국어 이름이 «어디서 끝나나»를 찾는다 — 무늬의 열여섯 글자 한도를 넘어서.
 *
 * 🔴 [2026-09-07] 이것이 없어서 긴 이름이 토막 나고, **앞 토막이 맨몸으로 걸렸다.**
 *   공공데이터 자료 이름은 스무 글자를 넘고, 안에 `(K-POP)` 처럼 괄호가 끼기도 한다.
 *
 * ⛔ 아무 데까지나 밀지 않는다. 한국어 이름의 «몸»으로 볼 것만 넘어간다 —
 *   한국어 · 공백 · 숫자 · 붙임표 · 그리고 «닫히는» 괄호 안의 로마자(`(K-POP)`).
 *   마침표·쉼표·낫표를 만나면 거기서 멈춘다. 그래야 다음 문장까지 삼키지 않는다.
 */
export function 이름끝(글, 자리) {
  const s = String(글 ?? '');
  let i = 자리;
  while (i < s.length) {
    const 남 = s.slice(i);
    /* 이름의 몸은 «한국어»다. 먼저 한국어를 다 넘는다 */
    const m0 = /^[가-힣]+/.exec(남);
    if (m0) { i += m0[0].length; continue; }
    /**
     * 🔴 한국어 사이에 끼는 숫자·공백·붙임표는 **열두 자까지만** 넘어간다.
     *   이 자가 2026-09-04 에 정한 선이 그것이다 — 법정 신고번호
     *   `2026-세종-0591 (Sejong)` 을 뜻 있는 것으로 보려고 열둘까지 열어 뒀다.
     * ⛔ 한도를 없애면 그 선이 사라진다. `배급 0000000000000000 (Distribution)` 처럼
     *   먼 로마자가 뜻으로 통과해 버린다 — 자가시험이 그것을 지키고 있다.
     */
    const m1 = /^[0-9\s\-–—]+/.exec(남);
    if (m1 && m1[0].length <= 12) { i += m1[0].length; continue; }
    /* 이름 «안»에 든 괄호 — 반드시 닫혀야 넘어간다. 뜻 괄호와 헷갈리지 않게 «로마자만» 든 것으로 좁힌다 */
    /* ⛔ 뒤에 «한국어»가 이어질 때만 넘어간다. 공백·숫자까지 넘으면 «뜻 괄호»를 삼킨다 —
       2026-09-07 에 그렇게 만들었다가 멀쩡한 시험 여섯이 깨졌다. */
    const m2 = /^\([A-Za-z0-9\s\-.&]+\)\s*(?=[가-힣])/.exec(남);
    if (m2) { i += m2[0].length; continue; }
    /**
     * 🔴 [2026-10-04 05:2x] 이름 «안»에 든 **한국어만 든 괄호** — `전산업생산지수(원지수)`.
     *   여기서 멈추면 앞 토막만 보고 「뜻이 없다」고 한다. 실제로는 그 뒤에 뜻이 있었다 —
     *   `전산업생산지수(원지수) — All-industry production index (original index)`.
     *   2번이 낸 멀쩡한 지면이 이것 때문에 빨강이었다.
     * ⛔ **뒤에 「 — 영어」가 이어질 때만** 넘긴다. 처음엔 뒤 조건 없이 넘겼더니
     *   `은행대출금 연체율(1개월 이상) (table 901Y12)` 까지 통과했다 — `(table 901Y12)` 를
     *   «뜻»으로 읽은 것이다. 표 번호는 뜻이 아니다. 그 한 줄로 사이트 빨강이 2건에서
     *   0건이 됐고, **진짜 누출을 놓치는** 자가 될 뻔했다.
     * ⚠ 넓히는 고침은 넓힌 만큼 «놓치는 것»이 생긴다. 고친 뒤 빨강이 줄면 먼저 의심한다.
     */
    const m2b = /^\([가-힣0-9\s·,/\-]+\)(?=\s*[—–-]\s*[A-Za-z])/.exec(남);
    if (m2b) { i += m2b[0].length; continue; }
    /**
     * 🔴 [2026-09-07] 이름 «안»에 든 로마자 낱말 — `미국의 K-POP 음원 순위 데이터`.
     *   여기서 멈추면 앞 토막(`미국의`)만 보고 「뜻이 없다」고 한다. 뜻은 이름 끝에 있다.
     * ⛔ **뒤에 한국어가 이어질 때만** 넘어간다. 그래서 `배급 Distribution` 처럼
     *   로마자가 «끝»에 오는 꼴은 그대로 걸린다 — 그것이 진짜 누출이다.
     */
    const m3 = /^[A-Za-z][A-Za-z0-9\-.&]*[\s]*(?=[가-힣])/.exec(남);
    if (m3) { i += m3[0].length; continue; }
    break;
  }
  /* ⛔ 뒤에 붙은 공백·붙임표는 이름이 아니다. 되돌린다 */
  while (i > 자리 && /[\s\-–—]/.test(s[i - 1])) i -= 1;
  return i;
}

/**
 * 🔴🔴 [2026-11-14 · 5번] **글자를 «지우고» 재고 있었다.**
 *
 * 따옴표는 지어낸 글에서는 `'` 지만, 손님이 받는 HTML 에서는 `&#39;` 다.
 * 이 자는 `&[a-z]+;` 만 **빈칸으로 지우고** 숫자 꼴(`&#39;`)은 그대로 뒀다.
 * 그래서 「따 온 원문 뒤에 뜻이 붙었나」를 보는 규칙이 따옴표를 못 찾아,
 * 뜻이 멀쩡히 붙은 인용 네 장이 누출로 찍혔다.
 *
 * ⭐ **손님이 보는 글자로 되돌려 놓고 잰다** — 검사는 손님이 겪는 것을 재야 한다.
 * ⛔ 지우지 않는다. 지우면 그 자리에 무엇이 있었는지 영영 모른다.
 * ⚠ 태그를 «먼저» 벗기고 그 다음에 되돌린다 — 순서를 바꾸면 &lt;b&gt; 가 태그가 된다.
 */
export function 글자로되돌린다(글) {
  return String(글 ?? '')
    .replace(/&(?:#0*39|#x0*27|apos|lsquo|rsquo);/gi, "'")
    .replace(/&(?:#0*34|#x0*22|quot|ldquo|rdquo);/gi, '"')
    .replace(/&(?:#0*40|lpar);/gi, '(')
    .replace(/&(?:#0*41|rpar);/gi, ')')
    .replace(/&(?:nbsp|#0*160);/gi, ' ')
    .replace(/&(?:#0*8230|hellip);/gi, '…')
    .replace(/&(?:#0*45|ndash|mdash|#0*8211|#0*8212);/gi, '-')
    .replace(/&(?:amp|#0*38);/gi, '&')
    /* ⛔ 남은 것은 빈칸으로 둔다 — 알아보지 못한 글자를 지어내지 않는다 */
    .replace(/&[a-zA-Z]+;|&#\d+;|&#x[0-9a-fA-F]+;/g, ' ');
}

/** 지면 하나에서 **뜻 없는 한국어**만 뽑는다 */
export function 맨몸한국어(글) {
  const 벗김 = 글자로되돌린다(
    String(글 ?? '').replace(/<script[\s\S]*?<\/script>/g, ' ').replace(/<style[\s\S]*?<\/style>/g, ' ')
      .replace(/<[^>]+>/g, ' '),
  ).replace(/\s+/g, ' ');
  const 맨몸 = [];
  const 본끝 = new Set();
  for (const m of 벗김.matchAll(/[가-힣][가-힣\s]{0,15}/g)) {
    const 낱 = m[0].trim();
    if (!낱) continue;
    /* 🔴 [2026-09-07] 토막이 아니라 «이름 끝»에서 뜻을 찾는다.
       이렇게 안 하면 긴 이름의 앞 토막이 늘 맨몸으로 걸린다 — 자가 유난해지고, 사람이 끈다. */
    const 끝 = 이름끝(벗김, m.index);
    /* 한 이름을 여러 토막으로 두 번 세지 않는다 */
    if (본끝.has(끝) ) { continue; }
    if (!뜻이있나(벗김, m.index, 벗김.slice(m.index, 끝))) { 맨몸.push(낱); 본끝.add(끝); }
    else 본끝.add(끝);
  }
  return [...new Set(맨몸)];
}

