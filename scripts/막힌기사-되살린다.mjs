/**
 * 막힌기사-되살린다.mjs — **데스킹에 막힌 기사를 버리지 않고 회차에 되돌린다.**
 *
 * ── 🔴 왜 (2026-10-17 · 사장님) ───────────────────────────────────
 * 「**중부매일계정으로 여러 건 걸어놓은 예약 기사들 항상 제 시간에 반드시 보내게 조치해**」
 *
 * 거두는 자는 매시 23분에 «돌고 있었다». 안 돈 것이 아니라 돌면서 막혔다.
 * 거둠 로그가 스스로 적어 두었다 —
 *   「🔴 데스킹에 막힌 뒤 «그대로 버려진» 기사가 최근 사흘에 4건 있다
 *      10-14 10시 · 10-14 11시 · 10-16 09시 · 10-16 11시
 *    ⛔ 막는 것은 옳다. **막고 잊는 것**이 흠이다 — 사장님은 그 기사를 못 받으셨다.
 *    ⚠ 까닭이 늘 같으면 «회차 지시문»을 고쳐야 끝난다.」
 *
 * ⭐ 그래서 이 자가 한다 — 막힌 까닭을 «그 회차 대화에 되돌려» 다시 쓰게 한다.
 *   사람이 보고 손으로 되돌리는 구조를 만들지 않는다. 기억에 맡긴 것은 잊힌다.
 *
 * ⛔ 되돌릴 수 «없는» 까닭이 있다 — 그것까지 되돌리면 같은 글이 되풀이해서 돈다.
 *   · 안 치른 경기      → 경기가 끝나야 쓴다. 되돌려도 소용없다
 *   · 중복             → 소재 자체가 겹친다. 다시 써도 겹친다
 *   되돌릴 수 있는 것은 «글을 고치면 풀리는» 까닭뿐이다.
 *
 * 쓰는 법
 *   node scripts/막힌기사-되살린다.mjs --회차 09 --까닭 "자체기사 미충족 …"
 *   node scripts/막힌기사-되살린다.mjs --자가시험
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

export const 뿌리 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * 되돌려서 풀 수 «없는» 까닭 — 글을 고쳐도 안 풀린다.
 * ⛔ 이 목록을 넓히지 않는다. 넓히면 고칠 수 있는 것까지 버려진다.
 */
export const 못되돌리는까닭 = [
  '안 치른 경기',
  '중복',
  '같은 경기',
  '소재가 같',
];

export function 되돌릴수있나(까닭) {
  const g = String(까닭 ?? '').trim();
  if (!g) return false;                       /* 까닭을 못 집었으면 되돌리지 않는다 */
  return !못되돌리는까닭.some((말) => g.includes(말));
}

