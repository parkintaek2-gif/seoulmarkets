#!/usr/bin/env node
/**
 * 고친다-고유어수사를-숫자로.mjs — **「예순 가지」를 「60가지」로 바꾼다.**
 * ═══════════════════════════════════════════════════════════════════════════
 * 🔴🔴 [2026-11-11 · 사장님] 손 없는 날 기사에서 「사흘」「여덟 달」을 짚어 주셨고,
 *   「순한글 또는 우리말 사전에서 순한글인 지 검수를 해」라고 이르셨다.
 *   표준국어대사전에 물어 보니 예순·다섯·여섯·일곱·여덟·보름·열흘이 모두 고유어였다.
 *
 * ⛔ **큰따옴표 안은 건드리지 않는다.** 사전과 법령과 판결문을 인용한 자리다.
 *   인용을 고치면 그것은 더 이상 인용이 아니다.
 * ⛔ 「열두 띠」처럼 수사가 이름의 일부인 자리는 손대지 않는다 — `그냥둔다` 에 적어 둔다.
 *
 * 쓰는 법
 *   node scripts/고친다-고유어수사를-숫자로.mjs <파일...> [--고친다]
 *   node scripts/고친다-고유어수사를-숫자로.mjs --자가시험
 *   (`--고친다` 가 없으면 무엇이 바뀌는지만 보여 준다)
 */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

/** 고유어 수사 → 숫자 */
export const 수사 = {
  하나: '1', 둘: '2', 셋: '3', 넷: '4', 다섯: '5', 여섯: '6', 일곱: '7',
  여덟: '8', 아홉: '9', 열: '10', 열하나: '11', 열둘: '12', 열셋: '13',
  열넷: '14', 열다섯: '15', 열여섯: '16', 열일곱: '17', 열여덟: '18',
  열아홉: '19', 스물: '20', 스물하나: '21', 스물셋: '23', 서른: '30',
  마흔: '40', 쉰: '50', 예순: '60', 일흔: '70', 여든: '80', 아흔: '90',
  쉰다섯: '55', 스물한: '21', 스물세: '23', 서른여덟: '38',
};

/** 수사 뒤에 붙으면 바꾸는 단위 — 띄어쓰기는 붙여 쓴다 (60가지) */
export const 단위 = ['가지', '개', '번', '장', '쪽', '해', '칸', '줄', '건', '곳'];

/** ⛔ 이름의 일부인 자리 — 손대지 않는다 */
export const 그냥둔다 = [
  '열두 띠', '열두 달', '열두 번', '여덟 글자', '네 기둥', '두 글자', '열두 칸',
  '세 띠', '열두 가지', '여덟 가지',
];

/** 큰따옴표로 묶인 자리를 찾아 둔다 — 그 안은 안 고친다 */
export function 인용자리(글) {
  const 자리 = [];
  const 꼴 = /"[^"]*"/g;
  let m;
  while ((m = 꼴.exec(String(글 ?? ''))) !== null) 자리.push([m.index, m.index + m[0].length]);
  return 자리;
}

export function 인용안인가(자리들, i) {
  return !(자리들 ?? []).some(([a, b]) => i >= a && i < b);
}

export function 고치기(글) {
  let g = String(글 ?? '');
  const 바뀐것 = [];
  for (const [말, 수] of Object.entries(수사)) {
    for (const u of 단위) {
      for (const 사이 of [' ', '']) {
        const 찾을것 = 말 + 사이 + u;
        if (그냥둔다.includes(찾을것)) continue;
        let i = -1;
        while ((i = g.indexOf(찾을것, i + 1)) !== -1) {
          /* ⛔ 앞에 한글이 붙어 있으면 다른 낱말의 일부다 (쉰다섯의 「다섯」) */
          const 앞 = i > 0 ? g[i - 1] : ' ';
          if (/[가-힣]/.test(앞)) continue;
          if (!인용안인가(인용자리(g), i)) continue;
          const 새말 = 수 + u;
          g = g.slice(0, i) + 새말 + g.slice(i + 찾을것.length);
          바뀐것.push(찾을것 + ' → ' + 새말);
          i = -1; /* 글이 바뀌었으니 처음부터 다시 */
        }
      }
    }
  }
  return { 글: g, 바뀐것 };
}

function 주다() {
  if (process.argv.includes('--자가시험')) return 자가시험();
  const 고친다 = process.argv.includes('--고친다');
  const 길들 = process.argv.slice(2).filter((x) => !x.startsWith('--'));
  if (!길들.length) { console.log('쓰는 법: node scripts/고친다-고유어수사를-숫자로.mjs <파일...> [--고친다]'); process.exit(1); }
  let 모두 = 0;
  for (const 길 of 길들) {
    const 원본 = fs.readFileSync(길, 'utf8');
    const r = 고치기(원본);
    if (!r.바뀐것.length) continue;
    console.log('■ ' + 길 + ' — ' + r.바뀐것.length + '곳');
    for (const x of [...new Set(r.바뀐것)]) console.log('   ' + x);
    모두 += r.바뀐것.length;
    if (고친다) fs.writeFileSync(길, r.글, 'utf8');
  }
  console.log('\n■ 모두 ' + 모두 + '곳' + (고친다 ? ' — 고쳤다' : ' — 아직 안 고쳤다. --고친다 를 붙인다'));
  process.exit(0);
}

function 자가시험() {
  let 통 = 0; let 탈 = 0;
  const 검 = (이름, 참) => { if (참) { 통++; console.log('✅', 이름); } else { 탈++; console.log('🔴', 이름); } };

  검('🔴 「예순 가지」를 「60가지」로', 고치기('예순 가지가 나왔다').글 === '60가지가 나왔다');
  검('🔴 붙여 쓴 것도 바꾼다', 고치기('다섯개를 세었다').글 === '5개를 세었다');
  검('🔴🔴 큰따옴표 안은 건드리지 않는다',
    고치기('사전은 "예순 가지"라고 적었다').글 === '사전은 "예순 가지"라고 적었다');
  검('⛔ 이름의 일부는 손대지 않는다',
    고치기('열두 띠 가운데').글 === '열두 띠 가운데'
    && 고치기('여덟 글자를 적는다').글 === '여덟 글자를 적는다');
  검('⛔ 다른 낱말 속의 수사를 안 집는다', 고치기('쉰다섯 가지').글 === '55가지');
  검('⛔ 단위가 없으면 안 바꾼다', 고치기('다섯 사람이 왔다').글 === '다섯 사람이 왔다');
  검('🔴 바꾼 자리를 적어 준다', 고치기('일곱 번 돌았다').바뀐것.length === 1);
  검('⛔ 빈 글에 안 터진다', 고치기(null).글 === '' && 고치기('').바뀐것.length === 0);
  검('🔴 인용 자리를 찾는다', 인용자리('가"나"다').length === 1);
  검('⛔ 인용 밖은 인용이 아니다', 인용안인가([[1, 4]], 0) === true && 인용안인가([[1, 4]], 2) === false);

  const 나 = fs.readFileSync(fileURLToPath(import.meta.url), 'utf8');
  검('🔴 사장님 지시를 적어 두었다', 나.includes('우리말 사전에서 순한글인 지 검수를 해'));

  console.log(탈 ? '\n🔴 자가시험 ' + 탈 + '건 탈' : '\n✅ 자가시험 ' + 통 + ' 통과');
  process.exit(탈 ? 1 : 0);
}

const 나를직접돌렸나 = String(process.argv[1] ?? '').endsWith('고친다-고유어수사를-숫자로.mjs');
if (나를직접돌렸나) 주다();
