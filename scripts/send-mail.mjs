export const 서술형종성 = [4, 20];   /* 4 = ㄴ (…ㄴ다/는다) · 20 = ㅆ (…했다/었다) */

export function 제목서술형인가(제목) {
  let g = String(제목 ?? '').trim();
  if (!g) return false;
  if (/["'’”」』]$/.test(g)) return false;   /* 인용은 그대로 */
  g = g.replace(/[.…!?s·]+$/, '');
  if (!g.endsWith('다') || g.length < 2) return false;
  const 앞 = g.charCodeAt(g.length - 2);
  if (앞 < 0xac00 || 앞 > 0xd7a3) return false;
  return 서술형종성.includes((앞 - 0xac00) % 28);
}

