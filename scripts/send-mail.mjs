export function 오류글읽기(글) {
  const t = String(글 ?? '');
  if (!t.trim()) return '없다';
  if (/Invalid email or User ID/i.test(t)) return '주소가없다';
  if (/unauthorized|not authorized/i.test(t)) return '위임이없다';
  if (/scope/i.test(t)) return '범위가모자라다';
  return '모름';
}
