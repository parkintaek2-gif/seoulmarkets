#!/usr/bin/env node
/**
 * 중부매일-일정1-상태읽는다.mjs — 일정 ①(2026-11-27) 대상 26건의 «지금 상태»를 읽는다.
 *
 * 일정 문서: docs/중부매일-작업일정-20261127-1204.md 「① 11월 27일」
 * ⛔ 읽기만 한다. 승인도 저장도 삭제도 하지 않는다.
 *
 *   node scripts/중부매일-일정1-상태읽는다.mjs            (26건을 읽어 docs/자국 에 적는다)
 *   node scripts/중부매일-일정1-상태읽는다.mjs --자가시험
 */
import fs from 'node:fs';
import { 새탭에서, 자리잡기, 재기 } from './lib/cdp.mjs';
import { 서식주소, 상태글 } from './중부매일-기자와분류-바꾼다.mjs';

export const 목록곳 = 'docs/자국/중부매일바이라인-오피니언아닌것-2026.json';
export const 적는곳 = 'docs/자국/중부매일-일정1-상태-20261127.json';

/** 일정 문서의 표를 그대로 옮긴 갈래 — ⛔ 여기에 없는 갈래는 대상이 아니다 */
export function 갈래(줄) {
  const 큰 = String(줄.큰섹션 ?? '').trim();
  const 작은 = String(줄.섹션 ?? '').trim();
  if (/오늘의운세/.test(작은)) return null;                       /* 건드리지 않는다 */
  if (큰 === '지역' && 작은 === '충북') return '보도자료로';
  if (큰 === '문화' && (작은 === '일반·문화' || 작은 === '학술·문화재')) return '문화칼럼으로';
  if (큰 === '기획·특집' && 작은 === '연재') return '문화칼럼으로';
  if (큰 === '경제' || 큰 === '포토' || 큰 === '스포츠·연예') return '삭제';
  if (큰 === '지역' && 작은 === '대전') return '삭제';
  return null;                                                   /* 사람들·정정·보도자료 — 그대로 둔다 */
}

export function 대상들() {
  const 전부 = JSON.parse(fs.readFileSync(목록곳, 'utf8'));
  return 전부.map((줄) => ({ ...줄, 할일: 갈래(줄) })).filter((줄) => 줄.할일);
}

const 쉰다 = (밀리) => new Promise((끝) => setTimeout(끝, 밀리));

async function 한건읽기(번호) {
  return 새탭에서(서식주소(번호), async (붙음) => {
    await 자리잡기(붙음, { 최대: 45000 });
    await 쉰다(3000);
    try { return JSON.parse(String(await 재기(붙음, 상태글, 25000))); } catch { return null; }
  });
}

function 자가시험() {
  const 탈 = [];
  const 검 = (이름, 참) => { if (!참) 탈.push(이름); };
  검('충북은 보도자료로', 갈래({ 큰섹션: '지역', 섹션: '충북' }) === '보도자료로');
  검('일반문화는 문화칼럼으로', 갈래({ 큰섹션: '문화', 섹션: '일반·문화' }) === '문화칼럼으로');
  검('연재는 문화칼럼으로', 갈래({ 큰섹션: '기획·특집', 섹션: '연재' }) === '문화칼럼으로');
  검('대전은 삭제', 갈래({ 큰섹션: '지역', 섹션: '대전' }) === '삭제');
  검('포토는 삭제', 갈래({ 큰섹션: '포토', 섹션: '포토뉴스' }) === '삭제');
  검('옛 운세는 대상이 아니다', 갈래({ 큰섹션: '사람들', 섹션: '(구)오늘의운세-네이버 X' }) === null);
  검('인사는 대상이 아니다', 갈래({ 큰섹션: '사람들', 섹션: '인사' }) === null);
  검('보도자료는 대상이 아니다', 갈래({ 큰섹션: '보도자료', 섹션: '보도자료' }) === null);
  const 것 = 대상들();
  const 수 = (할일) => 것.filter((x) => x.할일 === 할일).length;
  검('보도자료로 6건', 수('보도자료로') === 6);
  검('문화칼럼으로 15건', 수('문화칼럼으로') === 15);
  검('삭제 5건', 수('삭제') === 5);
  if (탈.length) { console.error('🔴 자가시험 실패 — ' + 탈.join(' / ')); process.exit(1); }
  console.log('✅ 중부매일-일정1-상태읽는다 자가시험 통과 (11)');
}

if (process.argv.includes('--자가시험')) {
  자가시험();
} else if (process.argv[1] && process.argv[1].endsWith('중부매일-일정1-상태읽는다.mjs')) {
  const 것 = 대상들();
  const 결과 = [];
  for (const 줄 of 것) {
    const 상태 = await 한건읽기(줄.번호);
    결과.push({ 번호: 줄.번호, 할일: 줄.할일, 목록제목: 줄.제목, 목록분류: 줄.큰섹션 + ' > ' + 줄.섹션, 상태 });
    const s = 상태 || {};
    console.log([줄.번호, 줄.할일, s.섹션1 + ' ' + s.섹션1글, s.섹션2 + ' ' + s.섹션2글, s.연재 + ' ' + s.연재글,
      s.승인 ? '승인' : (s.미승인 ? '미승인' : '?'), (s.노출날 || '') + ' ' + (s.노출시각 || ''), s.기자명, String(s.제목 || '🔴 못 읽음').slice(0, 28)].join(' | '));
  }
  fs.writeFileSync(적는곳, JSON.stringify(결과, null, 1));
  console.log('적었다 — ' + 적는곳 + ' · ' + 결과.length + '건 · 못 읽은 것 ' + 결과.filter((x) => !x.상태).length);
}
