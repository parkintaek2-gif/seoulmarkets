/**
 * 같은 사람이 여러 그룹에 있을 수 있다 — 한 번만 센다.
 *
 * 🔴 [2026-09-09 정정] 그때까지 «이름»으로 추렸다. 그래서 **이름이 같은 다른 사람이 묶였다.**
 *   실측 — 연예인 명부 9,249행은 Wikidata 번호가 9,249개인데 이름은 8,908개뿐이다.
 *   그 가운데 **288개 이름은 생일까지 서로 달랐다** ⇒ 확실히 다른 사람이다.
 *   (Kim So-hee 5명 · Kim Do-yeon 5명 · Kim Dong-hyun 5명 …)
 * ⇒ 열쇠를 이렇게 둔다 — **q 가 있으면 q, 없으면 «이름+생일»**.
 *   같은 이름·같은 생일은 같은 사람으로 봐도 안전하고, 생일이 다르면 따로 센다.
 * ⚠ 그룹 멤버 명단에는 q 가 «없다»(0개). 거기서는 이름+생일이 유일한 길이고, 이 정정으로
 *   그 명부의 사람 수도 조금 는다. 옛 수를 조용히 갈아 치우지 않고 지면에 정정으로 적는다.
 * ⛔ 이름만으로 추리는 코드로 되돌리지 않는다. 「같은 이름은 같은 사람」은 짐작이었다.
 */
export function 사람으로추리기(멤버들) {
  const 통 = new Map();
  for (const m of 멤버들) {
    if (!m || !/^\d{4}-\d{2}-\d{2}$/.test(String(m.born || ''))) continue;
    const 열쇠 = m.q ? `q:${m.q}` : `n:${m.name}|${m.born}`;
    if (!통.has(열쇠)) 통.set(열쇠, m);
  }
  return [...통.values()];
}

/** 달별로 세고 «하루당»으로 고른다 */
export function 달별로세기(사람들, 뺄날 = null) {
  const 쓸것 = 뺄날 ? 사람들.filter((m) => m.born.slice(5) !== 뺄날) : 사람들;
  const 셈 = new Array(12).fill(0);
  for (const m of 쓸것) 셈[Number(m.born.slice(5, 7)) - 1] += 1;
  const 이달날수 = [...날수];
  if (뺄날 && /^\d{2}-\d{2}$/.test(뺄날)) 이달날수[Number(뺄날.slice(0, 2)) - 1] -= 1;
  const 합 = 셈.reduce((a, b) => a + b, 0);
  const 총날 = 이달날수.reduce((a, b) => a + b, 0);
  const 고른 = 합 / 총날;
  return {
    합,
    달들: 셈.map((c, i) => ({
      달: 달이름[i], 수: c, 날수: +이달날수[i].toFixed(4),
      하루당: +(c / 이달날수[i]).toFixed(3),
      고른값의배: 고른 ? +((c / 이달날수[i]) / 고른).toFixed(3) : null,
      몫: 합 ? +(c / 합 * 100).toFixed(1) : null,
    })),
    날수쓴것: 이달날수,
  };
}

/**
 * 「달마다 다르다」가 우연인가 — 생일이 «고르게» 뿌려졌다고 놓고 되풀이해 굴린다.
 * ⛔ 5%를 넘으면 「몰려 있다」고 쓰지 않는다 (공용 규칙 · scripts/lib/noise-test.mjs)
 */
export function 잡음시험달(합, 날수목록, 실제폭, 횟수 = 10000, 씨 = 씨앗) {
  const 난수 = 난수기(씨);
  const 총날 = 날수목록.reduce((a, b) => a + b, 0);
  let 이상 = 0;
  for (let t = 0; t < 횟수; t += 1) {
    const 통 = new Array(12).fill(0);
    for (let i = 0; i < 합; i += 1) {
      let r = 난수() * 총날; let j = 0;
      while (r > 날수목록[j] && j < 11) { r -= 날수목록[j]; j += 1; }
      통[j] += 1;
    }
    const h = 통.map((c, i) => c / 날수목록[i]);
    if (Math.max(...h) - Math.min(...h) >= 실제폭 - 1e-9) 이상 += 1;
  }
  const 비율 = +(이상 / 횟수 * 100).toFixed(1);
  return { 횟수, 씨앗: 씨, 우연일확률: 비율, 못쟀다고적어야하나: 비율 > 5 };
}

/** 어떤 «날»이 유난히 몰렸나 — 채워 넣은 날짜를 찾는 자리다 */
export function 몰린날(사람들, 몇 = 5) {
  const 셈 = {};
  for (const m of 사람들) { const k = m.born.slice(5); 셈[k] = (셈[k] || 0) + 1; }
  const 하루평균 = 사람들.length / 366;
  return Object.entries(셈).sort((a, b) => b[1] - a[1]).slice(0, 몇)
    .map(([날, 수]) => ({ 날, 수, 하루평균의배: +(수 / 하루평균).toFixed(2) }));
}

/**
 * 어떤 «날»이 366일 가운데 몇째인가 — 「그 날이 특별한가」에 답하는 자다.
 *
 * ⭐ [2026-09-09] 손님이 묻는 것은 「내 스타 생일이 특별한 날인가」다. 그 답은 «수»가 아니라
 *   «자리»여야 한다 — 26명이라는 수만 주면 많은지 적은지 알 수 없다.
 * ⛔ 없는 날은 0 이 아니라 «없다»로 둔다. 2월 30일은 자리를 매길 대상이 아니다.
 * ⚠ 같은 수인 날이 여럿이면 자리가 겹친다. 그때는 «공동 몇째»가 맞으므로 같은 수의 날
 *   가운데 가장 앞자리를 준다 — 뒷자리를 주면 그 날이 실제보다 흔해 보인다.
 */
export function 날별순위(사람들, 볼날) {
  const 셈 = new Map();
  for (const m of 사람들) {
    if (!m || !/^\d{4}-\d{2}-\d{2}$/.test(String(m.born || ''))) continue;
    const k = m.born.slice(5);
    셈.set(k, (셈.get(k) || 0) + 1);
  }
  if (!셈.size) return { 날: 볼날, 수: null, 자리: null, 날칸수: 0, 하루평균: null };
  const 수 = 셈.get(볼날) ?? null;
  const 하루평균 = [...셈.values()].reduce((a, b) => a + b, 0) / 셈.size;
  /* 공동 순위 — 나보다 «많은» 날의 수 + 1 */
  const 자리 = 수 === null ? null : [...셈.values()].filter((v) => v > 수).length + 1;
  return { 날: 볼날, 수, 자리, 날칸수: 셈.size, 하루평균: +하루평균.toFixed(2) };
}

/**
 * 몰린 날을 여러 개 빼고도 결과가 사는지 본다.
 * ⛔ 「1월 1일만」 빼는 것으로는 모자랐다 — 2월 28일이 «똑같은 48명»으로 나란히 있었다.
 *   한 날에만 이름을 붙이고 넘어가면, 남은 몰린 날이 그대로 결과를 밀고 있다.
 */
export function 여러날빼기(사람들, 뺄날들) {
  const 쓸것 = 사람들.filter((m) => !뺄날들.includes(m.born.slice(5)));
  const 이달날수 = [...날수];
  for (const d of 뺄날들) if (/^\d{2}-\d{2}$/.test(d)) 이달날수[Number(d.slice(0, 2)) - 1] -= 1;
  const 셈 = new Array(12).fill(0);
  for (const m of 쓸것) 셈[Number(m.born.slice(5, 7)) - 1] += 1;
  const 합 = 셈.reduce((a, b) => a + b, 0);
  const 총날 = 이달날수.reduce((a, b) => a + b, 0);
  const 고른 = 합 / 총날;
  return {
    뺀날들: 뺄날들,
    뺀사람: 사람들.length - 합,
    합,
    달들: 셈.map((c, i) => ({
      달: 달이름[i], 수: c, 날수: +이달날수[i].toFixed(4),
      하루당: +(c / 이달날수[i]).toFixed(3),
      고른값의배: 고른 ? +((c / 이달날수[i]) / 고른).toFixed(3) : null,
    })),
    날수쓴것: 이달날수,
  };
}

/**
 * 366일을 «날마다» 센다 — 손님이 묻는 것은 「내 스타 생일이 특별한가」다.
 *
 * ⛔ 몇 날만 골라 싣지 않는다. 고르면 그 고름이 결과가 된다 —
 *   기사가 인용한 날만 싣는 것도 고르는 것이다. 366칸을 다 낸다.
 * ⛔ 사람이 없는 날은 «빼지» 않는다. 0 이 아니라 «그 날이 없다»가 되어 버린다 —
 *   2월 30일처럼 «있을 수 없는 날»과 «아무도 없는 날»은 다르다. 있는 날은 0 으로 남긴다.
 */
export function 날별세기(사람들) {
  const 셈 = new Map();
  for (const m of 사람들) {
    if (!m || !/^\d{4}-\d{2}-\d{2}$/.test(String(m.born || ''))) continue;
    const k = m.born.slice(5);
    셈.set(k, (셈.get(k) || 0) + 1);
  }
  /* 있을 수 있는 날을 먼저 깔고(윤년을 넣어 366칸), 없는 날은 0 으로 채운다 */
  const 달날수 = [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
  const 칸들 = [];
  for (let m = 0; m < 12; m += 1) {
    for (let d = 1; d <= 달날수[m]; d += 1) {
      칸들.push(`${String(m + 1).padStart(2, '0')}-${String(d).padStart(2, '0')}`);
    }
  }
  const 값들 = 칸들.map((날) => 셈.get(날) ?? 0);
  const 합 = 값들.reduce((a, b) => a + b, 0);
  const 하루평균 = 합 / 칸들.length;
  return {
    날칸수: 칸들.length,
    합,
    하루평균: +하루평균.toFixed(2),
    날들: 칸들.map((날, i) => ({
      날,
      수: 값들[i],
      /* 자리는 «공동»으로 — 나보다 많은 날의 수 + 1 */
      자리: 값들.filter((v) => v > 값들[i]).length + 1,
      하루평균의배: 하루평균 ? +(값들[i] / 하루평균).toFixed(2) : null,
    })),
  };
}

